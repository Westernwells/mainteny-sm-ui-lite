export const queryServiceOrders = async (
  params: ServiceOrderQueryParams,
): Promise<Resource<ServiceOrderView>> => {
  // Add all autogenerated payment statuses for given status
  const mappedPaymentStatus = params.paymentStatus?.reduce(
    (acc, currentStatus) => {
      const autoGeneratedValue =
        PAYMENT_STATUS_TO_AUTO_GENERATED.get(currentStatus);
      if (autoGeneratedValue)
        return [...acc, currentStatus, autoGeneratedValue];
      return [...acc, currentStatus];
    },
    [] as (
      | ServiceOrderPaymentStatus
      | ServiceOrderPaymentWithIndicationStatus
    )[],
  );

  const response: AxiosResponse<Resource<ServiceOrderView>> =
    await axiosClient.get(`/api/serviceOrders`, {
      params: {
        ...params,
        ...(mappedPaymentStatus ? {paymentStatus: mappedPaymentStatus} : {}),
      },
      paramsSerializer,
    });
  return response.data;
};

export function useServiceOrders(
  params: ServiceOrderQueryParams,
  options?: UseQueryOptions<any, any, any>,
) {
  const {user} = useUserSession();
  return useQuery<
    Resource<ServiceOrderView>,
    RestError,
    Resource<ServiceOrderView>
  >(
    [queryKeys.queryServiceOrders, params, user?.userAccount.serviceCompany.id],
    () =>
      queryServiceOrders({
        ...params,
        serviceCompanyId: user!.userAccount.serviceCompany.id,
      }),
    {enabled: !!user, ...options},
  );
}


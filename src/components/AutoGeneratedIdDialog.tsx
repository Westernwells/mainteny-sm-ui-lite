import {t} from 'i18next';
import {theme} from 'theme';
import {Alert, Grid, Switch, Typography, Box} from '@mui/material';
import {getIn, useFormik} from 'formik';
import {AutoGeneratedSchema} from 'pages/CompanyDetails/AutoGeneratedId/AutoGeneratedSchema';
import {Dispatch, SetStateAction, useEffect} from 'react';
import {AutoNumberConfigRecord} from 'models/service-company';
import * as Yup from 'yup';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import {
  useCompanyAutoNumberConfig,
  useUpdateAutoNumberConfig,
} from 'hooks/reactQuery/useCompanies';
import {configRecords} from 'utils/config-records';
import {Dialog} from './Dialog';
import {FormInput} from './form/FormInput';

type Props = {
  openDialog: boolean;
  setOpenDialog: Dispatch<SetStateAction<boolean>>;
};

const validationSchema = Yup.object().shape({
  configRecords: Yup.array().of(
    Yup.object().shape({
      type: Yup.string(),
      prefix: Yup.string().test(
        'last-char-not-digit',
        `Last character can't be a digit`,
        (value) => {
          if (!value) {
            return true;
          }
          const lastChar = value.charAt(value.length - 1);
          return Number.isNaN(Number(lastChar));
        },
      ),
      startFrom: Yup.number().min(1, "Can't be less than 1"),
      numberOfDigits: Yup.number().min(1, "Can't be less than 1"),
      enabled: Yup.boolean(),
    }),
  ),
});

const AutoGeneratedIdDialog = ({openDialog, setOpenDialog}: Props) => {
  const {user} = useUserSession();
  const {data} = useCompanyAutoNumberConfig(
    user?.userAccount.serviceCompany.id,
  );

  const {mutateAsync: updateAutoNumberConfig} = useUpdateAutoNumberConfig(
    'Updated Successfully',
  );

  const renderAlert = () => (
    <Alert severity="info">
      <Typography variant="subtitle2">
        {t('Automatic ID generation')}
      </Typography>
      <Typography variant="body2" pt={0.5}>
        {t(
          'Any service with disabled auto ID generation will need to be populated manually.',
        )}
      </Typography>
      <Typography variant="body2">
        {t('Configure and enable to populate automatically.')}
      </Typography>
    </Alert>
  );

  const renderHeader = () => (
    <Grid
      container
      textTransform="uppercase"
      color={theme.palette.text.secondary}
      pb={1.5}
      pt={3}
      borderBottom={`1px solid ${theme.palette.text.disabled}`}
      columnSpacing={4}>
      <Grid item xs={2.4}>
        <Typography variant="body2" fontWeight={600}>
          {t('Service')}
        </Typography>
      </Grid>

      <Grid item xs={2.4}>
        <Typography textAlign="center" variant="body2" fontWeight={600}>
          {t('Prefix')}
        </Typography>
      </Grid>

      <Grid item xs={2.4}>
        <Typography textAlign="center" variant="body2" fontWeight={600}>
          {t('# of digits')}
        </Typography>
      </Grid>

      <Grid item xs={2}>
        <Typography variant="body2" fontWeight={600} textAlign="center">
          {t('Start from')}
        </Typography>
      </Grid>

      <Grid item xs={2.8} pr={3}>
        <Typography textAlign="center" variant="body2" fontWeight={600}>
          {t('Status')}
        </Typography>
      </Grid>
    </Grid>
  );

  const formik = useFormik<{
    configRecords: AutoNumberConfigRecord[];
  }>({
    initialValues: {
      configRecords,
    },
    onSubmit: () => {},
    validationSchema,
  });

  const onSave = () => {
    if (formik.values.configRecords) {
      const requestBody = {
        configRecords: formik.values.configRecords,
      };
      updateAutoNumberConfig({
        body: requestBody,
        companyId: user!.userAccount.serviceCompany.id,
      });
    }
    setOpenDialog(false);
  };

  useEffect(() => {
    if (data?.configRecords) {
      const finalArray = formik.initialValues.configRecords.map((item) => {
        data.configRecords.forEach((configItem) => {
          if (configItem.type === item.type) {
            item = configItem;
          }
        });
        return item;
      });
      formik.resetForm({
        values: {
          configRecords: finalArray,
        },
      });
    }
  }, [data, openDialog]);

  return (
    <Dialog
      title="Auto generated ID"
      onCancel={() => setOpenDialog(false)}
      onSave={() => onSave()}
      disableSaveBtn={!formik.dirty || !!Object.keys(formik.errors).length}
      dialogProps={{
        maxWidth: 'md',
        open: openDialog || false,
      }}
      dialogContentStyles={{
        mx: 0,
        mt: 0,
        px: 3,
      }}>
      {renderAlert()}
      {renderHeader()}
      <Box pt={2}>
        {formik.values.configRecords
          ?.sort((a, b) => {
            const nameA = a.type.toUpperCase();
            const nameB = b.type.toUpperCase();
            if (nameA < nameB) {
              return -1;
            }
            if (nameA > nameB) {
              return 1;
            }

            return 0;
          })
          .map((item, index) => (
            <Grid
              key={item.type}
              container
              columnSpacing={4}
              alignItems="center"
              mb={formik.values.configRecords.length - 1 === index ? 0 : 1.875}>
              <Grid item xs={2.4} mt={2}>
                <AutoGeneratedSchema
                  type={formik.values?.configRecords[index].type}
                  enabled={formik.values?.configRecords[index].enabled}
                />
              </Grid>
              <Grid item xs={2.4}>
                <FormInput
                  props={{
                    size: 'small',
                    id: 'prefix',
                    disabled: !formik.values.configRecords[index].enabled,
                    value: formik.values.configRecords[index].prefix,
                    name: `configRecords[${index}].prefix`,
                    type: 'text',
                    error: !!(
                      getIn(formik.touched, `configRecords[${index}]`) &&
                      getIn(formik.errors, `configRecords[${index}]`)
                    ),
                    helperText:
                      formik.errors.configRecords &&
                      formik.touched.configRecords
                        ? getIn(formik.errors, `configRecords[${index}].prefix`)
                        : '',
                    onBlur: formik.handleBlur,
                    onChange: formik.handleChange,
                    required: true,
                    sx: {
                      height: '1.5em',
                      '& .MuiFormHelperText-root': {
                        fontSize: '0.55rem',
                        marginLeft: 0,
                        marginRight: 0,
                      },
                    },
                  }}
                />
              </Grid>
              <Grid item xs={2.4}>
                <FormInput
                  props={{
                    size: 'small',
                    id: 'numberOfDigits',
                    disabled: !formik.values.configRecords[index].enabled,
                    value: formik.values.configRecords[index].numberOfDigits,
                    name: `configRecords[${index}].numberOfDigits`,
                    type: 'number',
                    error: !!(
                      getIn(formik.touched, `configRecords[${index}]`) &&
                      getIn(formik.errors, `configRecords[${index}]`)
                    ),
                    helperText:
                      formik.errors.configRecords &&
                      formik.touched.configRecords
                        ? getIn(
                            formik.errors,
                            `configRecords[${index}].numberOfDigits`,
                          )
                        : '',
                    onBlur: formik.handleBlur,
                    onChange: formik.handleChange,
                    required: true,
                    sx: {
                      height: '1.5em',
                      '& .MuiFormHelperText-root': {
                        fontSize: '0.65rem',
                        marginLeft: 0,
                        marginRight: 0,
                      },
                      '& input': {
                        textAlign: 'right',
                      },
                    },
                  }}
                />
              </Grid>
              <Grid item xs={2}>
                <FormInput
                  props={{
                    size: 'small',
                    id: 'startFrom',
                    disabled: !formik.values.configRecords[index].enabled,
                    value: formik.values.configRecords[index].startFrom,
                    name: `configRecords[${index}].startFrom`,
                    type: 'number',
                    error: !!(
                      getIn(formik.touched, `configRecords[${index}]`) &&
                      getIn(formik.errors, `configRecords[${index}]`)
                    ),
                    helperText:
                      formik.errors.configRecords &&
                      formik.touched.configRecords
                        ? getIn(
                            formik.errors,
                            `configRecords[${index}].startFrom`,
                          )
                        : '',
                    onBlur: formik.handleBlur,
                    onChange: formik.handleChange,
                    required: true,
                    sx: {
                      height: '1.5em',
                      '& .MuiFormHelperText-root': {
                        fontSize: '0.65rem',
                        marginLeft: 0,
                        marginRight: 0,
                      },
                      '& input': {
                        textAlign: 'right',
                      },
                    },
                  }}
                />
              </Grid>
              <Grid
                item
                xs={2.8}
                display="flex"
                alignItems="center"
                flexDirection="row"
                mt={2}>
                <Switch
                  defaultChecked={!!formik.values.configRecords[index].enabled}
                  id="enabled"
                  name={`configRecords[${index}].enabled`}
                  onChange={formik.handleChange}
                  size="small"
                  sx={{ml: 2}}
                />

                <Typography variant="body1">
                  {item.enabled ? t('Enabled') : t('Disabled')}
                </Typography>
              </Grid>
            </Grid>
          ))}
      </Box>
    </Dialog>
  );
};

export default AutoGeneratedIdDialog;

import {Text, View, StyleSheet, Font} from '@react-pdf/renderer';
import {formatDate} from 'utils/datetime';
import {formatAddressFullname} from 'utils/utils';
import {InvoiceView} from 'models/invoice';
import MontserratRegular from '../../assets/fonts/Montserrat/Montserrat-Regular.ttf';
import MontserratBold from '../../assets/fonts/Montserrat/Montserrat-SemiBold.ttf';
import NotoSansGeorgianRegular from '../../assets/fonts/NotoSans/NotoSansGeorgian-Regular.ttf';
import NotoSansGeorgianBold from '../../assets/fonts/NotoSans/NotoSansGeorgian-Bold.ttf';

Font.register({
  family: 'Montserrat-Bold',
  format: 'truetype',
  src: MontserratBold,
});

Font.register({
  family: 'Montserrat-Regular',
  format: 'truetype',
  src: MontserratRegular,
});
Font.register({
  family: 'NotoSans-Regular',
  format: 'truetype',
  src: NotoSansGeorgianRegular,
});

Font.register({
  family: 'NotoSans-Bold',
  format: 'truetype',
  src: NotoSansGeorgianBold,
});

const getStyles = (
  boldFontStyle?: {fontFamily: string},
  regularFontStyle?: {fontFamily: string},
) =>
  StyleSheet.create({
    rightAddress: {
      flex: '0 0 42%',
      display: 'flex',
      flexDirection: 'column',
    },
    rightAddressContent: {
      display: 'flex',
      alignItems: 'flex-start',
      flexDirection: 'row',
      justifyContent: 'space-between',
      paddingBottom: 6,
    },
    tag: {
      ...boldFontStyle,
      fontSize: 9,
      color: '#212121',
      flex: '0 0 43%',
    },
    tagContent: {
      fontSize: 9,
      color: '#616161',
      flex: '0 0 57%',
      textAlign: 'right',
      ...regularFontStyle,
    },
  });

type Props = {
  translate: (key: string) => string;
  invoice?: InvoiceView;
  selectedLng?: string;
};

const PdfTemplateInvoiceDetails = ({
  translate,
  invoice,
  selectedLng,
}: Props) => {
  const boldFontStyle = {
    fontFamily: selectedLng === 'ka-ge' ? 'NotoSans-Bold' : 'Montserrat-Bold',
  };

  const regularFontStyle = {
    fontFamily:
      selectedLng === 'ka-ge' ? 'NotoSans-Regular' : 'Montserrat-Regular',
  };

  const styles = getStyles(boldFontStyle, regularFontStyle);
  return (
    <View style={styles.rightAddress}>
      {invoice?.externalId && (
        <View style={styles.rightAddressContent}>
          <Text style={styles.tag}>{translate('Invoice no.')}</Text>
          <Text style={styles.tagContent}>{invoice?.externalId}</Text>
        </View>
      )}

      <View style={styles.rightAddressContent}>
        <Text style={styles.tag}>{translate('Invoice date')}</Text>
        <Text style={styles.tagContent}>
          {invoice?.sentDate
            ? formatDate(invoice?.sentDate)
            : formatDate(invoice?.meta.createdAt) || '-'}
        </Text>
      </View>

      {invoice?.dueDate && (
        <View style={styles.rightAddressContent}>
          <Text style={styles.tag}>{translate('Due date')}</Text>
          <Text style={styles.tagContent}>
            {formatDate(invoice?.dueDate) || '-'}
          </Text>
        </View>
      )}

      {(invoice?.meta.creator?.firstName ||
        invoice?.meta.creator?.lastName) && (
        <View style={styles.rightAddressContent}>
          <Text style={styles.tag}>{translate('Generated by')}</Text>
          <Text style={styles.tagContent}>
            {invoice?.meta.creator?.firstName} {invoice?.meta.creator?.lastName}
          </Text>
        </View>
      )}

      {invoice?.propertyOwner?.externalId && (
        <View style={styles.rightAddressContent}>
          <Text style={styles.tag}>{translate('Customer no.')}</Text>
          <Text style={styles.tagContent}>
            {invoice?.propertyOwner?.externalId}
          </Text>
        </View>
      )}

      <View style={styles.rightAddressContent}>
        <Text style={styles.tag}>{translate('Order date')}</Text>
        <Text style={styles.tagContent}>
          {formatDate(invoice?.serviceOrder?.meta.createdAt) || '-'}
        </Text>
      </View>

      {invoice?.additionalInfo.customerSpecificOrderNumber && (
        <View style={styles.rightAddressContent}>
          <Text style={styles.tag}>{translate('Purchase no.')}</Text>
          <Text style={styles.tagContent}>
            {invoice?.additionalInfo.customerSpecificOrderNumber}
          </Text>
        </View>
      )}

      {invoice?.additionalInfo.costCenter && (
        <View style={styles.rightAddressContent}>
          <Text style={styles.tag}>{translate('Cost center')}</Text>
          <Text style={styles.tagContent}>
            {invoice?.additionalInfo.costCenter}
          </Text>
        </View>
      )}

      {invoice?.serviceOrder?.externalId && (
        <View style={styles.rightAddressContent}>
          <Text style={styles.tag}>{translate('Job no.')}</Text>
          <Text style={styles.tagContent}>
            {invoice?.serviceOrder?.externalId}
          </Text>
        </View>
      )}

      {invoice?.additionalInfo.deliveryEndDate && (
        <View style={styles.rightAddressContent}>
          <Text style={styles.tag}>{translate('Delivery date')}</Text>
          <Text style={styles.tagContent}>
            {formatDate(invoice?.additionalInfo.deliveryEndDate) || '-'}
          </Text>
        </View>
      )}

      <View style={{marginTop: 20}}>
        {invoice?.serviceOrder?.elevator.externalId && (
          <View style={styles.rightAddressContent}>
            <Text style={styles.tag}>{translate('Unit no.')}</Text>
            <Text style={styles.tagContent}>
              {invoice?.serviceOrder?.elevator.externalId}
            </Text>
          </View>
        )}

        {invoice?.serviceOrder?.elevator?.address?.fullName && (
          <View style={styles.rightAddressContent}>
            <Text style={styles.tag}>{translate('Unit address')}</Text>
            <Text style={styles.tagContent}>{`${
              formatAddressFullname(invoice?.serviceOrder?.elevator?.address)
                ?.fullCityName
            }`}</Text>
          </View>
        )}
      </View>
    </View>
  );
};

export default PdfTemplateInvoiceDetails;

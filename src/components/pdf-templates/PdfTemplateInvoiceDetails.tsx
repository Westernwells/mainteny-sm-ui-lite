import {Text, View, StyleSheet, Font} from '@react-pdf/renderer';
import {formatDate} from 'utils/datetime';
import {getDisplayDeliveryDate} from 'utils/invoice';
import {InvoiceType, InvoiceView} from 'models/invoice';
import {useMemo} from 'react';
import {ClientReportForPDFConfig} from 'models/client-storage';
import {UserAccount} from 'models/user';
import MontserratRegular from '../../assets/fonts/Montserrat/Montserrat-Regular.ttf';
import MontserratBold from '../../assets/fonts/Montserrat/Montserrat-SemiBold.ttf';
import NotoSansGeorgianRegular from '../../assets/fonts/NotoSans/NotoSansGeorgian-Regular.ttf';
import NotoSansGeorgianBold from '../../assets/fonts/NotoSans/NotoSansGeorgian-Bold.ttf';
import PdfUnitAddress from './containers/PdfUnitAddress';

Font.register({
  family: 'Montserrat-Bold',
  format: 'truetype',
  src: MontserratBold,
});

Font.register({
  family: 'Montserrat-Regular',
  format: 'truetype',
  src: MontserratRegular,
});
Font.register({
  family: 'NotoSans-Regular',
  format: 'truetype',
  src: NotoSansGeorgianRegular,
});

Font.register({
  family: 'NotoSans-Bold',
  format: 'truetype',
  src: NotoSansGeorgianBold,
});

const getStyles = (
  boldFontStyle?: {fontFamily: string},
  regularFontStyle?: {fontFamily: string},
) =>
  StyleSheet.create({
    rightAddress: {
      flex: '0 0 42%',
      display: 'flex',
      flexDirection: 'column',
    },
    rightAddressContent: {
      display: 'flex',
      alignItems: 'flex-start',
      flexDirection: 'row',
      justifyContent: 'space-between',
      paddingBottom: 6,
    },
    tag: {
      ...boldFontStyle,
      fontSize: 8.5,
      color: '#212121',
      flex: '0 0 43%',
    },
    tagContent: {
      fontSize: 8.5,
      color: '#616161',
      flex: '0 0 57%',
      textAlign: 'right',
      ...regularFontStyle,
    },
  });

type Props = {
  translate: (key: string, options?: {context: string}) => string;
  invoice?: InvoiceView;
  selectedLng?: string;
  nextCompanyExternalId?: string;
  showCurrentDateAsInvoiceDate?: boolean;
  pdfConfigClientStorage: ClientReportForPDFConfig;
  userInfo?: UserAccount;
};

const PdfTemplateInvoiceDetails = ({
  translate,
  invoice,
  selectedLng,
  nextCompanyExternalId,
  showCurrentDateAsInvoiceDate,
  pdfConfigClientStorage,
  userInfo,
}: Props) => {
  const startDate = invoice?.additionalInfo.deliveryStartDate;
  const endDate = invoice?.additionalInfo.deliveryEndDate;

  const displayDeliveryDate = getDisplayDeliveryDate(startDate, endDate);

  const boldFontStyle = {
    fontFamily: selectedLng === 'ka-ge' ? 'NotoSans-Bold' : 'Montserrat-Bold',
  };

  const regularFontStyle = {
    fontFamily:
      selectedLng === 'ka-ge' ? 'NotoSans-Regular' : 'Montserrat-Regular',
  };

  const styles = getStyles(boldFontStyle, regularFontStyle);

  const getInvoiceDate = () => {
    if (showCurrentDateAsInvoiceDate) return formatDate(new Date());

    return invoice?.sentDate
      ? formatDate(invoice?.sentDate)
      : formatDate(new Date());
  };

  const elevatorExternalId = useMemo(
    () =>
      invoice?.additionalInfo.elevatorExternalId ||
      invoice?.serviceOrder?.elevator.externalId,
    [
      invoice?.additionalInfo.elevatorExternalId,
      invoice?.serviceOrder?.elevator.externalId,
    ],
  );

  const unitBuilding =
    (pdfConfigClientStorage.includeUnitBuilding &&
      invoice?.serviceOrder?.elevator?.additionalInfo?.buildingLocation) ||
    '';

  return (
    <View style={styles.rightAddress}>
      {(invoice?.externalId || nextCompanyExternalId) && (
        <View style={styles.rightAddressContent}>
          <Text style={styles.tag}>{translate('Invoice no.')}</Text>
          <Text style={styles.tagContent}>
            {invoice?.externalId || nextCompanyExternalId}
          </Text>
        </View>
      )}

      <View style={styles.rightAddressContent}>
        <Text style={styles.tag}>
          {invoice?.type === InvoiceType.CREDIT_NOTE
            ? translate('Date of credit note')
            : translate('Invoice date')}
        </Text>
        <Text style={styles.tagContent}>{getInvoiceDate()}</Text>
      </View>

      {invoice?.dueDate && (
        <View style={styles.rightAddressContent}>
          <Text style={styles.tag}>{translate('Due date')}</Text>
          <Text style={styles.tagContent}>
            {formatDate(invoice?.dueDate) || '-'}
          </Text>
        </View>
      )}

      {pdfConfigClientStorage.includeUsername &&
        (invoice?.meta.creator?.firstName ||
          invoice?.meta.creator?.lastName) && (
          <View style={styles.rightAddressContent}>
            <Text style={styles.tag}>{translate('Generated by')}</Text>
            <Text style={styles.tagContent}>
              {invoice?.meta.creator?.firstName}{' '}
              {invoice?.meta.creator?.lastName}
            </Text>
          </View>
        )}

      {userInfo?.contact?.phone && pdfConfigClientStorage.includeUserPhone && (
        <View style={styles.rightAddressContent}>
          <Text style={styles.tag}>{translate('Phone number')}</Text>
          <Text style={styles.tagContent}>{userInfo?.contact?.phone}</Text>
        </View>
      )}
      {userInfo?.contact?.email && pdfConfigClientStorage.includeUserEmail && (
        <View style={styles.rightAddressContent}>
          <Text style={styles.tag}>{translate('Email address')}</Text>
          <Text style={styles.tagContent}>{userInfo?.contact?.email}</Text>
        </View>
      )}

      {invoice?.propertyOwner?.externalId && (
        <View style={styles.rightAddressContent}>
          <Text style={styles.tag}>{translate('Customer no.')}</Text>
          <Text style={styles.tagContent}>
            {invoice?.propertyOwner?.externalId}
          </Text>
        </View>
      )}

      {invoice?.serviceOrder?.meta.createdAt && (
        <View style={styles.rightAddressContent}>
          <Text style={styles.tag}>{translate('Order date')}</Text>
          <Text style={styles.tagContent}>
            {formatDate(invoice?.serviceOrder?.meta.createdAt) || '-'}
          </Text>
        </View>
      )}

      {invoice?.additionalInfo.customerSpecificOrderNumber && (
        <View style={styles.rightAddressContent}>
          <Text style={styles.tag}>{translate('Purchase no.')}</Text>
          <Text style={styles.tagContent}>
            {invoice?.additionalInfo.customerSpecificOrderNumber}
          </Text>
        </View>
      )}

      {invoice?.additionalInfo.costCenter && (
        <View style={styles.rightAddressContent}>
          <Text style={styles.tag}>{translate('Cost Center')}</Text>
          <Text style={styles.tagContent}>
            {invoice?.additionalInfo.costCenter}
          </Text>
        </View>
      )}

      {invoice?.serviceOrder?.externalId && (
        <View style={styles.rightAddressContent}>
          <Text style={styles.tag}>{translate('Job no.')}</Text>
          <Text style={styles.tagContent}>
            {invoice?.serviceOrder?.externalId}
          </Text>
        </View>
      )}

      {displayDeliveryDate && (
        <View style={styles.rightAddressContent}>
          <Text style={styles.tag}>{translate('Delivery date')}</Text>
          <Text style={styles.tagContent}>{displayDeliveryDate}</Text>
        </View>
      )}

      <View style={{marginTop: 20}}>
        {pdfConfigClientStorage.includeUnitNumber && elevatorExternalId && (
          <View style={styles.rightAddressContent}>
            <Text style={styles.tag}>
              {translate('Unit no.', {context: 'elevator'})}
            </Text>
            <Text style={styles.tagContent}>{elevatorExternalId}</Text>
          </View>
        )}
        {invoice?.serviceOrder?.elevator.serialNumber &&
          pdfConfigClientStorage.includeSerialNumber && (
            <View style={styles.rightAddressContent}>
              <Text style={styles.tag}>{translate('Serial number')}.</Text>
              <Text style={styles.tagContent}>
                {invoice?.serviceOrder?.elevator.serialNumber ?? '-'}
              </Text>
            </View>
          )}

        <PdfUnitAddress
          address={invoice?.serviceOrder?.elevator?.address}
          translate={translate}
          selectedLng={selectedLng}
          building={unitBuilding}
        />
      </View>
    </View>
  );
};

export default PdfTemplateInvoiceDetails;

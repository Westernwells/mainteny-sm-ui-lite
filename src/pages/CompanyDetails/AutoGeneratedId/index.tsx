import {useEffect, useState} from 'react';
import {useTranslation} from 'react-i18next';
import Typography from '@mui/material/Typography';
import {Alert, Box, Grid} from '@mui/material';
import {grey} from '@mui/material/colors';
import {useCompanyAutoNumberConfig} from 'hooks/reactQuery/useCompanies';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import {StatusChip} from 'components/StatusChip';
import useTheme from '@mui/material/styles/useTheme';
import {AutoNumberConfigRecord} from 'models/service-company';
import AutoGeneratedIdDialog from 'components/AutoGeneratedIdDialog';
import {Card} from 'components/Card';
import {configRecords} from 'utils/config-records';
import {AutoGeneratedSchema} from './AutoGeneratedSchema';

export const AutoGeneratedId = () => {
  const [openDialog, setOpenDialog] = useState(false);
  const {user} = useUserSession();
  const theme = useTheme();
  const {t} = useTranslation();

  const [displayRecords, setDisplayRecords] = useState<
    AutoNumberConfigRecord[] | undefined
  >([]);

  const {data} = useCompanyAutoNumberConfig(
    user?.userAccount.serviceCompany.id,
  );

  useEffect(() => {
    const apiRecordsMap: any = {};

    data?.configRecords.forEach((record) => {
      apiRecordsMap[record.type] = true;
    });

    const mergedRecords = data?.configRecords.map((apiRecord) => {
      const defaultRecord = configRecords.find(
        (record) => record.type === apiRecord.type,
      );

      if (defaultRecord) {
        return {...defaultRecord, ...apiRecord};
      }
      return apiRecord;
    });

    configRecords.forEach((defaultRecord) => {
      if (!apiRecordsMap[defaultRecord.type]) {
        mergedRecords?.push(defaultRecord);
      }
    });

    setDisplayRecords(mergedRecords);
  }, [data]);

  const renderAlert = () => (
    <Alert severity="info">
      <Typography variant="subtitle2">
        {t('Automatic ID generation')}
      </Typography>
      <Typography variant="body2" pt={0.5}>
        {t(
          'Any service with disabled auto ID generation will need to be populated manually.',
        )}
      </Typography>
      <Typography variant="body2">
        {t('Configure and enable to populate automatically.')}
      </Typography>
    </Alert>
  );

  const renderHeader = () => (
    <Grid
      container
      textTransform="uppercase"
      color={theme.palette.text.secondary}
      pb={1.5}
      pt={3}
      borderBottom={`1px solid ${theme.palette.text.disabled}`}>
      <Grid item xs={2.4}>
        <Typography variant="body2" fontWeight={600}>
          {t('Service')}
        </Typography>
      </Grid>

      <Grid item xs={2.4}>
        <Typography textAlign="center" variant="body2" fontWeight={600}>
          {t('Prefix')}
        </Typography>
      </Grid>

      <Grid item xs={2.4}>
        <Typography textAlign="center" variant="body2" fontWeight={600}>
          {t('# of digits')}
        </Typography>
      </Grid>

      <Grid item xs={2}>
        <Typography variant="body2" fontWeight={600} textAlign="right">
          {t('Start from')}
        </Typography>
      </Grid>

      <Grid item xs={2.8} pr={3}>
        <Typography textAlign="right" variant="body2" fontWeight={600}>
          {t('Status')}
        </Typography>
      </Grid>
    </Grid>
  );

  return (
    <>
      <Card title="Auto Generate ID" actionHandler={() => setOpenDialog(true)}>
        {renderAlert()}
        {renderHeader()}
        <Box pt={2}>
          {displayRecords
            ?.sort((a, b) => {
              const nameA = a.type.toUpperCase();
              const nameB = b.type.toUpperCase();
              if (nameA < nameB) {
                return -1;
              }
              if (nameA > nameB) {
                return 1;
              }

              return 0;
            })
            .map((item, idx) => (
              <Grid
                key={item.type}
                container
                alignItems="center"
                mb={displayRecords.length - 1 === idx ? 0 : 1.875}>
                <Grid item xs={2.4}>
                  <AutoGeneratedSchema
                    type={item.type}
                    enabled={item.enabled}
                  />
                </Grid>
                <Grid item xs={2.4}>
                  <Typography
                    variant="subtitle2"
                    color={theme.palette.text.primary}
                    textAlign="center">
                    {item.prefix ? item.prefix : '-'}
                  </Typography>
                </Grid>
                <Grid item xs={2.4}>
                  <Typography
                    color={theme.palette.text.primary}
                    variant="subtitle2"
                    textAlign="center">
                    {item.numberOfDigits}
                  </Typography>
                </Grid>
                <Grid item xs={2}>
                  <Typography
                    color={theme.palette.text.primary}
                    variant="subtitle2"
                    textAlign="right">
                    {item.startFrom}
                  </Typography>
                </Grid>
                <Grid item xs={2.8} textAlign="right">
                  <StatusChip
                    label={item.enabled ? 'Enabled' : 'Disabled'}
                    color={item.enabled ? 'white' : 'text.primary'}
                    bgColor={item.enabled ? 'success.darkSuccess' : grey[300]}
                    length="short"
                    style={{fontWeight: 600}}
                  />
                </Grid>
              </Grid>
            ))}
        </Box>
      </Card>
      <AutoGeneratedIdDialog
        openDialog={openDialog}
        setOpenDialog={setOpenDialog}
      />
    </>
  );
};

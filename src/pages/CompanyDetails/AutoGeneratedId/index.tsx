import {useEffect, useState} from 'react';
import {useTranslation} from 'react-i18next';
import Typography from '@mui/material/Typography';
import {Alert, Box, Grid} from '@mui/material';
import EditIcon from '@mui/icons-material/Edit';
import {InfoCard} from 'components/InfoCard';
import {useCompanyAutoNumberConfig} from 'hooks/reactQuery/useCompanies';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import {StatusChip} from 'components/StatusChip';
import useTheme from '@mui/material/styles/useTheme';
import {AutoNumberConfigRecord} from 'models/service-company';
import AutoGeneratedIdDialog from 'components/AutoGeneratedIdDialog';
import {configRecords} from 'utils/config-records';
import {AutoGeneratedSchema} from './AutoGeneratedSchema';

interface Props {
  containerStyles?: {[key: string]: any};
}

export const AutoGeneratedId = ({containerStyles}: Props) => {
  const [openDialog, setOpenDialog] = useState(false);
  const {user} = useUserSession();
  const theme = useTheme();
  const {t} = useTranslation();

  const [displayRecords, setDisplayRecords] = useState<
    AutoNumberConfigRecord[] | undefined
  >([]);

  const {data} = useCompanyAutoNumberConfig(
    user?.userAccount.serviceCompany.id,
  );

  useEffect(() => {
    const apiRecordsMap: any = {};

    data?.configRecords.forEach((record) => {
      apiRecordsMap[record.type] = true;
    });

    const mergedRecords = data?.configRecords.map((apiRecord) => {
      const defaultRecord = configRecords.find(
        (record) => record.type === apiRecord.type,
      );

      if (defaultRecord) {
        return {...defaultRecord, ...apiRecord};
      }
      return apiRecord;
    });

    configRecords.forEach((defaultRecord) => {
      if (!apiRecordsMap[defaultRecord.type]) {
        mergedRecords?.push(defaultRecord);
      }
    });

    setDisplayRecords(mergedRecords);
  }, [data]);

  const renderAlert = () => (
    <Alert severity="info">
      <Typography variant="subtitle2">
        {t('Automatic ID generation')}
      </Typography>
      <Typography variant="body1">
        {t(
          'Any service with disabled auto ID generation will need to be populated manually.',
        )}
      </Typography>
      <Typography variant="body1">
        {t('Configure and enable to populate automatically.')}
      </Typography>
    </Alert>
  );

  const renderHeader = () => (
    <Box
      sx={{
        p: '1em',
        border: '1px solid #8F9BB3',
        borderRadius: '4px',
        m: '1em 0em',
      }}>
      <Grid container spacing={4}>
        <Grid item xs={3}>
          <Typography variant="body1">{t('Service')}</Typography>
        </Grid>

        <Grid item xs={2.5}>
          <Typography variant="body1">{t('Prefix')}</Typography>
        </Grid>

        <Grid item xs={2}>
          <Typography variant="body1">{t('# of digits')}</Typography>
        </Grid>

        <Grid item xs={2}>
          <Typography variant="body1">{t('Start from')}</Typography>
        </Grid>

        <Grid item xs={2.5}>
          <Typography textAlign="right" variant="body1">
            {t('Status')}
          </Typography>
        </Grid>
      </Grid>
    </Box>
  );
  return (
    <InfoCard
      containerStyles={{...containerStyles}}
      header={
        <Typography variant="subtitle1">{t('Auto generated ID')}</Typography>
      }
      showHeaderBackground
      handleAction={() => setOpenDialog(true)}
      headerActionIcon={<EditIcon />}>
      <>
        {renderAlert()}
        {renderHeader()}
        <Grid p="0em 1em 0em 0em">
          {displayRecords
            ?.sort((a, b) => {
              const nameA = a.type.toUpperCase();
              const nameB = b.type.toUpperCase();
              if (nameA < nameB) {
                return -1;
              }
              if (nameA > nameB) {
                return 1;
              }

              return 0;
            })
            .map((item) => (
              <Grid
                key={item.type}
                container
                spacing={4}
                alignItems="center"
                marginBottom="1em">
                <Grid item xs={3}>
                  <AutoGeneratedSchema
                    type={item.type}
                    enabled={item.enabled}
                  />
                </Grid>
                <Grid item xs={2.5}>
                  <Typography
                    variant="body1"
                    color={
                      item.enabled
                        ? theme.palette.text.primary
                        : theme.palette.text.secondary
                    }>
                    {item.prefix ? item.prefix : '-'}
                  </Typography>
                </Grid>
                <Grid item xs={1.5}>
                  <Typography
                    color={
                      item.enabled
                        ? theme.palette.text.primary
                        : theme.palette.text.secondary
                    }
                    variant="body1"
                    textAlign="center">
                    {item.numberOfDigits}
                  </Typography>
                </Grid>
                <Grid item xs={2}>
                  <Typography
                    color={
                      item.enabled
                        ? theme.palette.text.primary
                        : theme.palette.text.secondary
                    }
                    variant="body1"
                    textAlign="center">
                    {item.startFrom}
                  </Typography>
                </Grid>
                <Grid item xs={3} textAlign="right">
                  <StatusChip
                    label={item.enabled ? 'Enabled' : 'Disabled'}
                    color={item.enabled ? 'success' : 'info'}
                  />
                </Grid>
              </Grid>
            ))}
        </Grid>
        <AutoGeneratedIdDialog
          openDialog={openDialog}
          setOpenDialog={setOpenDialog}
        />
      </>
    </InfoCard>
  );
};

import {useEffect, useRef, useState} from 'react';
import {useTranslation} from 'react-i18next';
import Typography from '@mui/material/Typography';
import {Alert, Box, Grid, Switch, TextField} from '@mui/material';
import * as Yup from 'yup';
import {useFormik, getIn} from 'formik';
import EditIcon from '@mui/icons-material/Edit';
import {InfoCard} from 'components/InfoCard';
import {AutoNumberConfigRecord} from 'models/service-company';
import {Dialog} from 'components/Dialog';
import {
  useCompanyAutoNumberConfig,
  useUpdateAutoNumberConfig,
} from 'hooks/reactQuery/useCompanies';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import {StatusChip} from 'components/StatusChip';
import useTheme from '@mui/material/styles/useTheme';
import {FormInput} from 'components/form/FormInput';
import {AutoGeneratedSchema} from './AutoGeneratedSchema';

interface Props {
  containerStyles?: {[key: string]: any};
}

const validationSchema = Yup.object().shape({
  configRecords: Yup.array().of(
    Yup.object().shape({
      type: Yup.string(),
      prefix: Yup.string(),
      startFrom: Yup.boolean(),
      numberOfDigits: Yup.number(),
      enabled: Yup.boolean(),
    }),
  ),
});

export const AutoGeneratedId = ({containerStyles}: Props) => {
  const [openDialog, setOpenDialog] = useState(false);
  const {user} = useUserSession();
  const theme = useTheme();
  const {t} = useTranslation();

  const {data, isLoading} = useCompanyAutoNumberConfig(
    user?.userAccount.serviceCompany.id,
  );

  const [configRecords, setConfigRecords] = useState<AutoNumberConfigRecord[]>(
    [],
  );

  const {mutateAsync: updateAutoNumberConfig} = useUpdateAutoNumberConfig(
    'Updated Successfully',
  );

  const formik = useFormik<{
    configRecords: {
      type: string;
      prefix: string;
      numberOfDigits: number;
      enabled: boolean;
      startFrom: string;
    }[];
  }>({
    initialValues: {
      configRecords: [],
    },
    onSubmit: () => {},
    validationSchema,
  });

  const onSave = () => {
    console.log(formik.values, 'formik.values');
  };

  useEffect(() => {
    setConfigRecords(data?.configRecords!);
  }, [isLoading]);

  useEffect(() => {
    formik.setFieldValue('configRecords', data?.configRecords!);
  }, [isLoading]);

  return (
    <InfoCard
      containerStyles={{...containerStyles}}
      header={
        <Typography variant="subtitle1">{t('Auto generated ID')}</Typography>
      }
      showHeaderBackground
      handleAction={() => setOpenDialog(true)}
      headerActionIcon={<EditIcon />}>
      <>
        <Alert severity="info">
          <Typography variant="subtitle2">
            {t('Automatic ID generation')}
          </Typography>
          <Typography variant="body1">
            {t(
              'Any service with disabled auto ID generation will need to be populated manually.',
            )}
          </Typography>
          <Typography variant="body1">
            {t('Configure and enable to populate automatically.')}
          </Typography>
        </Alert>
        <Box
          sx={{
            p: '1em',
            border: '1px solid #8F9BB3',
            borderRadius: '4px',
            m: '1em 0em',
          }}>
          <Grid display="flex" width="100%">
            <Grid item xs={3.5}>
              <Typography
                variant="subtitle2"
                color={theme.palette.text.secondary}>
                {t('Service')}
              </Typography>
            </Grid>

            <Grid xs={2.5}>
              <Typography
                variant="subtitle2"
                color={theme.palette.text.secondary}>
                {t('Prefix')}
              </Typography>
            </Grid>

            <Grid xs={1.5}>
              <Typography
                variant="subtitle2"
                color={theme.palette.text.secondary}
                textAlign="center">
                {t('# of digits')}
              </Typography>
            </Grid>

            <Grid xs={2.5}>
              <Typography
                variant="subtitle2"
                color={theme.palette.text.secondary}
                textAlign="right">
                {t('Start from')}
              </Typography>
            </Grid>

            <Grid xs={2.5}>
              <Typography
                textAlign="right"
                color={theme.palette.text.secondary}
                variant="subtitle2">
                {t('Status')}
              </Typography>
            </Grid>
          </Grid>
        </Box>
        <Grid p="0em 1em 0em 0em">
          {configRecords?.map((item) => (
            <Grid
              key={item.type}
              display="flex"
              alignItems="center"
              padding="0.3em 0em">
              <Grid xs={3.5}>
                <AutoGeneratedSchema type={item.type} enabled={item.enabled} />
              </Grid>
              <Grid xs={2.5}>
                <Typography
                  variant="body1"
                  color={
                    item.enabled
                      ? theme.palette.text.primary
                      : theme.palette.text.secondary
                  }>
                  {item.prefix}
                </Typography>
              </Grid>
              <Grid xs={1.5}>
                <Typography
                  color={
                    item.enabled
                      ? theme.palette.text.primary
                      : theme.palette.text.secondary
                  }
                  variant="body1"
                  textAlign="center">
                  {item.numberOfDigits}
                </Typography>
              </Grid>
              <Grid xs={2.5}>
                <Typography
                  color={
                    item.enabled
                      ? theme.palette.text.primary
                      : theme.palette.text.secondary
                  }
                  variant="body1"
                  textAlign="right">
                  {item.startFrom}
                </Typography>
              </Grid>
              <Grid xs={2.5} textAlign="right">
                <StatusChip
                  label={item.enabled ? 'Enabled' : 'Disabled'}
                  color={item.enabled ? 'success' : 'info'}
                />
              </Grid>
            </Grid>
          ))}
        </Grid>
        <Dialog
          title="Auto generated ID"
          onCancel={() => setOpenDialog(false)}
          onSave={() => onSave()}
          dialogProps={{
            maxWidth: 'md',
            open: openDialog || false,
          }}>
          <Alert severity="info">
            <Typography variant="subtitle2">
              {t('Automatic ID generation')}
            </Typography>
            <Typography variant="body1">
              {t(
                'Any service with disabled auto ID generation will need to be populated manually.',
              )}
            </Typography>
            <Typography variant="body1">
              {t('Configure and enable to populate automatically.')}
            </Typography>
          </Alert>
          <Box
            sx={{
              p: '1em',
              border: '1px solid #8F9BB3',
              borderRadius: '4px',
              m: '1em 0em',
            }}>
            <Grid display="flex" width="100%">
              <Grid item xs={3}>
                <Typography variant="body1">{t('Service')}</Typography>
              </Grid>

              <Grid xs={2.5}>
                <Typography variant="body1">{t('Prefix')}</Typography>
              </Grid>

              <Grid xs={1.5}>
                <Typography variant="body1">{t('# of digits')}</Typography>
              </Grid>

              <Grid xs={2.5}>
                <Typography variant="body1">{t('Start from')}</Typography>
              </Grid>

              <Grid xs={2.5}>
                <Typography textAlign="right" variant="body1">
                  {t('Status')}
                </Typography>
              </Grid>
            </Grid>
          </Box>
          <Grid>
            {formik.values.configRecords?.map((item, index) => (
              <Grid
                key={item.type}
                display="flex"
                alignItems="center"
                padding="0.3em 0em">
                <Grid xs={3}>
                  <AutoGeneratedSchema
                    type={configRecords[index].type}
                    enabled={configRecords[index].enabled}
                  />
                </Grid>
                <Grid xs={2.5} pr={4}>
                  <TextField
                    size="small"
                    id="prefix"
                    disabled={!formik.values.configRecords[index].enabled}
                    value={formik.values.configRecords[index].prefix}
                    name={`configRecords[${index}].prefix`}
                    onChange={formik.handleChange}
                    onBlur={formik.handleBlur}
                    type="text"
                  />
                </Grid>
                <Grid xs={1.5} pr={4}>
                  <TextField
                    size="small"
                    id="numberOfDigits"
                    disabled={!formik.values.configRecords[index].enabled}
                    value={formik.values.configRecords[index].numberOfDigits}
                    name={`configRecords[${index}].numberOfDigits`}
                    onChange={formik.handleChange}
                    type="number"
                    InputProps={{
                      sx: {
                        '& input': {
                          textAlign: 'right',
                        },
                      },
                    }}
                  />
                </Grid>
                <Grid xs={2.5} pr={4}>
                  <TextField
                    size="small"
                    id="startFrom"
                    disabled={!formik.values.configRecords[index].enabled}
                    value={formik.values.configRecords[index].startFrom}
                    name={`configRecords[${index}].startFrom`}
                    onChange={formik.handleChange}
                    type="number"
                    InputProps={{
                      sx: {
                        '& input': {
                          textAlign: 'right',
                        },
                      },
                    }}
                  />
                </Grid>
                <Grid
                  xs={2.5}
                  width="100%"
                  display="flex"
                  justifyContent="flex-start"
                  alignItems="center">
                  <Box width="25%">
                    <Switch
                      defaultChecked={
                        !!formik.values.configRecords[index].enabled
                      }
                      id="enabled"
                      name={`configRecords[${index}].enabled`}
                      onChange={formik.handleChange}
                    />
                  </Box>

                  <Typography width="50%" textAlign="left" pl="1em">
                    {item.enabled ? t('Enabled') : t('Disabled')}
                  </Typography>
                </Grid>
              </Grid>
            ))}
          </Grid>
        </Dialog>
      </>
    </InfoCard>
  );
};

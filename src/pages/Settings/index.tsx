import {Fragment} from 'react';
import {Route, Routes, useLocation, useNavigate} from 'react-router-dom';
import {useTranslation} from 'react-i18next';
import {theme} from 'theme';
import {
  Box,
  Drawer,
  Grid,
  List,
  ListItem,
  ListItemButton,
  ListItemIcon,
  ListItemText,
} from '@mui/material';
import {
  AutoAwesomeOutlined,
  ExtensionOutlined,
  FactCheckOutlined,
  InfoOutlined,
  MonetizationOnOutlined,
} from '@mui/icons-material';
import {Progress} from 'components/Progress';
import {useCompanyById} from 'hooks/reactQuery/useCompanies';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import {BasicInformation} from 'pages/CompanyDetails/BasicInformation';
import {Addresses} from 'pages/CompanyDetails/Addresses';
import {Settings} from 'pages/CompanyDetails/Settings';
import {LegalInformation} from 'pages/CompanyDetails/LegalInformation';
import {PaymentInformation} from 'pages/CompanyDetails/PaymentInformation';
import {BillingInformation} from 'pages/CompanyDetails/BillingInformation';
import {WhiteLabel} from 'pages/CompanyDetails/WhiteLabel';
import {Policies} from 'pages/CompanyDetails/Policies';
import {DefinedContractNames} from 'pages/CompanyDetails/DefinedContractNames';
import {AutoGeneratedId} from 'pages/CompanyDetails/AutoGeneratedId';
import {ChecklistDataGrid} from './ChecklistDataGrid';
import Integrations from './Integrations';
import Automations from './Automations';
import Checklist from './Checklist';
import Financials from './Financials';

interface DrawerItem {
  label: string;
  icon: JSX.Element;
  route: string;
  component: JSX.Element;
  children?: DrawerItem[];
}

export const SettingsPage = () => {
  const navigate = useNavigate();
  const {t} = useTranslation();
  const {user} = useUserSession();
  const location = useLocation();
  const currentRoute = location.pathname.split('/').pop() || '/';

  const {data: company, isLoading} = useCompanyById(
    user?.userAccount.serviceCompany.id,
  );

  const drawerItems = [
    {
      label: 'Basic Information',
      icon: <InfoOutlined />,
      route: '/',
      component: (
        <>
          <Grid container spacing={2}>
            <Grid item md={3} sm={12}>
              <BasicInformation
                company={company!}
                containerStyles={{height: '100%'}}
              />
            </Grid>
            <Grid item md={6} sm={12}>
              <Addresses
                company={company!}
                containerStyles={{height: '100%'}}
              />
            </Grid>
            <Grid item md={3} sm={12}>
              <Settings company={company!} containerStyles={{height: '100%'}} />
            </Grid>
          </Grid>
          <Grid container spacing={2} sx={{mt: '0.3em'}}>
            <Grid item md={3} sm={12}>
              <LegalInformation company={company!} />
            </Grid>
            <Grid item md={6} sm={12}>
              <PaymentInformation
                company={company!}
                containerStyles={{height: '100%'}}
              />
            </Grid>
            <Grid item md={3} sm={12}>
              <BillingInformation
                company={company!}
                containerStyles={{height: '100%'}}
              />
            </Grid>
          </Grid>
          <Grid container spacing={2} sx={{my: '0.3em'}}>
            <Grid item md={3} sm={12}>
              <Policies company={company!} containerStyles={{height: '100%'}} />
            </Grid>
            <Grid item md={6} sm={12}>
              <DefinedContractNames
                company={company!}
                containerStyles={{height: '100%'}}
              />
            </Grid>
            <Grid item md={3} sm={12}>
              <WhiteLabel
                company={company!}
                containerStyles={{height: '100%'}}
              />
            </Grid>
            <Grid item md={9} sm={12}>
              <AutoGeneratedId containerStyles={{height: '100%'}} />
            </Grid>
          </Grid>
        </>
      ),
    },
    {
      label: 'Financials',
      icon: <MonetizationOnOutlined />,
      route: 'financials',
      component: <Financials company={company!} />,
    },
    {
      label: 'Automations',
      icon: <AutoAwesomeOutlined />,
      route: 'automations',
      component: <Automations company={company!} />,
    },
    {
      label: 'Checklists',
      icon: <FactCheckOutlined />,
      route: 'checklist',
      component: <ChecklistDataGrid />,
      children: [
        {
          label: 'New Checklist',
          icon: <FactCheckOutlined />,
          route: 'new',
          component: <Checklist />,
        },
        {
          label: 'Edit Checklist',
          icon: <FactCheckOutlined />,
          route: ':id',
          component: <Checklist />,
        },
      ],
    },
    {
      label: 'Integrations',
      icon: <ExtensionOutlined />,
      route: 'integrations',
      component: <Integrations />,
    },
  ];

  if (isLoading) {
    return <Progress />;
  }

  const DrawerList = (
    <List sx={{m: 3}}>
      {drawerItems.map((i) => {
        const isActive =
          i.route === '/' && currentRoute === 'settings'
            ? true
            : i.children && i.children.length > 0
            ? location.pathname.includes(i.route)
            : i.route === currentRoute;

        return (
          <ListItem key={i.route} disablePadding>
            <ListItemButton
              sx={{
                px: 1,
                py: 0.75,
                gap: 1,
                borderRadius: '4px',
                ...(isActive && {
                  backgroundColor: theme.palette.primary.outlinedHoverBg,
                  color: theme.palette.primary.dark,
                }),
              }}
              onClick={() => navigate(i.route === '/' ? '/settings' : i.route)}>
              <ListItemIcon
                sx={{
                  minWidth: 24,
                  ...(isActive && {
                    color: theme.palette.primary.light,
                  }),
                }}>
                {i.icon}
              </ListItemIcon>
              <ListItemText
                primary={t(i.label)}
                primaryTypographyProps={{
                  typography: 'subtitle1',
                  fontWeight: 600,
                }}
              />
            </ListItemButton>
          </ListItem>
        );
      })}
    </List>
  );

  const drawerWidth = 274;

  const renderRoutes = (items: DrawerItem[]) => {
    const element = (component: JSX.Element) => (
      <Box
        pl={`${drawerWidth + 24}px`}
        pr="24px"
        height="100%"
        display="flex"
        flexDirection="column">
        {component}
      </Box>
    );
    return items.map((item, idx) => (
      <Fragment key={`${item.route}-${idx}`}>
        <Route path={item.route} element={element(item.component)} />
        {item.children &&
          item.children?.map((i) => (
            <Route
              key={`${i.route}-${idx}`}
              path={`${item.route}/${i.route}`}
              element={element(i.component)}
            />
          ))}
      </Fragment>
    ));
  };

  return (
    <>
      <Drawer
        sx={{
          width: drawerWidth,
          flexShrink: 0,
          '& .MuiDrawer-paper': {
            zIndex: (thm) => thm.zIndex.drawer - 300,
            width: drawerWidth,
            boxSizing: 'border-box',
            ml: '72px',
            mt: '82px',
            backgroundColor: 'white',
            color: 'text.secondary',
          },
        }}
        variant="permanent">
        {DrawerList}
      </Drawer>
      <Routes>{renderRoutes(drawerItems)}</Routes>
    </>
  );
};

export default SettingsPage;

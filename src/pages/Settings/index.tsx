import {Fragment, lazy, Suspense} from 'react';
import {Route, Routes, useLocation, useNavigate} from 'react-router-dom';
import {useTranslation} from 'react-i18next';
import {theme} from 'theme';
import {
  Box,
  Drawer,
  Grid,
  List,
  ListItem,
  ListItemButton,
  ListItemIcon,
  ListItemText,
} from '@mui/material';
import {
  AutoAwesomeOutlined,
  ExtensionOutlined,
  FactCheckOutlined,
  InfoOutlined,
  MonetizationOnOutlined,
  PictureAsPdfOutlined,
  TextSnippetOutlined,
} from '@mui/icons-material';
import {Progress} from 'components/Progress';
import {useCompanyById} from 'hooks/reactQuery/useCompanies';
import {useUserSession} from 'hooks/reactQuery/useUserSession';

const BasicInformation = lazy(() =>
  import('pages/CompanyDetails/BasicInformation').then((m) => ({
    default: m.BasicInformation,
  })),
);
const Settings = lazy(() =>
  import('pages/CompanyDetails/Settings').then((m) => ({
    default: m.Settings,
  })),
);
const LegalInformation = lazy(() =>
  import('pages/CompanyDetails/LegalInformation').then((m) => ({
    default: m.LegalInformation,
  })),
);
const Policies = lazy(() =>
  import('pages/CompanyDetails/Policies').then((m) => ({
    default: m.Policies,
  })),
);
const AutoGeneratedId = lazy(() =>
  import('pages/CompanyDetails/AutoGeneratedId').then((m) => ({
    default: m.AutoGeneratedId,
  })),
);
const AbsenceAndPresence = lazy(() =>
  import('pages/CompanyDetails/AbsenceAndPresence').then((m) => ({
    default: m.AbsenceAndPresence,
  })),
);
const ChecklistDataGrid = lazy(() =>
  import('./ChecklistDataGrid').then((m) => ({
    default: m.ChecklistDataGrid,
  })),
);
const Integrations = lazy(() => import('./Integrations'));
const Automations = lazy(() => import('./Automations'));
const Checklist = lazy(() => import('./Checklist'));
const Financials = lazy(() => import('./Financials'));
const TextBlocks = lazy(() => import('./TextBlocks'));
const PDFSettingLayout = lazy(() => import('./PdfSettings/layout'));

interface DrawerItem {
  label: string;
  icon: JSX.Element;
  route: string;
  component: JSX.Element;
  children?: DrawerItem[];
}

export const SettingsPage = () => {
  const navigate = useNavigate();
  const {t} = useTranslation();
  const {user} = useUserSession();
  const location = useLocation();
  const currentRoute = location.pathname.split('/').pop() || '/';

  const {data: company, isLoading} = useCompanyById(
    user?.userAccount.serviceCompany.id,
  );

  const drawerItems = [
    {
      label: 'Basic Information',
      icon: <InfoOutlined />,
      route: '/',
      component: (
        <Grid container spacing={2}>
          <Grid item xs={12}>
            <BasicInformation company={company!} />
          </Grid>
          <Grid item md={6}>
            <Settings company={company!} />
          </Grid>
          <Grid item md={6}>
            <Policies company={company!} />
          </Grid>
          <Grid item xs={6}>
            <LegalInformation company={company!} />
          </Grid>
          <Grid item xs={6}>
            <AbsenceAndPresence />
          </Grid>
          <Grid item xs={12}>
            <AutoGeneratedId />
          </Grid>
        </Grid>
      ),
    },
    {
      label: 'Financials',
      icon: <MonetizationOnOutlined />,
      route: 'financials',
      component: <Financials company={company!} />,
    },
    {
      label: 'Automations',
      icon: <AutoAwesomeOutlined />,
      route: 'automations',
      component: <Automations company={company!} />,
    },
    {
      label: 'PDF',
      icon: <PictureAsPdfOutlined />,
      route: 'pdf',
      component: <PDFSettingLayout company={company!} />,
    },
    {
      label: 'Checklists',
      icon: <FactCheckOutlined />,
      route: 'checklist',
      component: <ChecklistDataGrid />,
      children: [
        {
          label: 'New Checklist',
          icon: <FactCheckOutlined />,
          route: 'new',
          component: <Checklist />,
        },
        {
          label: 'Edit Checklist',
          icon: <FactCheckOutlined />,
          route: ':id',
          component: <Checklist />,
        },
      ],
    },
    {
      label: 'Text Blocks',
      icon: <TextSnippetOutlined />,
      route: 'text-blocks',
      component: <TextBlocks company={company!} />,
    },
    {
      label: 'Integrations',
      icon: <ExtensionOutlined />,
      route: 'integrations',
      component: <Integrations />,
    },
  ];

  if (isLoading) {
    return <Progress />;
  }

  const DrawerList = (
    <List sx={{m: 3}}>
      {drawerItems.map((i) => {
        const isActive =
          i.route === '/' && currentRoute === 'settings'
            ? true
            : i.children && i.children.length > 0
            ? location.pathname.includes(i.route)
            : i.route === currentRoute;

        return (
          <ListItem key={i.route} disablePadding>
            <ListItemButton
              sx={{
                px: 1,
                py: 0.75,
                gap: 1,
                borderRadius: '4px',
                ...(isActive && {
                  backgroundColor: theme.palette.primary.outlinedHoverBg,
                  color: theme.palette.primary.dark,
                }),
              }}
              onClick={() => navigate(i.route === '/' ? '/settings' : i.route)}>
              <ListItemIcon
                sx={{
                  minWidth: 24,
                  ...(isActive && {
                    color: theme.palette.primary.light,
                  }),
                }}>
                {i.icon}
              </ListItemIcon>
              <ListItemText
                primary={t(i.label)}
                primaryTypographyProps={{
                  typography: 'subtitle1',
                  fontWeight: 600,
                }}
              />
            </ListItemButton>
          </ListItem>
        );
      })}
    </List>
  );

  const drawerWidth = 250;

  const renderRoutes = (items: DrawerItem[]) => {
    const element = (component: JSX.Element) => (
      <Box
        pl={`${drawerWidth + 24}px`}
        pr="24px"
        height="100%"
        display="flex"
        flexDirection="column">
        {component}
      </Box>
    );
    return items.map((item, idx) => (
      <Fragment key={`${item.route}-${idx}`}>
        <Route path={item.route} element={element(item.component)} />
        {item.children &&
          item.children?.map((i) => (
            <Route
              key={`${i.route}-${idx}`}
              path={`${item.route}/${i.route}`}
              element={element(i.component)}
            />
          ))}
      </Fragment>
    ));
  };

  return (
    <>
      <Drawer
        sx={{
          width: drawerWidth,
          flexShrink: 0,
          '& .MuiDrawer-paper': {
            zIndex: (thm) => thm.zIndex.drawer - 300,
            width: drawerWidth,
            boxSizing: 'border-box',
            ml: '72px',
            mt: '82px',
            backgroundColor: 'white',
            color: 'text.secondary',
          },
        }}
        variant="permanent">
        {DrawerList}
      </Drawer>
      <Suspense fallback={<Progress />}>
        <Routes>{renderRoutes(drawerItems)}</Routes>
      </Suspense>
    </>
  );
};

export default SettingsPage;

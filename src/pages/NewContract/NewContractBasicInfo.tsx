import {FC, useEffect, useState} from 'react';
import {theme} from 'theme';
import Grid from '@mui/material/Grid';
import Box from '@mui/material/Box';
import Typography from '@mui/material/Typography';
import Button from '@mui/material/Button';
import AutoAwesome from '@mui/icons-material/AutoAwesome';
import {FormikProps} from 'formik';
import {useTranslation} from 'react-i18next';
import {CustomerAutoComplete} from 'components/CustomerAutocomplete';
import {DatePicker} from 'components/DatePicker';
import {FormSelect} from 'components/form/FormSelect';
import {FormInput} from 'components/form/FormInput';
import AutoGeneratedIdDialog from 'components/AutoGeneratedIdDialog';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import {
  useCompanyAutoNumberConfig,
  useCompanyNextNumber,
} from 'hooks/reactQuery/useCompanies';
import {ContractBasicInfoFormModel, ContractView} from 'models/contract';
import {PropertyOwnerView} from 'models/propertyManager';
import {ServiceCompanyNumberType} from 'models/service-company';

interface Props {
  formik: FormikProps<ContractBasicInfoFormModel>;
  getCustomer?: (customer?: PropertyOwnerView) => void;
  initialCustomer?: PropertyOwnerView;
  contractResource: ContractView[];
}

const NewContractBasicInfo: FC<Props> = ({
  formik,
  getCustomer,
  initialCustomer,
  contractResource,
}) => {
  const {t} = useTranslation();
  const {user} = useUserSession();
  const [customer, setCustomer] = useState(initialCustomer);
  const [openDialog, setOpenDialog] = useState<boolean>(false);
  const [externalIdActive, setExternalIdActive] = useState<boolean>(false);
  const {data: companyAutoNumberConfig} = useCompanyAutoNumberConfig(
    user?.userAccount.serviceCompany.id,
  );
  const {data: companyNextNumber, refetch: refetchCompanyNumber} =
    useCompanyNextNumber(
      {
        type: ServiceCompanyNumberType.CONTRACT,
      },
      user?.userAccount.serviceCompany.id,
    );

  useEffect(() => {
    if (getCustomer) {
      getCustomer(customer);
    }
  }, [customer]);

  const handleFocus = (e: any) => {
    setExternalIdActive(e.target.name);
  };

  return (
    <Grid container spacing={4}>
      <Grid item xs={4}>
        <CustomerAutoComplete
          getCustomer={(value) => {
            formik.setValues({
              ...formik.values,
              propertyOwnerId: value ? value.id : '',
            });
            if (value) {
              setCustomer(value);
            }
          }}
          initialValue={initialCustomer || null}
          textFieldProps={{
            error: !!(
              formik.errors.propertyOwnerId && formik.touched.propertyOwnerId
            ),
            helperText:
              formik.errors.propertyOwnerId && formik.touched.propertyOwnerId
                ? formik.errors.propertyOwnerId
                : '',
            label: 'Customer',
            name: 'propertyOwnerId',
            onBlur: formik.handleBlur,
          }}
        />
      </Grid>
      <Box width="100%" />
      <Grid item xs={4}>
        <DatePicker
          getSelectedDate={(val) => formik.setFieldValue('startDate', val)}
          textFieldProps={{
            name: 'startDate',
            id: 'startDate',
            label: 'Start Date',
            onChange: formik.handleChange,
            required: true,
            helperText:
              formik.errors.startDate && formik.touched.startDate
                ? formik.errors.startDate
                : '',
            error: !!(formik.touched.startDate && formik.errors.startDate),
            onBlur: formik.handleBlur,
          }}
          defaultDate={formik.values.startDate}
          maxDate={formik.values.endDate!}
        />
      </Grid>
      <Grid item xs={4}>
        <DatePicker
          getSelectedDate={(val) => formik.setFieldValue('endDate', val)}
          textFieldProps={{
            name: 'endDate',
            id: 'endDate',
            label: 'End Date',
            onChange: formik.handleChange,
            required: true,
            helperText:
              formik.errors.endDate && formik.touched.endDate
                ? formik.errors.endDate
                : '',
            error: !!(formik.touched.endDate && formik.errors.endDate),
            onBlur: formik.handleBlur,
          }}
          defaultDate={formik.values.endDate}
          minDate={
            new Date(
              new Date(formik.values.startDate! || Date.now()).getTime() +
                86400000,
            )
          }
        />
      </Grid>
      <Box width="100%" />
      <Grid item xs={4}>
        <FormSelect
          labelId="contractTypeSelect-label"
          label="Select Contract Type"
          options={(
            user?.userAccount?.serviceCompany?.settings?.contractNameTypes ?? []
          ).map((item) => ({
            label: item.name,
            value: item.name,
          }))}
          selectProps={{
            id: 'contractTypeSelect',
            value: formik.values.name,
            onChange: formik.handleChange,
            name: 'name',
            onBlur: formik.handleBlur,
          }}
          required
        />
      </Grid>
      <Grid item xs={4}>
        <FormInput
          props={{
            size: 'small',
            placeholder: 'e.g 1234',
            label: 'Contract Number',
            name: 'externalId',
            value: formik.values.externalId,
            helperText: formik.touched.externalId && formik.errors.externalId,
            error: !!formik.errors.externalId && formik.touched.externalId,
            onChange: formik.handleChange,
            onBlur: formik.handleBlur,
          }}
          handleFocus={handleFocus}
        />
        {(externalIdActive || formik.touched.externalId) &&
          formik.values.externalId &&
          contractResource.filter(
            (item) => item.externalId === formik.values.externalId,
          ).length > 0 && (
            <Typography
              color="error"
              fontSize="0.75rem"
              letterSpacing="0.03em"
              padding="0.45em 0.65em">
              {t('This ID is already taken. Please enter a different one.')}
            </Typography>
          )}
        {externalIdActive &&
        !formik.values.externalId &&
        companyAutoNumberConfig?.configRecords.find(
          (item) => item.type === ServiceCompanyNumberType.CONTRACT,
        )?.enabled ? (
          <Box
            sx={{
              borderRadius: '4px',
              boxShadow: '0px 9px 46px 8px #0000001F',
              marginTop: '0.2em',
            }}>
            <Button
              sx={{
                display: 'flex',
                flexDirection: 'column',
                justifyContent: 'flex-start',
                textAlign: 'left',
                alignItems: 'flex-start',
                width: '100%',
                padding: '1em 2em',
              }}
              onClick={() => {
                refetchCompanyNumber();
                formik.setFieldValue('externalId', companyNextNumber?.value);
              }}>
              <Box
                sx={{
                  display: 'flex',
                  flexDirection: 'row',
                  alignItems: 'center',
                  paddingBottom: '0.6em',
                }}>
                <AutoAwesome />
                <Typography variant="subtitle2" sx={{paddingLeft: '0.5em'}}>
                  {t('Generate ID')}
                </Typography>
              </Box>

              <Typography variant="body2" color={theme.palette.text.secondary}>
                {t('Customizable in Settings')}
              </Typography>
            </Button>
          </Box>
        ) : (
          externalIdActive &&
          !formik.values.externalId &&
          !companyAutoNumberConfig?.configRecords.find(
            (item) => item.type === ServiceCompanyNumberType.CONTRACT,
          )?.enabled && (
            <Box
              sx={{
                borderRadius: '4px',
                boxShadow: '0px 9px 46px 8px #0000001F',
                marginTop: '0.2em',
              }}>
              <Button
                sx={{
                  display: 'flex',
                  flexDirection: 'column',
                  justifyContent: 'flex-start',
                  textAlign: 'left',
                  alignItems: 'flex-start',
                  width: '100%',
                  padding: '1em 2em',
                }}
                onClick={() => setOpenDialog(true)}>
                <Box
                  sx={{
                    display: 'flex',
                    flexDirection: 'row',
                    alignItems: 'center',
                    paddingBottom: '0.6em',
                  }}>
                  <AutoAwesome />
                  <Typography variant="subtitle2" sx={{paddingLeft: '0.5em'}}>
                    {t('Enable Automatic ID Generation')}
                  </Typography>
                </Box>

                <Typography
                  variant="body2"
                  color={theme.palette.text.secondary}>
                  {t('Allows for easier number input')}
                </Typography>
              </Button>
            </Box>
          )
        )}
      </Grid>
      <Box width="100%" />
      <Grid item xs={8}>
        <FormInput
          containerStyles={{mt: '1rem'}}
          props={{
            label: 'Description',
            name: 'description',
            value: formik.values.description,
            onChange: formik.handleChange,
            onBlur: formik.handleBlur,
            multiline: true,
            minRows: 6,
            maxRows: 6,
          }}
        />
      </Grid>
      <AutoGeneratedIdDialog
        openDialog={openDialog}
        setOpenDialog={setOpenDialog}
      />
    </Grid>
  );
};

export default NewContractBasicInfo;

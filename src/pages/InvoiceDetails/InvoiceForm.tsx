const isExternalIdUnique = async (resource: InvoiceView[], value?: string) => {
  if (!value) {
    return true;
  }

  try {
    return !(resource && resource.some((item) => item.externalId === value));
  } catch (error) {
    console.error('Error checking externalId uniqueness:', error);
    return true;
  }
};


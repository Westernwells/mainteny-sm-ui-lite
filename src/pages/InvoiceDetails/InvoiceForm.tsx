interface Props {
  invoice?: InvoiceView;
  serviceOrderResource?: ServiceOrderView;
  formType?: 'new' | 'edit';
  invoiceType?: InvoiceType;
  customer?: PropertyOwnerView;
}

const payment = {
  accountNumber: '',
  bic: '',
  iban: '',
};

const dateToString = (date: Date) => date.toISOString().split('T')[0];

const alternativeInvoiceDestinationTooltip =
  'Enter address to receive invoice if different from billing or shipping address. Ensure accuracy to prevent misdelivery.';

const pageSize = 50;

export const InvoiceForm = ({
  invoice,
  serviceOrderResource,
  formType = 'new',
  invoiceType,
  customer: customerByProp,
}: Props) => {
  const {t} = useTranslation();
  const DEFAULT_LABOR_COST_TEXT = t('Labor costs without VAT: {LABOR_COST}');
  const DEFAULT_MATERIAL_COST_TEXT = t(
    'Material costs without VAT: {MATERIAL_COST}',
  );
  const DEFAULT_INVOICE_MATERIAL_LABOR_COST_TEXT = `${DEFAULT_LABOR_COST_TEXT}\n${DEFAULT_MATERIAL_COST_TEXT}`;

  const theme = useTheme();
  const formatDate = useFormatDate();
  const navigate = useNavigate();
  const [searchParams, setSearchParams] = useSearchParams();
  const [resetDueDatePicker, setResetDueDatePicker] = useState(false);
  const {user} = useUserSession();
  const percentageVat =
    user?.userAccount?.serviceCompany?.settings?.percentageVat ?? 0;
  const currentCurrency = useCurrentCurrency();
  const {enqueueSnackbar} = useSnackbar();

  const {mutateAsync: updateInvoiceAsync, isLoading: isUpdating} =
    useUpdateInvoice();
  const {mutateAsync: createNewInvoice, isLoading: isCreating} =
    useCreateInvoice();
  const {mutateAsync: deleteInvoice} = useDeleteInvoice();
  const {mutateAsync: publishInvoice, isLoading: isPublishing} =
    usePublishInvoice({
      shouldNavigate: false,
    });
  const {data: downloadUrl} = useDownloadUrl(
    invoice ? [invoice.additionalInfo.pdfPath] : [],
  );
  const [isDrawerOpen] = useState<boolean>(true);
  const [isAddNewCustomerDialogOpen, setIsAddNewCustomerDialogOpen] =
    useState<boolean>(false);
  const [isSendEmailDialogOpen, setIsSendEmailDialogOpen] = useState(false);
  const [isDeleteDialogOpen, setIsDeleteDialogOpen] = useState(false);
  const [openContractPaymentTermsDialog, setOpenContractPaymentTermsDialog] =
    useState(false);
  const [
    openContractPaymentTermSelectDialog,
    setOpenContractPaymentTermSelectDialog,
  ] = useState(false);
  const [showCheckListTooltip, setShowCheckListTooltip] = useState(false);
  const [showWorkReportTooltip, setShowWorlReportTooltip] = useState(false);

  const [customer, setCustomer] = useState<
    PropertyOwnerView | PropertyOwnerSimpleView | undefined
  >(customerByProp);
  const [serviceOrder, setServiceOrder] = useState<
    ServiceOrderView | undefined
  >(serviceOrderResource ?? undefined);

  const [isWorkReportPDFGenerated, setIsWorkReportPDFGenerated] = useState(
    !!serviceOrder?.additionalInfo.workReportGenerated,
  );
  const [isCheckListPDFGenerated, setIsCheckListPDFGenerated] = useState(
    serviceOrder?.additionalInfo.checkListInfo?.pdfGenerationStatus ===
      PdfGenerationStatus.DONE,
  );
  const [laborMaterialCosts, setLaborMaterialCosts] = useState<
    InvoiceAdditionalInfo['laborMaterialCosts']
  >({
    LABOR:
      invoice?.additionalInfo?.laborMaterialCosts?.LABOR ||
      'Your labor cost is {LABOR_COST}',
    MATERIAL:
      invoice?.additionalInfo?.laborMaterialCosts?.MATERIAL ||
      'Your material cost is {MATERIAL_COST}',
  });

  const [laborMaterialCostText, setLaborMaterialCostText] = useState(
    DEFAULT_INVOICE_MATERIAL_LABOR_COST_TEXT,
  );

  const articleViewToItem = (
    article: ServiceOrderArticleView,
  ): InvoiceItemRecord<Amount> => {
    const record = {
      articleId: article.article.id,
      articleUnit: article.article.unit,
      description: article.description,
      name: article.name,
      quantity: 1,
      unitAmount: article.article.unitSellingAmount,
      type: article.article.type,
      costPackage: article.article.additionalInfo?.costPackage,
    };
    return getItemRecord(record, percentageVat);
  };
  const [invoiceItems, setInvoiceItems] = useState<InvoiceItemRecord<Amount>[]>(
    serviceOrderResource?.articles?.map((item) => articleViewToItem(item)) ??
      [],
  );

  const [dueDate, setDueDate] = useState<Date | null>(
    invoice?.dueDate ? new Date(invoice.dueDate) : null,
  );
  const [dueDateError, setDueDateError] = useState('');
  const [, setFinalAmountText] = useState('');

  const [openDialog, setOpenDialog] = useState<boolean>(false);
  const [activeField, setActiveField] = useState<string>('');

  const handleFocus = (e: any) => {
    setActiveField(e.target.name);
  };

  const {data: companyNextNumber} = useCompanyNextNumber(
    {
      type: ServiceCompanyNumberType.INVOICE,
    },
    user?.userAccount.serviceCompany.id,
  );

  useEffect(() => {
    if (formType === 'new') {
      formik.setFieldValue('externalId', companyNextNumber?.value);
    }
  }, [companyNextNumber]);

  const [totalAmountFrom, totalAmountTo] = useMemo(
    () => getStartEndPrice([]),
    [[]],
  );

  const {data: contractPaymentTerms = createEmptyResource(pageSize)} =
    useQueryContractPaymentTerms({
      page: {
        pageIndex: 0,
        pageSize,
      },
      query: '',
    });

  const invoiceTypeOptions = useRef([
    {
      value: InvoiceType.FULL,
      label: 'Full',
    },
    {
      value: InvoiceType.PARTIAL,
      label: 'Partial',
    },
    {
      value: InvoiceType.FINAL,
      label: 'Final',
    },
    {
      value: InvoiceType.CREDIT_NOTE,
      label: 'Credit Note',
    },
  ]).current;

  const initialValues: InvoiceFormData = {
    subject:
      invoice?.subject ||
      t('Invoice {{invoiceNumber}} for Job {{orderNumber}}', {
        invoiceNumber: invoice?.number ?? '',
        orderNumber: serviceOrder?.number ?? '',
      }),
    description: invoice?.description || '',
    dueDate: '',
    sentDate: dateToString(new Date()),
    type:
      typeof invoiceType === 'string' &&
      invoiceType &&
      invoiceType in InvoiceType
        ? InvoiceType[invoiceType as InvoiceType]
        : InvoiceType.FULL,
    items: [],
    paymentTerms: '',
    propertyOwnerId: '',
    serviceCompanyId: '',
    serviceOrderId: '',
    paymentInfo: payment,
    shouldSendOut: false,
    includeWorkReport: false,
    includeCheckList: false,
    beneficialName: invoice?.additionalInfo.beneficialDetails?.name || '',
    beneficialAddress: invoice?.additionalInfo.beneficialDetails?.address,
    costCenter: invoice?.additionalInfo?.costCenter || '',
    customerSpecificOrderNumber:
      invoice?.additionalInfo?.customerSpecificOrderNumber || '',
    moreInfo: invoice?.additionalInfo?.moreInfo ?? '',
    billingAddress: invoice?.additionalInfo?.billingAddress,
    beneficiaryAddress: invoice?.additionalInfo?.beneficiaryAddress,
    alternativeAddress: invoice?.additionalInfo?.alternativeAddress,
    laborMaterialCosts: invoice?.additionalInfo.laborMaterialCosts || {
      LABOR: '',
      MATERIAL: '',
    },
    laborMaterialCostText:
      invoice?.additionalInfo.laborMaterialCostText ||
      DEFAULT_INVOICE_MATERIAL_LABOR_COST_TEXT,
    externalId:
      formType === 'new' ? companyNextNumber?.value : invoice?.externalId ?? '',
  };

  const validationSchema = Yup.object().shape({
    subject: Yup.string().required('Subject is required'),
  });

  const formik = useFormik({
    initialValues,
    validationSchema,
    // eslint-disable-next-line @typescript-eslint/no-use-before-define
    onSubmit: async (values) => {
      const response = await onSave(values);
      const invoiceId = formType === 'new' ? response.value : invoice?.id;
      navigate(`/invoices/details/${invoiceId}`);
    },
  });

  const handleSelectCustomer = (row: PropertyOwnerView) => {
    setCustomer(row);
    formik.setValues({
      ...formik.values,
      propertyOwnerId: row.id,
      billingAddress: row.billingAddress,
      beneficiaryAddress: row.beneficiaryAddress,
      alternativeAddress: row.otherAddress,
    });
  };

  const handleSelectServiceOrder = (row: ServiceOrderView) => {
    setServiceOrder(row);
  };

  useEffect(() => {
    if (formType === 'new') {
      formik.setFieldValue(
        'subject',
        t(
          `${
            formik.values.type === InvoiceType.CREDIT_NOTE
              ? 'Credit note'
              : 'Invoice'
          } {{invoiceNumber}}for Job {{orderNumber}}`,
          {
            invoiceNumber: invoice?.number ?? '',
            orderNumber: serviceOrder?.number ?? '',
          },
        ),
      );
    }
  }, [formik.values.type]);

  useEffect(() => {
    if (user && user.userAccount) {
      formik.setFieldValue(
        'serviceCompanyId',
        user.userAccount.serviceCompany.id,
        true,
      );
    }
  }, [user]);

  useEffect(() => {
    if (dueDate) formik.setFieldValue('dueDate', dateToString(dueDate), true);
  }, [dueDate]);

  useEffect(() => {
    const workReportGenerated =
      !!serviceOrder?.additionalInfo.workReportGenerated;
    const checkListGenerated =
      serviceOrder?.additionalInfo.checkListInfo?.pdfGenerationStatus ===
      PdfGenerationStatus.DONE;
    setIsWorkReportPDFGenerated(workReportGenerated);
    setIsCheckListPDFGenerated(checkListGenerated);
    formik.setFieldValue(
      'includeWorkReport',
      invoice?.additionalInfo.includeWorkReport || false,
    );
    formik.setFieldValue(
      'includeCheckList',
      invoice?.additionalInfo.includeCheckList || false,
    );

    const dueDays = serviceOrder?.contract?.additionalInfo?.invoiceDueDays || 0;

    if (dueDays > 0) {
      const currentDate = new Date();
      const futureDate = addDays(currentDate, dueDays);

      setDueDate(futureDate);
      setResetDueDatePicker(true);
    }
  }, [serviceOrder]);

  useEffect(() => {
    if (invoice) {
      const invoiceCustomer = invoice.propertyOwner;
      setServiceOrder(invoice.serviceOrder);
      setCustomer(invoiceCustomer);
      formik.setValues({
        ...formik.values,
        propertyOwnerId: invoiceCustomer?.id ?? '',
        billingAddress:
          invoice.additionalInfo?.billingAddress ??
          invoiceCustomer?.billingAddress,
        beneficiaryAddress:
          invoice.additionalInfo?.beneficiaryAddress ??
          invoiceCustomer?.beneficiaryAddress,
        alternativeAddress:
          invoice.additionalInfo?.alternativeAddress ??
          invoiceCustomer?.otherAddress,
      });
      if (!ALL_MANUAL_INVOICE_TYPES.includes(invoice.type)) {
        const newItems = invoice.items.map(
          (i): InvoiceItemRecord<Amount> => ({
            articleId: i.article.id,
            description: i.description || i.article.description,
            name: i.name || i.article.name,
            articleUnit: i.article.unit,
            quantity: i.quantity,
            unitAmount: invoice.totalAmount,
          }),
        );
        setInvoiceItems(newItems);
      }

      setLaborMaterialCosts({
        LABOR:
          invoice.additionalInfo?.laborMaterialCosts?.LABOR ||
          'Your labor cost is {LABOR_COST}',
        MATERIAL:
          invoice.additionalInfo?.laborMaterialCosts?.MATERIAL ||
          'Your material cost is {MATERIAL_COST}',
      });

      setLaborMaterialCostText(
        invoice.additionalInfo.laborMaterialCostText ||
          DEFAULT_INVOICE_MATERIAL_LABOR_COST_TEXT,
      );
    }

    formik.setFieldValue(
      'type',
      invoiceType || invoice?.type || InvoiceType.FULL,
      true,
    );
    formik.setFieldValue('paymentTerms', invoice?.paymentTerms || '', true);
    formik.setFieldValue('dueDate', invoice?.dueDate || '', true);
    formik.setFieldValue(
      'serviceOrderId',
      invoice?.serviceOrder?.id || '',
      true,
    );
  }, [invoice]);

  useEffect(() => {
    if (serviceOrder) {
      const serviceOrderCustomer = serviceOrder.elevator.propertyOwner;
      setCustomer(serviceOrderCustomer);

      // if customer is changed, then update billing address
      if (serviceOrderCustomer.id !== customer?.id) {
        formik.setValues({
          ...formik.values,
          billingAddress: serviceOrderCustomer?.billingAddress,
          beneficiaryAddress: serviceOrderCustomer?.beneficiaryAddress,
          alternativeAddress: serviceOrderCustomer?.otherAddress,
        });
      }

      formik.setFieldValue(
        'propertyOwnerId',
        serviceOrder.elevator.propertyOwner.id,
        true,
      );
      formik.setFieldValue(
        'serviceCompanyId',
        user?.userAccount.serviceCompany.id,
        true,
      );
      formik.setFieldValue('serviceOrderId', serviceOrder.id, true);
      formik.setFieldValue(
        'subject',
        invoiceType === InvoiceType.CREDIT_NOTE
          ? t('Credit note for {{invoiceNumber}}', {
              invoiceNumber: invoice?.number ?? '',
            })
          : invoice?.subject ??
              t(
                `{{customerName}} - ${
                  formik.values.type === InvoiceType.CREDIT_NOTE
                    ? 'Credit note for'
                    : 'Invoice for'
                } {{invoiceNumber}}`,
                {
                  invoiceNumber: invoice?.externalId ?? '',
                  customerName: customer?.name ?? serviceOrderCustomer?.name,
                },
              ),
        true,
      );
    }
  }, [serviceOrder, formik.values.type]);

  useEffect(() => {
    formik.setFieldValue(
      'items',
      invoiceItems.map(
        (item): WithOptional<InvoiceItemRecord<Amount>, 'articleUnit'> => ({
          articleId: item.articleId,
          description: item.description,
          name: item.name,
          quantity: item.quantity,
          unitAmount: item.unitAmount,
        }),
      ),
      true,
    );
    const currencyCode = getCurrencySymbol[currentCurrency.code];
    const {materialCost, laborCost} = calculateCostPackage(invoiceItems);
    setFinalAmountText(
      materialCost && laborCost
        ? t(
            `Labor costs: {{laborCost}}{{currencyCode}}, Material costs: {{materialCost}}{{currencyCode}}`,
            {
              materialCost,
              laborCost,
              currencyCode,
            },
          )
        : materialCost
        ? t(`Material costs: {{materialCost}}{{currencyCode}}`, {
            materialCost,
            currencyCode,
          })
        : laborCost
        ? t(`Labor costs: {{laborCost}}{{currencyCode}}`, {
            laborCost,
            currencyCode,
          })
        : '',
    );
  }, [invoiceItems, t]);

  const isDueDateInPast = () => {
    const localDueDate = invoice?.dueDate as string;
    const dueDateObject = startOfDay(
      parseISO(new Date(localDueDate).toISOString()),
    );
    const todayObject = startOfDay(new Date());

    return isBefore(dueDateObject, todayObject);
  };

  const validateDueDate = () => {
    let errorMessage = '';

    if (isDueDateInPast()) {
      errorMessage = t(`The due date for the invoice has expired`);
    }

    return errorMessage;
  };

  const onInvoiceSaveAndSend = () => {
    const errorMessage = validateDueDate();

    if (errorMessage) {
      setDueDateError(errorMessage);
      enqueueSnackbar(errorMessage, {
        variant: 'error',
      });

      return;
    }

    setIsSendEmailDialogOpen(true);
  };

  const actions = useMemo(() => {
    const items = [
      {
        label: t('Save & Send'),
        icon: <Send />,
        onClick: () => {
          onInvoiceSaveAndSend();
        },
      },
    ];
    if (
      invoice &&
      ![
        InvoiceStatus.NOT_PAID,
        InvoiceStatus.EXPIRED,
        InvoiceStatus.PARTIALLY_PAID,
      ].includes(invoice.status)
    ) {
      items.push({
        label: t('Delete'),
        icon: <DeleteIcon />,
        onClick: () => {
          setIsDeleteDialogOpen(true);
        },
      });
    }
    return items;
  }, [downloadUrl, dueDate]);

  const isValid = () => {
    const valid =
      formik.values.subject &&
      formik.values.type.length &&
      formik.values.items.length;
    if (formik.values.type !== InvoiceType.CREDIT_NOTE) {
      return !!(valid && dueDate !== null);
    }
    return !!valid;
  };

  const handleCheckListMouseEnter = () => {
    if (!isCheckListPDFGenerated) {
      setShowCheckListTooltip(true);
    }
  };

  const handleCheckListMouseLeave = () => {
    if (showCheckListTooltip) {
      setShowCheckListTooltip(false);
    }
  };

  const handleWorkReportMouseEnter = () => {
    if (!isWorkReportPDFGenerated) {
      setShowWorlReportTooltip(true);
    }
  };

  const handleWorkReportMouseLeave = () => {
    if (showWorkReportTooltip) {
      setShowWorlReportTooltip(false);
    }
  };

  async function onSave(values: InvoiceFormData) {
    if (!values.description.length) values.description = '';
    if (!values?.moreInfo?.length) values.moreInfo = '';

    const dueDateToString: string =
      formik.values.type === InvoiceType.CREDIT_NOTE
        ? dateToString(addYears(new Date(), 1))
        : values.dueDate;

    if (formType === 'edit' && invoice) {
      return updateInvoiceAsync({
        data: formatInvoiceRecord({
          ...values,
          includeWorkReport: values.includeWorkReport,
          includeCheckList: values.includeCheckList,
          dueDate: dueDateToString,
          laborMaterialCosts: {
            LABOR: laborMaterialCosts.LABOR,
            MATERIAL: laborMaterialCosts.MATERIAL,
          },
          laborMaterialCostText,
        }),
        invoiceId: invoice.id,
      });
    }

    return createNewInvoice({
      data: formatInvoiceRecord({
        ...values,
        serviceCompanyId:
          values.serviceCompanyId ||
          (user?.userAccount.serviceCompany.id ?? ''),
        includeWorkReport: values.includeWorkReport,
        includeCheckList: values.includeCheckList,
        dueDate: dueDateToString,
        laborMaterialCosts: {
          LABOR: laborMaterialCosts.LABOR,
          MATERIAL: laborMaterialCosts.MATERIAL,
        },
        laborMaterialCostText,
      }),
    });
  }

  const handleContractPaymentTermsModal = (paymentTermId: string) => {
    const paymentTermObj = contractPaymentTerms?.data.find(
      ({id}) => id === paymentTermId,
    );
    formik.setFieldValue('paymentTerms', paymentTermObj?.term);
    setOpenContractPaymentTermsDialog(false);
  };

  const {data: InvoiceList = []} = useFetchServiceOrderInvoices(
    serviceOrder?.id,
  );

  const removeAddress = (
    addressType: 'billingAddress' | 'beneficiaryAddress' | 'alternativeAddress',
  ) => {
    formik.setFieldValue(addressType, {fullName: null});
  };

  const setNewlyCreatedCustomer = (customerId: string) => {
    setSearchParams(formatSearchParams({customerId}, searchParams));
    setIsAddNewCustomerDialogOpen(false);
  };

  const toolTipText = (
    <div>
      {t('Full')} - {t('Standard invoice for the full amount.')} <br />
      {t('Partial')} -{' '}
      {t('Partial payment when less than the full amount is due.')}
      <br />
      {t('Final')} -{' '}
      {t('Final invoice after partial invoices have been created before.')}
      <br />
      {t('Credit note - Is issued to indicate a return of funds.')}
      <br />
    </div>
  );

  const {data: allInvoiceResource = createEmptyResource<InvoiceView>(10)} =
    useInvoices(
      {
        pageIndex: 0,
        pageSize: 25,
        query: String(formik.values.externalId!),
        status: [],
        totalAmountFrom,
        totalAmountTo,
      },
      {keepPreviousData: true},
    );

  const externalIdInputProps = {
    id: 'externalId',
    name: 'externalId',
    placeholder: !formik.values.externalId && t('Unassigned'),
    label: 'Invoice Number',
    value: formik.values.externalId,
    onChange: formik.handleChange,
    onBlur: formik.handleBlur,
    error: !!(formik.touched.externalId && formik.errors.externalId),
    helperText: formik.touched.externalId && formik.errors.externalId,
  };

  return (
    <Box>
      {invoice && (
        <Box
          display="flex"
          alignItems="flex-end"
          justifyContent="space-between">
          <StatusChip
            label={getInvoiceStatusStyles(invoice?.status ?? '').label}
            color={getInvoiceStatusStyles(invoice?.status ?? '').color}
            size="small"
            variant="filled"
          />
          <Notes invoice={invoice!} />
        </Box>
      )}
      <Box
        width="min(calc(1240px + 1.25em), 100%)"
        mx="auto"
        mb="8em"
        mt="1.5em">
        <Box
          p="1em"
          bgcolor="grey.300"
          border="2px solid"
          borderColor="text.disabled"
          borderRadius=".5em">
          <Box bgcolor="white" p="1em">
            <Box display="flex" mt="1em" gap="2em">
              <Box
                flexGrow={1}
                display="flex"
                flexDirection="column"
                gap="1.5rem">
                <Box>
                  <FormLabel text={t('From')} />
                  <Box
                    display="flex"
                    bgcolor="grey.200"
                    alignItems="start"
                    justifyContent="space-between"
                    px="0.75rem"
                    py=".5rem"
                    border="1px solid"
                    borderColor="inputBackground.main"
                    borderRadius="4px">
                    <Box>
                      <Typography variant="body2">
                        {user?.userAccount.serviceCompany.name || ''}
                      </Typography>
                      <Box color="text.secondary">
                        {user &&
                        'businessAddress' in user.userAccount.serviceCompany &&
                        user.userAccount.serviceCompany.postalAddress
                          ?.fullName ? (
                          <Typography variant="caption">
                            {
                              user.userAccount.serviceCompany.postalAddress
                                ?.fullName
                            }
                          </Typography>
                        ) : (
                          ''
                        )}
                      </Box>
                    </Box>
                  </Box>
                </Box>
                <SelectCombined
                  selected={customer !== undefined}
                  label={
                    <Box
                      display="flex"
                      justifyContent="space-between"
                      alignItems="center">
                      <FormLabel text={t('Customer')} required />
                      <Button
                        label="Add New Customer"
                        style={{color: theme.palette.primary.light}}
                        buttonProps={{
                          size: 'small',
                          startIcon: <AddIcon />,
                          onClick: () => setIsAddNewCustomerDialogOpen(true),
                        }}
                      />
                    </Box>
                  }
                  buttonText="Select Customer"
                  cardHeader={
                    customer && (
                      <Typography variant="body2">{customer.name}</Typography>
                    )
                  }
                  cardOnClose={() => {
                    setCustomer(undefined);
                    setServiceOrder(undefined);
                  }}
                  modalHeader="Select Customer"
                  modalBody={
                    <CustomersDataGrid setRowItem={handleSelectCustomer} />
                  }
                  labelRequired
                />

                {customer && (
                  <>
                    <SelectAndEditCombined
                      selected={!!formik.values.billingAddress?.fullName}
                      label="Billing Address"
                      buttonText="Add Billing Address"
                      cardHeader={
                        formik.values.billingAddress ? (
                          <Typography variant="body2">
                            {formik.values.billingAddress.fullName}
                          </Typography>
                        ) : null
                      }
                      cardOnClose={() => removeAddress('billingAddress')}
                      editButtonText="Edit Billing Address"
                      modalHeader="Edit Billing Address"
                      addressType="billingAddress"
                      formik={formik}
                    />

                    <SelectAndEditCombined
                      selected={!!formik.values.beneficiaryAddress?.fullName}
                      label="Beneficiary Address"
                      buttonText="Add Beneficiary Address"
                      cardHeader={
                        formik.values.beneficiaryAddress ? (
                          <Typography variant="body2">
                            {formik.values.beneficiaryAddress.fullName}
                          </Typography>
                        ) : null
                      }
                      cardOnClose={() => removeAddress('beneficiaryAddress')}
                      editButtonText="Edit Beneficiary Address"
                      modalHeader="Edit Beneficiary Address"
                      addressType="beneficiaryAddress"
                      formik={formik}
                    />

                    <SelectAndEditCombined
                      selected={!!formik.values.alternativeAddress?.fullName}
                      label={
                        <Box>
                          <FormLabel
                            text={t('Alternative Invoice Destination')}
                          />
                          <Tooltip
                            title={t(alternativeInvoiceDestinationTooltip)}
                            placement="top"
                            componentsProps={{
                              tooltip: {
                                sx: {
                                  bgcolor: 'common.gray',
                                  maxWidth: 500,
                                  padding: '1em',
                                  fontSize: '0.85rem',
                                },
                              },
                            }}>
                            <IconButton sx={{fontSize: '1.375rem'}}>
                              <InfoOutlinedIcon />
                            </IconButton>
                          </Tooltip>
                        </Box>
                      }
                      buttonText="Add Alternative Address"
                      cardHeader={
                        formik.values.alternativeAddress ? (
                          <Typography variant="body2">
                            {formik.values.alternativeAddress.fullName}
                          </Typography>
                        ) : null
                      }
                      cardOnClose={() => removeAddress('alternativeAddress')}
                      editButtonText="Edit Alternative Address"
                      modalHeader="Edit Alternative Address"
                      addressType="alternativeAddress"
                      formik={formik}
                    />
                  </>
                )}

                <SelectCombined
                  selected={serviceOrder !== undefined}
                  label="Job Number"
                  buttonText="Select Job"
                  cardHeader={
                    serviceOrder && (
                      <Typography variant="body2">
                        {serviceOrder.number}
                      </Typography>
                    )
                  }
                  cardBody={
                    serviceOrder && (
                      <>
                        <ServiceOrderTypeText
                          serviceOrderType={serviceOrder.type}
                          capitalizeText
                          variant="caption"
                        />
                        <Typography variant="caption" component="p">
                          {serviceOrder.schedules.length
                            ? `${serviceOrder.schedules[0].technician.userAccount.firstName} ${serviceOrder.schedules[0].technician.userAccount.lastName}`
                            : '-'}
                        </Typography>
                      </>
                    )
                  }
                  cardOnClose={() => setServiceOrder(undefined)}
                  modalHeader="Select Job"
                  modalBody={
                    <ServiceOrdersDataGrid
                      setRowItem={handleSelectServiceOrder}
                      selectedCustomer={customer}
                      searchCustomer={customer?.name}
                      propertyOwnerId={customer?.id ?? ''}
                    />
                  }
                />
              </Box>
              <Box
                width="35%"
                display="flex"
                flexDirection="column"
                gap="1.5rem"
                px="2rem">
                {[
                  {
                    label: 'Invoice Type',
                    value: formik.values.type
                      ? t(`${convertToText(formik.values.type)} invoice`)
                      : '-',
                  },
                  {
                    label: 'Unit Number',
                    value: serviceOrder?.elevator.externalId || '-',
                  },
                  {
                    label: 'Created By',
                    value: invoice?.meta.creator
                      ? `${invoice.meta.creator?.firstName} ${invoice.meta.creator?.lastName}`
                      : `${user?.userAccount.firstName} ${user?.userAccount.lastName}`,
                  },
                  {
                    label: 'Invoice Date',
                    value: invoice?.sentDate
                      ? formatDate(invoice.sentDate)
                      : '-',
                  },
                ].map((i) => (
                  <Box key={i.label}>
                    <FormLabel text={i.label} />
                    <Typography>{i.value}</Typography>
                  </Box>
                ))}

                <Box>
                  <AutoDropdown
                    formik={formik}
                    activeField={activeField}
                    fieldProps={externalIdInputProps}
                    setOpenDialog={setOpenDialog}
                    serviceTypeResource={allInvoiceResource.data}
                    handleFocus={handleFocus}
                    numberType={ServiceCompanyNumberType.INVOICE}
                  />
                </Box>

                <FormInput
                  props={{
                    id: 'customerSpecificOrderNumber',
                    name: 'customerSpecificOrderNumber',
                    placeholder: 'e.g 000 000 000',
                    label: 'Purchase order number',
                    value: formik.values.customerSpecificOrderNumber,
                    onChange: formik.handleChange,
                    onBlur: formik.handleBlur,
                    error: !!(
                      formik.touched.customerSpecificOrderNumber &&
                      formik.errors.customerSpecificOrderNumber
                    ),
                    helperText:
                      formik.touched.customerSpecificOrderNumber &&
                      formik.errors.customerSpecificOrderNumber,
                    sx: {mt: '1em'},
                  }}
                  handleFocus={handleFocus}
                />
                <FormInput
                  props={{
                    id: 'costCenter',
                    name: 'costCenter',
                    placeholder: 'e.g 000 000 000',
                    label: 'Cost Center',
                    value: formik.values.costCenter,
                    onChange: formik.handleChange,
                    onBlur: formik.handleBlur,
                    error: !!(
                      formik.touched.costCenter && formik.errors.costCenter
                    ),
                    helperText:
                      formik.touched.costCenter && formik.errors.costCenter,
                    sx: {mt: '1em'},
                  }}
                  handleFocus={handleFocus}
                />
              </Box>
            </Box>

            <Box mt="2em">
              <Typography variant="body1" color={theme.palette.text.secondary}>
                {t('Invoice Type')}{' '}
                <Tooltip
                  title={toolTipText}
                  placement="top"
                  componentsProps={{
                    tooltip: {
                      sx: {
                        bgcolor: 'common.gray',
                        maxWidth: 500,
                        padding: '1em',
                        fontSize: '0.85rem',
                      },
                    },
                  }}>
                  <IconButton>
                    <InfoOutlinedIcon />
                  </IconButton>
                </Tooltip>
              </Typography>

              <RadioGroup
                name="radio-buttons-group"
                sx={{flexDirection: 'row'}}>
                {(invoice?.type === InvoiceType.FULL ||
                  invoice?.type === InvoiceType.CREDIT_NOTE) &&
                !invoice.partialInvoices?.length
                  ? invoiceTypeOptions
                      .filter((option) => option.value !== InvoiceType.FINAL)
                      .map((option) => (
                        <FormRadio
                          key={option.value}
                          name="type"
                          value={option.value}
                          checked={formik.values.type === option.value}
                          handleChange={formik.handleChange}
                          label={t(option.label)}
                          radioProps={{
                            sx: {color: theme.palette.text.secondary},
                          }}
                          disabled={formType === 'edit'}
                        />
                      ))
                  : invoice?.type === InvoiceType.FINAL &&
                    invoice.partialInvoices?.length
                  ? invoiceTypeOptions
                      .filter((option) => option.value !== InvoiceType.FULL)
                      .map((option) => (
                        <FormRadio
                          key={option.value}
                          name="type"
                          value={option.value}
                          checked={formik.values.type === option.value}
                          handleChange={formik.handleChange}
                          label={t(option.label)}
                          radioProps={{
                            sx: {color: theme.palette.text.secondary},
                          }}
                          disabled={formType === 'edit'}
                        />
                      ))
                  : invoiceTypeOptions.map((option) => (
                      <FormRadio
                        key={option.value}
                        name="type"
                        value={option.value}
                        checked={formik.values.type === option.value}
                        handleChange={formik.handleChange}
                        label={t(option.label)}
                        radioProps={{
                          sx: {color: theme.palette.text.secondary},
                        }}
                        disabled={formType === 'edit'}
                      />
                    ))}
              </RadioGroup>
            </Box>

            {formik.values.type !== InvoiceType.CREDIT_NOTE && (
              <>
                <Box sx={{display: 'flex'}}>
                  <InvoiceCheckbox
                    onMouseEnter={handleWorkReportMouseEnter}
                    onMouseLeave={handleWorkReportMouseLeave}
                    checkboxName="includeWorkReport"
                    disabled={!isWorkReportPDFGenerated}
                    handleChange={formik.handleChange}
                    showTooltip={showWorkReportTooltip}
                    tooltipTitle="No work report for the selected service job"
                    title="Work Report"
                    checkboxLabel="Add work report to invoice"
                    checked={
                      isWorkReportPDFGenerated &&
                      formik.values.includeWorkReport
                    }
                  />

                  <InvoiceCheckbox
                    onMouseEnter={handleCheckListMouseEnter}
                    onMouseLeave={handleCheckListMouseLeave}
                    checkboxName="includeCheckList"
                    disabled={!isCheckListPDFGenerated}
                    handleChange={formik.handleChange}
                    showTooltip={showCheckListTooltip}
                    tooltipTitle="No checklist for selected service job"
                    title="Checklist"
                    checkboxLabel="Add checklist to invoice"
                    checked={
                      isCheckListPDFGenerated && formik.values.includeCheckList
                    }
                  />
                </Box>
                <Box mt="2em" width="32ch">
                  <DatePicker
                    defaultDate={dueDate}
                    reset={resetDueDatePicker}
                    getReset={(_reset) => {
                      if (_reset) {
                        setResetDueDatePicker(false);
                      }
                    }}
                    errorMessage={dueDateError}
                    minDate={new Date()}
                    getSelectedDate={(newValue) => {
                      setDueDateError('');
                      if (newValue) setDueDate(newValue);
                    }}
                    textFieldProps={{
                      label: 'Due Date',
                      InputLabelProps: {shrink: true},
                    }}
                    required
                  />
                </Box>
              </>
            )}

            {[
              {
                id: 'subject',
                value: formik.values.subject,
                error: !!(formik.touched.subject && formik.errors.subject),
                helperText: formik.touched.subject && formik.errors.subject,
                minRows: 1,
                maxRows: 3,
                required: true,
              },
              {
                id: 'description',
                value: formik.values.description,
                error: false,
                helperText: undefined,
                minRows: 2,
                maxRows: 6,
                required: false,
              },
            ].map((i) => (
              <Box mt="1em" key={i.id}>
                <FormLabel text={t(i.id)} required={i.required} />
                <FormInput
                  props={{
                    id: i.id,
                    value: i.value,
                    onChange: formik.handleChange,
                    onBlur: formik.handleBlur,
                    error: i.error,
                    helperText: i.helperText,
                    minRows: i.minRows,
                    maxRows: i.maxRows,
                    multiline: true,
                    fullWidth: true,
                  }}
                />
              </Box>
            ))}

            <ArticleItemsTable
              invoice={invoice}
              items={invoiceItems}
              setItems={setInvoiceItems}
              isPartial={!(formik.values.type !== InvoiceType.PARTIAL)}
              isCreditNote={formik.values.type === InvoiceType.CREDIT_NOTE}
              unitSellingAmount={invoice?.totalAmount}
              propertyOwnerId={customer?.id ?? ''}
              formType={formType}
              orderPartialInvoices={InvoiceList.filter(
                (item) => item.type === InvoiceType.PARTIAL,
              )}
            />

            <Box sx={{display: 'flex', flexDirection: 'row', columnGap: 2}}>
              <FormInput
                containerStyles={{mt: '1rem'}}
                props={{
                  size: 'small',
                  label: 'Final Amount',
                  name: 'laborMaterialCostText',
                  minRows: 2,
                  maxRows: 5,
                  multiline: true,
                  value: laborMaterialCostText,
                  disabled: false,
                  onChange: (e) => {
                    setLaborMaterialCostText(e.target.value);
                  },
                }}
              />
            </Box>

            <InfoCard
              containerStyles={{
                my: '1rem',
                boxShadow: 'none',
                border: '1px solid #E4E9F2',
              }}
              headerActionIcon={<EditIcon />}
              handleAction={() => setOpenContractPaymentTermSelectDialog(true)}
              showHeaderBackground
              header={
                <Typography variant="subtitle1">
                  {t('Payment Terms')}
                </Typography>
              }>
              {formik.values.paymentTerms ? (
                <Typography variant="body2">
                  {formik.values.paymentTerms}
                </Typography>
              ) : (
                <EmptySection
                  label="No payment terms applied"
                  illustration="clipboard"
                  size="tiny"
                  containerStyle={{
                    height: '100%',
                    gap: '0.5rem',
                  }}
                />
              )}
            </InfoCard>

            <Box my="1.5em">
              <FormLabel text="Additional Information" />
              <FormInput
                props={{
                  id: 'moreInfo',
                  name: 'moreInfo',
                  value: formik.values.moreInfo,
                  onChange: formik.handleChange,
                  minRows: 2,
                  maxRows: 4,
                  multiline: true,
                  fullWidth: true,
                }}
              />
            </Box>
          </Box>
        </Box>
      </Box>

      <BottomDrawer
        isOpen={isDrawerOpen}
        isSaving={isUpdating || isCreating}
        primaryButtonLabel={t('Save')}
        primaryButtonAction={formik.handleSubmit}
        listItems={actions.map((item) => ({
          ...item,
          showBorder: actions[actions.length - 1] !== item,
        }))}
        isValid={isValid()}
      />
      <NewCustomer
        isDialogOpen={isAddNewCustomerDialogOpen}
        onClose={() => setIsAddNewCustomerDialogOpen(false)}
        onSave={setNewlyCreatedCustomer}
      />
      <SendEmailDialog
        open={isSendEmailDialogOpen}
        onClose={() => setIsSendEmailDialogOpen(false)}
        confirmBtnDisabled={isPublishing || isUpdating || isCreating}
        callback={async (emailRecord) => {
          const response = await onSave(formik.values);
          setIsSendEmailDialogOpen(false);
          const invoiceId = formType === 'new' ? response.value : invoice?.id;
          await publishInvoice({
            id: invoiceId!,
            body: {
              email: emailRecord.email,
              subject: emailRecord.subject,
              content: emailRecord.content,
            },
          });
          navigate(`/invoices/details/${invoiceId}`);
        }}
        email={customer?.additionalInfo.billingEmail || customer?.contact.email}
        subject={t(`${customer?.name} - ${t('Invoice')} {{invoiceNumber}}`, {
          invoiceNumber: invoice?.number ?? '',
        })}
        content={formik.values.description}
      />
      <Confirm
        open={isDeleteDialogOpen}
        onConfirm={() => {
          if (invoice)
            deleteInvoice(
              {invoiceId: invoice.id, shouldNavigate: true},
              {
                onSuccess: () => {
                  enqueueSnackbar(
                    <CustomSnackbar
                      message="Invoice deleted"
                      snackIcon="delete"
                    />,
                    {
                      variant: 'info',
                      anchorOrigin: {horizontal: 'right', vertical: 'bottom'},
                    },
                  );
                },
              },
            );
          setIsDeleteDialogOpen(false);
        }}
        onClose={() => setIsDeleteDialogOpen(false)}
        title="Delete Invoice"
        content="Do you want to delete this Invoice?"
        helperText="This action is irreversible."
      />
      <ContractPaymentTermSelectDialog
        title={t('Payment Terms')}
        alertText={t('Choose a payment term to be used on your invoice')}
        open={openContractPaymentTermSelectDialog}
        onSave={handleContractPaymentTermsModal}
        onCancel={() => setOpenContractPaymentTermSelectDialog(false)}
        onClickPaymentTerms={() => setOpenContractPaymentTermsDialog(true)}
      />

      <ContractPaymentTermsDialog
        title={t('Manage Payment Terms')}
        open={openContractPaymentTermsDialog}
        onCancel={() => setOpenContractPaymentTermsDialog(false)}
      />

      <AutoGeneratedIdDialog
        openDialog={openDialog}
        setOpenDialog={setOpenDialog}
      />
    </Box>
  );
};

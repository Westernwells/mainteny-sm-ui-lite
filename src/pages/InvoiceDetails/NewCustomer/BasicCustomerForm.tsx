import {useEffect, useState} from 'react';
import {FormikProps} from 'formik';
import {useTranslation} from 'react-i18next';
import Box from '@mui/material/Box';
import Typography from '@mui/material/Typography';
import Grid from '@mui/material/Grid';
import InputAdornment from '@mui/material/InputAdornment';
import {AutoAwesome, Email, Phone} from '@mui/icons-material';
import {MultipleSelectCheckmarks} from 'components/MultipleSelectCheckmarks';
import {FormInput} from 'components/form/FormInput';
import {DatePicker} from 'components/DatePicker';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import {
  useCompanyAutoNumberConfig,
  useCompanyNextNumber,
} from 'hooks/reactQuery/useCompanies';
import {ServiceCompanyNumberType} from 'models/service-company';
import {PropertyOwnerView} from 'models/propertyManager';
import {Button} from '@mui/material';
import {theme} from 'theme';
import AutoGeneratedIdDialog from 'components/AutoGeneratedIdDialog';
import {CustomerBasicInfoFormModel} from '../../NewCustomer/model';

interface Props {
  formik: FormikProps<CustomerBasicInfoFormModel>;
  customerResource: PropertyOwnerView[];
}

export const BasicCustomerForm = ({formik, customerResource}: Props) => {
  const defaultProps = {
    InputLabelProps: {shrink: true},
    onChange: formik.handleChange,
    onBlur: formik.handleBlur,
  };

  const {t} = useTranslation();
  const {user} = useUserSession();

  const [openDialog, setOpenDialog] = useState<boolean>(false);
  const [activeField, setActiveField] = useState<string>('');

  const {data: companyAutoNumberConfig} = useCompanyAutoNumberConfig(
    user?.userAccount.serviceCompany.id,
  );

  const {data: companyNextNumber, refetch: refetchCompanyNumber} =
    useCompanyNextNumber(
      {
        type: ServiceCompanyNumberType.PROPERTY_OWNER,
      },
      user?.userAccount.serviceCompany.id,
    );

  useEffect(() => {
    formik.setFieldValue('externalId', companyNextNumber?.value);
  }, [companyNextNumber]);

  const handleFocus = (e: any) => {
    setActiveField(e.target.name);
  };

  return (
    <Box pt="0.5rem" component="form">
      <Typography variant="h6" color="text.secondary" pb={2}>
        {t('Basic Information')}
      </Typography>
      <Grid container spacing={3}>
        <Grid item md={6}>
          <FormInput
            fieldProps={{
              size: 'small',
              placeholder: 'e.g. Mainteny GmbH',
              label: 'Customer Name',
              name: 'name',
              value: formik.values.name,
              helperText: formik.touched.name && formik.errors.name,
              error: !!formik.errors.name && formik.touched.name,
              required: true,
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
        <Grid item md={6}>
          <FormInput
            fieldProps={{
              size: 'small',
              placeholder: 'e.g. johndoe@example.com',
              label: 'Email',
              name: 'email',
              value: formik.values.email,
              helperText: formik.touched.email && formik.errors.email,
              error: !!formik.errors.email && formik.touched.email,
              InputProps: {
                endAdornment: (
                  <InputAdornment position="end">
                    <Email />
                  </InputAdornment>
                ),
              },
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
        <Grid item md={6}>
          <FormInput
            fieldProps={{
              size: 'small',
              placeholder: 'e.g. johndoe@example.com',
              label: 'Billing Email Address',
              name: 'billingEmail',
              value: formik.values.billingEmail,
              helperText:
                formik.touched.billingEmail && formik.errors.billingEmail,
              error:
                !!formik.errors.billingEmail && formik.touched.billingEmail,
              InputProps: {
                endAdornment: (
                  <InputAdornment position="end">
                    <Email />
                  </InputAdornment>
                ),
              },
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
        <Grid item md={6}>
          <FormInput
            fieldProps={{
              size: 'small',
              placeholder: 'e.g. +34 12345678',
              label: 'Phone',
              name: 'phone',
              value: formik.values.phone,
              helperText: formik.errors.phone,
              error: !!formik.errors.phone,
              InputProps: {
                startAdornment: (
                  <InputAdornment position="start"> + </InputAdornment>
                ),
                endAdornment: (
                  <InputAdornment position="end">
                    <Phone />
                  </InputAdornment>
                ),
              },
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
        <Grid item md={6}>
          <FormInput
            fieldProps={{
              size: 'small',
              placeholder: 'e.g. +34 12345678',
              label: '2nd Phone',
              name: 'secondaryPhoneNumber',
              value: formik.values.secondaryPhoneNumber,
              helperText: formik.errors.secondaryPhoneNumber,
              error: !!formik.errors.secondaryPhoneNumber,
              InputProps: {
                startAdornment: (
                  <InputAdornment position="start"> + </InputAdornment>
                ),
                endAdornment: (
                  <InputAdornment position="end">
                    <Phone />
                  </InputAdornment>
                ),
              },
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
        <Grid item md={6}>
          <FormInput
            fieldProps={{
              size: 'small',
              placeholder: 'e.g. mainteny.com',
              label: 'Website/URL',
              name: 'url',
              value: formik.values.url,
              helperText: formik.errors.url,
              error: !!formik.errors.url,
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
        <Grid item md={6}>
          <FormInput
            fieldProps={{
              size: 'small',
              placeholder: 'e.g. 1234',
              label: 'Customer Number',
              name: 'externalId',
              value: formik.values.externalId || '',
              helperText: formik.touched.externalId && formik.errors.externalId,
              error: !!formik.errors.externalId && formik.touched.externalId,
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
          {(activeField === 'externalId' || formik.touched.externalId) &&
            formik.values.externalId &&
            customerResource?.filter(
              (item) => item.externalId === formik.values.externalId,
            ).length > 0 && (
              <Typography
                color="error"
                fontSize="0.75rem"
                letterSpacing="0.03em"
                padding="0.45em 0.65em">
                {t('This ID is already taken. Please enter a different one.')}
              </Typography>
            )}
          {activeField === 'externalId' &&
          !formik.values.externalId &&
          companyAutoNumberConfig?.configRecords.find(
            (item) => item.type === ServiceCompanyNumberType.PROPERTY_OWNER,
          )?.enabled ? (
            <Box
              sx={{
                borderRadius: '4px',
                boxShadow: '0px 9px 46px 8px #0000001F',
                marginTop: '0.2em',
              }}>
              <Button
                sx={{
                  display: 'flex',
                  flexDirection: 'column',
                  justifyContent: 'flex-start',
                  textAlign: 'left',
                  alignItems: 'flex-start',
                  width: '100%',
                  padding: '1em 2em',
                }}
                onClick={() => {
                  refetchCompanyNumber();
                  formik.setFieldValue('externalId', companyNextNumber?.value);
                }}>
                <Box
                  sx={{
                    display: 'flex',
                    flexDirection: 'row',
                    alignItems: 'center',
                    paddingBottom: '0.6em',
                  }}>
                  <AutoAwesome />
                  <Typography variant="subtitle2" sx={{paddingLeft: '0.5em'}}>
                    {t('Generate ID')}
                  </Typography>
                </Box>

                <Typography
                  variant="body2"
                  color={theme.palette.text.secondary}>
                  {t('Customizable in Settings')}
                </Typography>
              </Button>
            </Box>
          ) : (
            activeField === 'externalId' &&
            !formik.values.externalId &&
            !companyAutoNumberConfig?.configRecords.find(
              (item) => item.type === ServiceCompanyNumberType.PROPERTY_OWNER,
            )?.enabled && (
              <Box
                sx={{
                  borderRadius: '4px',
                  boxShadow: '0px 9px 46px 8px #0000001F',
                  marginTop: '0.2em',
                }}>
                <Button
                  sx={{
                    display: 'flex',
                    flexDirection: 'column',
                    justifyContent: 'flex-start',
                    textAlign: 'left',
                    alignItems: 'flex-start',
                    width: '100%',
                    padding: '1em 2em',
                  }}
                  onClick={() => setOpenDialog(true)}>
                  <Box
                    sx={{
                      display: 'flex',
                      flexDirection: 'row',
                      alignItems: 'center',
                      paddingBottom: '0.6em',
                    }}>
                    <AutoAwesome />
                    <Typography variant="subtitle2" sx={{paddingLeft: '0.5em'}}>
                      {t('Enable Automatic ID Generation')}
                    </Typography>
                  </Box>

                  <Typography
                    variant="body2"
                    color={theme.palette.text.secondary}>
                    {t('Allows for easier number input')}
                  </Typography>
                </Button>
              </Box>
            )
          )}
        </Grid>
        <Grid item md={6}>
          <DatePicker
            getSelectedDate={(newValue) => {
              if (newValue) formik.setFieldValue('registrationDate', newValue);
            }}
            textFieldProps={{
              label: 'Customer Since',
              placeholder: 'Select date',
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={6}>
          <FormInput
            fieldProps={{
              size: 'small',
              placeholder: 'e.g. 000 000 000',
              label: 'Cost Center',
              name: 'costCenter',
              value: formik.values.costCenter,
              helperText: formik.errors.costCenter,
              error: !!formik.errors.costCenter,
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
        <Grid item md={6}>
          <Box display="flex" gap="1em">
            <MultipleSelectCheckmarks
              label="Priority"
              options={['A', 'B', 'C', 'NONE']}
              getSelectedValue={(item: string[]) =>
                formik.setFieldValue('priority', item[0])
              }
              initialSelectedItems={
                formik.values.priority ? [formik.values.priority] : ['NONE']
              }
              disableClearBtn
              multiple={false}
              containerStyles={{width: '100%'}}
              formControlStyles={{width: '100%'}}
            />
          </Box>
        </Grid>
        <Grid item md={6}>
          <FormInput
            fieldProps={{
              size: 'small',
              label: 'VAT ID',
              name: 'vatId',
              value: formik.values.vatId,
              helperText: formik.touched.vatId && formik.errors.vatId,
              error: !!formik.errors.vatId && formik.touched.vatId,
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
        <Grid item md={6}>
          <FormInput
            fieldProps={{
              size: 'small',
              label: 'Offsetting Account',
              name: 'offsettingAccount',
              value: formik.values.offsettingAccount,
              helperText:
                formik.touched.offsettingAccount &&
                formik.errors.offsettingAccount,
              error:
                !!formik.errors.offsettingAccount &&
                formik.touched.offsettingAccount,
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
      </Grid>
      <AutoGeneratedIdDialog
        openDialog={openDialog}
        setOpenDialog={setOpenDialog}
      />
    </Box>
  );
};

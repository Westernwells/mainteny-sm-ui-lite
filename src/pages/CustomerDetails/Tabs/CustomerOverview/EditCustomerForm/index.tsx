import {
  Dispatch,
  SetStateAction,
  useCallback,
  useEffect,
  useState,
} from 'react';
import {format} from 'date-fns';
import {useTranslation} from 'react-i18next';
import {useFormikContext} from 'formik';
import Grid from '@mui/material/Grid';
import Box from '@mui/material/Box';
import InputAdornment from '@mui/material/InputAdornment';
import IconButton from '@mui/material/IconButton';
import Delete from '@mui/icons-material/Delete';
import {countriesOptions, getStatesByCountry} from 'utils/countries';
import {FormInput} from 'components/form/FormInput';
import {Dialog} from 'components/Dialog';
import {DatePicker} from 'components/DatePicker';
import {FormSelect} from 'components/form/FormSelect';
import {Button} from 'components/Button';
import {ServiceCompanyNumberType} from 'models/service-company';
import {Typography} from '@mui/material';
import AutoGeneratedIdDialog from 'components/AutoGeneratedIdDialog';
import {ComboBox} from 'components/ComboBox';
import {
  useCompanyAutoNumberConfig,
  useCompanyNextNumber,
} from 'hooks/reactQuery/useCompanies';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import {CustomerEditForm} from './model';
import {SelectPriority} from './SelectPriority';

interface Props {
  openDialog: boolean;
  onClose: () => void;
  setCurrentCustomerId: Dispatch<SetStateAction<string>>;
}

export const EditCustomerForm = ({
  openDialog,
  onClose,
  setCurrentCustomerId,
}: Props) => {
  const {t} = useTranslation();
  const {user} = useUserSession();

  const {
    values: formikValues,
    handleChange,
    handleBlur,
    handleSubmit,
    touched,
    errors,
    dirty,
    resetForm,
    setFieldValue,
    setValues,
  } = useFormikContext<CustomerEditForm>();

  const [openNewDialog, setOpenNewDialog] = useState<boolean>(false);

  const {data: companyAutoNumberConfig} = useCompanyAutoNumberConfig(
    user?.userAccount.serviceCompany.id,
  );

  const {data: companyNextNumber} = useCompanyNextNumber(
    {
      type: ServiceCompanyNumberType.PROPERTY_OWNER,
    },
    user?.userAccount.serviceCompany.id,
  );

  const generateNextNumber = () => {
    setFieldValue('externalId', companyNextNumber?.value);
  };

  useEffect(() => {
    setCurrentCustomerId(formikValues.externalId);
  }, [formikValues.externalId]);

  const [showBeneficiaryAddress, setShowBeneficiaryAddress] = useState(
    !!formikValues.beneficiaryAddress || false,
  );
  const [showSendInvoiceViaAddress, setShowSendInvoiceViaAddress] = useState(
    !!formikValues.otherAddress || false,
  );

  const statesByCountry = useCallback(
    (country?: string) => getStatesByCountry(country ?? ''),
    [
      formikValues.billingAddress?.component?.country,
      formikValues.beneficiaryAddress?.component?.country,
      formikValues.otherAddress?.component?.country,
    ],
  );

  const removeBeneficiaryAddress = () => {
    setFieldValue('beneficiaryAddress.fullName', null);
    setShowBeneficiaryAddress(false);
  };

  const removeSendInvoiceViaAddress = () => {
    setFieldValue('otherAddress.fullName', null);
    setShowSendInvoiceViaAddress(false);
  };

  const defaultProps = {
    onChange: handleChange,
    onBlur: handleBlur,
  };

  const handleClose = () => {
    resetForm();
    onClose();
  };

  useEffect(() => {
    setCurrentCustomerId(formikValues.externalId);
  }, [formikValues.externalId]);

  return (
    <Dialog
      title="Edit Information"
      onCancel={handleClose}
      onSave={handleSubmit}
      disableSaveBtn={!!Object.keys(errors).length || !dirty}
      dialogProps={{
        maxWidth: 'lg',
        open: openDialog || false,
      }}>
      <Typography variant="h6" pt="1rem" pb="1.5rem">
        {t('Basic Information')}
      </Typography>
      <Grid container spacing={3}>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g Mainteny GmbH',
              label: 'Customer Name',
              name: 'name',
              value: formikValues.name,
              helperText: touched.name && errors.name,
              error: !!errors.name && touched.name,
              required: true,
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g johndoe@example.com',
              label: 'Email',
              name: 'email',
              value: formikValues.email,
              helperText: touched.email && errors.email,
              error: !!errors.email && touched.email,
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g johndoe@example.com',
              label: 'Billing Email Address',
              name: 'billingEmail',
              value: formikValues.billingEmail,
              helperText: touched.billingEmail && errors.billingEmail,
              error: !!errors.billingEmail && touched.billingEmail,
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g +34 12345678',
              label: 'Phone',
              name: 'phone',
              value: formikValues.phone,
              helperText: touched.phone && errors.phone,
              error: !!errors.phone && touched.phone,
              InputProps: {
                startAdornment: (
                  <InputAdornment position="start">+</InputAdornment>
                ),
              },
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g +34 12345678',
              label: '2nd Phone',
              name: 'secondaryPhoneNumber',
              value: formikValues.secondaryPhoneNumber,
              helperText:
                touched.secondaryPhoneNumber && errors.secondaryPhoneNumber,
              error:
                !!errors.secondaryPhoneNumber && touched.secondaryPhoneNumber,
              InputProps: {
                startAdornment: (
                  <InputAdornment position="start"> + </InputAdornment>
                ),
              },
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g mainteny.com',
              label: 'Website/URL',
              name: 'url',
              value: formikValues.url,
              helperText: touched.url && errors.url,
              error: !!errors.url && touched.url,
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={4}>
          <ComboBox
            options={[]}
            initialValue={
              formikValues.externalId
                ? {
                    label: formikValues.externalId,
                    value: formikValues.externalId || '',
                  }
                : null
            }
            initialQuery={formikValues.externalId}
            getValue={(item) => {
              setFieldValue('externalId', item?.value || '');
            }}
            autoIdProps={{
              handleAction: companyAutoNumberConfig?.configRecords.find(
                (item: any) =>
                  item.type === ServiceCompanyNumberType.PROPERTY_OWNER,
              )?.enabled
                ? () => {
                    generateNextNumber();
                  }
                : () => {
                    setOpenNewDialog(true);
                  },
              isEnabled: companyAutoNumberConfig?.configRecords.find(
                (item: any) =>
                  item.type === ServiceCompanyNumberType.PROPERTY_OWNER,
              )?.enabled,
            }}
            textFieldProps={{
              size: 'small',
              placeholder: 'e.g 1234',
              label: 'Customer Number',
              name: 'externalId',
              value: formikValues.externalId || '',
              helperText: touched.externalId && errors.externalId,
              error: !!errors.externalId && touched.externalId,
              ...defaultProps,
            }}
          />
        </Grid>

        <Grid item md={4}>
          <DatePicker
            containerStyles={{mr: '1em', width: '100%'}}
            getSelectedDate={(date) => {
              if (date) {
                setValues({
                  ...formikValues,
                  registrationDate: format(date, 'yyyy-MM-dd'),
                });
              }
            }}
            disableMask
            textFieldProps={{
              label: t('Customer Since'),
              name: 'registrationDate',
              helperText:
                errors.registrationDate && touched.registrationDate
                  ? errors.registrationDate
                  : '',
              error: !!(touched.registrationDate && errors.registrationDate),
              sx: {width: '100%'},
              ...defaultProps,
            }}
          />
        </Grid>

        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g 000 000 000',
              label: 'Cost Center',
              name: 'costCenter',
              value: formikValues.costCenter,
              helperText: touched.costCenter && errors.costCenter,
              error: !!errors.costCenter && touched.costCenter,
              ...defaultProps,
            }}
          />
        </Grid>

        <Grid item md={4}>
          <SelectPriority />
        </Grid>

        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              label: 'VAT ID',
              name: 'vatId',
              value: formikValues.vatId,
              helperText: touched.vatId && errors.vatId,
              error: !!errors.vatId && touched.vatId,
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              label: 'Offsetting Account',
              name: 'offsettingAccount',
              value: formikValues.offsettingAccount,
              helperText: touched.offsettingAccount && errors.offsettingAccount,
              error: !!errors.offsettingAccount && touched.offsettingAccount,
              ...defaultProps,
            }}
          />
        </Grid>
      </Grid>

      <Typography variant="h6" pt="2rem" pb="1.5rem">
        {t('Billing Address')}
      </Typography>
      <Grid container spacing={3}>
        <Grid item md={2.5}>
          <FormInput
            props={{
              size: 'small',
              label: 'Name',
              name: 'billingAddress.component.name',
              value: formikValues.billingAddress?.component?.name ?? '',
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={2.5}>
          <FormInput
            props={{
              size: 'small',
              label: 'Address line 1',
              name: 'billingAddress.component.street',
              value: formikValues.billingAddress?.component?.street ?? '',
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={2.5}>
          <FormInput
            props={{
              size: 'small',
              label: 'Address line 2',
              name: 'billingAddress.component.street2',
              value: formikValues.billingAddress?.component?.street2 ?? '',
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={2.5}>
          <FormInput
            props={{
              size: 'small',
              label: 'City',
              name: 'billingAddress.component.city',
              value: formikValues.billingAddress?.component?.city ?? '',
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={1.5}>
          <FormInput
            props={{
              size: 'small',
              label: 'ZIP/Postal Code',
              name: 'billingAddress.component.postalCode',
              value: formikValues.billingAddress?.component?.postalCode ?? '',
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={2.5}>
          <FormSelect
            labelId="billingAddress.component.country"
            label="Country"
            options={countriesOptions}
            selectProps={{
              id: 'billingAddress.component.country',
              name: 'billingAddress.component.country',
              value: formikValues.billingAddress?.component?.country ?? '',
              multiple: false,
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={2.5}>
          <FormSelect
            labelId="billingAddress.component.state"
            label="State/Province/Region"
            options={statesByCountry(
              formikValues.billingAddress?.component?.country,
            )}
            selectProps={{
              id: 'billingAddress.component.state',
              name: 'billingAddress.component.state',
              value: formikValues.billingAddress?.component?.state ?? '',
              multiple: false,
              onChange: handleChange,
            }}
          />
        </Grid>
      </Grid>

      <Box
        pt={4}
        pb={2}
        display="flex"
        alignItems="center"
        justifyContent="space-between">
        <Typography variant="h6">{t('Beneficiary address')}</Typography>
        {showBeneficiaryAddress && (
          <IconButton onClick={removeBeneficiaryAddress} size="small">
            <Delete />
          </IconButton>
        )}
      </Box>
      {showBeneficiaryAddress ? (
        <Grid container spacing={3}>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'Name',
                name: 'beneficiaryAddress.component.name',
                value: formikValues.beneficiaryAddress?.component?.name ?? '',
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'Address line 1',
                name: 'beneficiaryAddress.component.street',
                value: formikValues.beneficiaryAddress?.component?.street ?? '',
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'Address line 2',
                name: 'beneficiaryAddress.component.street2',
                value:
                  formikValues.beneficiaryAddress?.component?.street2 ?? '',
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'City',
                name: 'beneficiaryAddress.component.city',
                value: formikValues.beneficiaryAddress?.component?.city ?? '',
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid item md={1.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'ZIP/Postal Code',
                name: 'beneficiaryAddress.component.postalCode',
                value:
                  formikValues.beneficiaryAddress?.component?.postalCode ?? '',
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormSelect
              labelId="beneficiaryAddress.component.country"
              label="Country"
              options={countriesOptions}
              selectProps={{
                id: 'beneficiaryAddress.component.country',
                name: 'beneficiaryAddress.component.country',
                value:
                  formikValues.beneficiaryAddress?.component?.country ?? '',
                multiple: false,
                ...defaultProps,
                onChange: handleChange,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormSelect
              labelId="beneficiaryAddress.component.state"
              label="State/Province/Region"
              options={statesByCountry(
                formikValues.beneficiaryAddress?.component?.country,
              )}
              selectProps={{
                id: 'beneficiaryAddress.component.state',
                name: 'beneficiaryAddress.component.state',
                value: formikValues.beneficiaryAddress?.component?.state ?? '',
                multiple: false,
                ...defaultProps,
                onChange: handleChange,
              }}
            />
          </Grid>
        </Grid>
      ) : (
        <Button
          buttonProps={{
            size: 'medium',
            variant: 'outlined',
            onClick: () => setShowBeneficiaryAddress(true),
            sx: {background: 'transparent'},
          }}>
          <Typography variant="subtitle2">
            {t('Add Beneficiary Address')}
          </Typography>
        </Button>
      )}

      <Box
        pt={4}
        pb={2}
        display="flex"
        alignItems="center"
        justifyContent="space-between">
        <Typography variant="h6">
          {t('Send invoice via different address')}
        </Typography>
        {showSendInvoiceViaAddress && (
          <IconButton onClick={removeSendInvoiceViaAddress} size="small">
            <Delete />
          </IconButton>
        )}
      </Box>
      {showSendInvoiceViaAddress ? (
        <Grid container spacing={3}>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'Name',
                name: 'otherAddress.component.name',
                value: formikValues.otherAddress?.component?.name ?? '',
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'Address line 1',
                name: 'otherAddress.component.street',
                value: formikValues.otherAddress?.component?.street ?? '',
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'Address line 2',
                name: 'otherAddress.component.street2',
                value: formikValues.otherAddress?.component?.street2 ?? '',
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'City',
                name: 'otherAddress.component.city',
                value: formikValues.otherAddress?.component?.city ?? '',
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid item md={1.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'ZIP/Postal Code',
                name: 'otherAddress.component.postalCode',
                value: formikValues.otherAddress?.component?.postalCode ?? '',
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormSelect
              labelId="otherAddress.component.country"
              label="Country"
              options={countriesOptions}
              selectProps={{
                id: 'otherAddress.component.country',
                name: 'otherAddress.component.country',
                value: formikValues.otherAddress?.component?.country ?? '',
                multiple: false,
                onChange: handleChange,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormSelect
              labelId="otherAddress.component.state"
              label="State/Province/Region"
              options={statesByCountry(
                formikValues.otherAddress?.component?.country,
              )}
              selectProps={{
                id: 'otherAddress.component.state',
                name: 'otherAddress.component.state',
                value: formikValues.otherAddress?.component?.state ?? '',
                multiple: false,
                ...defaultProps,
              }}
            />
          </Grid>
        </Grid>
      ) : (
        <Button
          buttonProps={{
            size: 'medium',
            variant: 'outlined',
            onClick: () => setShowSendInvoiceViaAddress(true),
            sx: {
              background: 'transparent',
            },
          }}>
          <Typography variant="subtitle2">
            {t('Add Send invoice via')}
          </Typography>
        </Button>
      )}

      <AutoGeneratedIdDialog
        openDialog={openNewDialog}
        setOpenDialog={setOpenNewDialog}
      />
    </Dialog>
  );
};

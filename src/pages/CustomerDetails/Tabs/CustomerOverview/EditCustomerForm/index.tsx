import {useCallback, useEffect, useState} from 'react';
import {format} from 'date-fns';
import {useTranslation} from 'react-i18next';
import {useFormikContext} from 'formik';
import Grid from '@mui/material/Grid';
import Box from '@mui/material/Box';
import InputAdornment from '@mui/material/InputAdornment';
import IconButton from '@mui/material/IconButton';
import Delete from '@mui/icons-material/Delete';
import {countriesOptions, getStatesByCountry} from 'utils/countries';
import {FormInput} from 'components/form/FormInput';
import {Dialog} from 'components/Dialog';
import {DatePicker} from 'components/DatePicker';
import {FormSelect} from 'components/form/FormSelect';
import {Button} from 'components/Button';
import {AutoAwesome} from '@mui/icons-material';
import {
  useCompanyAutoNumberConfig,
  useCompanyNextNumber,
} from 'hooks/reactQuery/useCompanies';
import {ServiceCompanyNumberType} from 'models/service-company';
import {Typography, useTheme} from '@mui/material';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import {useQueryCustomers} from 'hooks/reactQuery/useCustomers';
import {PropertyOwnerView} from 'models/propertyManager';
import {createEmptyResource} from 'utils/paging-utils';
import AutoGeneratedIdDialog from 'components/AutoGeneratedIdDialog';
import {CustomerEditForm} from './model';
import {SelectPriority} from './SelectPriority';

interface Props {
  openDialog: boolean;
  onClose: () => void;
}

export const EditCustomerForm = ({openDialog, onClose}: Props) => {
  const {
    values,
    errors,
    touched,
    handleChange,
    handleBlur,
    submitForm,
    setValues,
    setFieldValue,
  } = useFormikContext<CustomerEditForm>();
  const {t} = useTranslation();

  const theme = useTheme();
  const {user} = useUserSession();

  const [initId, setInitId] = useState(values.externalId);
  const {data: customerResource = createEmptyResource<PropertyOwnerView>(50)} =
    useQueryCustomers(
      {
        pageIndex: 0,
        pageSize: 50,
        query: values.externalId,
      },
      {keepPreviousData: true},
    );

  const [openNewDialog, setOpenNewDialog] = useState<boolean>(false);
  const [activeField, setActiveField] = useState<string>('');

  const handleFocus = (e: any) => {
    setActiveField(e.target.name);
  };

  const {data: companyAutoNumberConfig} = useCompanyAutoNumberConfig(
    user?.userAccount.serviceCompany.id,
  );

  const {data: companyNextNumber, refetch: refetchCompanyNumber} =
    useCompanyNextNumber(
      {
        type: ServiceCompanyNumberType.PROPERTY_OWNER,
      },
      user?.userAccount.serviceCompany.id,
    );

  useEffect(() => {
    setInitId(values.externalId);
  }, []);

  const [showBeneficiaryAddress, setShowBeneficiaryAddress] = useState(
    !!values.beneficiaryAddress || false,
  );
  const [showSendInvoiceViaAddress, setShowSendInvoiceViaAddress] = useState(
    !!values.otherAddress || false,
  );

  const statesByCountry = useCallback(
    (country?: string) => getStatesByCountry(country ?? ''),
    [
      values.billingAddress?.component?.country,
      values.beneficiaryAddress?.component?.country,
      values.otherAddress?.component?.country,
    ],
  );

  const removeBeneficiaryAddress = () => {
    setFieldValue('beneficiaryAddress.fullName', null);
    setShowBeneficiaryAddress(false);
  };

  const removeSendInvoiceViaAddress = () => {
    setFieldValue('otherAddress.fullName', null);
    setShowSendInvoiceViaAddress(false);
  };

  const defaultProps = {
    onChange: handleChange,
    onBlur: handleBlur,
  };

  return (
    <Dialog
      title="Edit Information"
      onCancel={onClose}
      onSave={submitForm}
      disableSaveBtn={!!Object.keys(errors).length}
      dialogProps={{
        maxWidth: 'lg',
        open: openDialog || false,
      }}>
      <Typography variant="h6" pt="1rem" pb="1.5rem">
        {t('Basic Information')}
      </Typography>
      <Grid container spacing={3}>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g Mainteny GmbH',
              label: 'Customer Name',
              name: 'name',
              value: values.name,
              helperText: touched.name && errors.name,
              error: !!errors.name && touched.name,
              required: true,
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g johndoe@example.com',
              label: 'Email',
              name: 'email',
              value: values.email,
              helperText: touched.email && errors.email,
              error: !!errors.email && touched.email,
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g johndoe@example.com',
              label: 'Billing Email Address',
              name: 'billingEmail',
              value: values.billingEmail,
              helperText: touched.billingEmail && errors.billingEmail,
              error: !!errors.billingEmail && touched.billingEmail,
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g +34 12345678',
              label: 'Phone',
              name: 'phone',
              value: values.phone,
              helperText: touched.phone && errors.phone,
              error: !!errors.phone && touched.phone,
              InputProps: {
                startAdornment: (
                  <InputAdornment position="start">+</InputAdornment>
                ),
              },
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g +34 12345678',
              label: '2nd Phone',
              name: 'secondaryPhoneNumber',
              value: values.secondaryPhoneNumber,
              helperText:
                touched.secondaryPhoneNumber && errors.secondaryPhoneNumber,
              error:
                !!errors.secondaryPhoneNumber && touched.secondaryPhoneNumber,
              InputProps: {
                startAdornment: (
                  <InputAdornment position="start"> + </InputAdornment>
                ),
              },
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g mainteny.com',
              label: 'Website/URL',
              name: 'url',
              value: values.url,
              helperText: touched.url && errors.url,
              error: !!errors.url && touched.url,
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g 1234',
              label: 'Customer Number',
              name: 'externalId',
              value: values.externalId,
              helperText: touched.externalId && errors.externalId,
              error: !!errors.externalId && touched.externalId,
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
          {(activeField === 'externalId' || touched.externalId) &&
            values.externalId &&
            initId !== values.externalId &&
            customerResource?.data.filter(
              (item) => item.externalId === values.externalId,
            ).length > 0 && (
              <Typography
                color="error"
                fontSize="0.75rem"
                letterSpacing="0.03em"
                padding="0.45em 0.65em">
                {t('This ID is already taken. Please enter a different one.')}
              </Typography>
            )}
          {activeField === 'externalId' &&
          !values.externalId &&
          companyAutoNumberConfig?.configRecords.find(
            (item) => item.type === ServiceCompanyNumberType.PROPERTY_OWNER,
          )?.enabled ? (
            <Box
              sx={{
                borderRadius: '4px',
                boxShadow: '0px 9px 46px 8px #0000001F',
                marginTop: '0.2em',
              }}>
              <Button
                buttonProps={{
                  onClick: () => {
                    refetchCompanyNumber();
                    setFieldValue('externalId', companyNextNumber?.value);
                  },
                  sx: {
                    display: 'flex',
                    flexDirection: 'column',
                    justifyContent: 'flex-start',
                    textAlign: 'left',
                    alignItems: 'flex-start',
                    width: '100%',
                    padding: '1em 2em',
                  },
                }}>
                <Box
                  sx={{
                    display: 'flex',
                    flexDirection: 'row',
                    alignItems: 'center',
                    paddingBottom: '0.6em',
                  }}>
                  <AutoAwesome />
                  <Typography variant="subtitle2" sx={{paddingLeft: '0.5em'}}>
                    {t('Generate ID')}
                  </Typography>
                </Box>

                <Typography
                  variant="body2"
                  color={theme.palette.text.secondary}>
                  {t('Customizable in Settings')}
                </Typography>
              </Button>
            </Box>
          ) : (
            activeField === 'externalId' &&
            !values.externalId &&
            !companyAutoNumberConfig?.configRecords.find(
              (item) => item.type === ServiceCompanyNumberType.PROPERTY_OWNER,
            )?.enabled && (
              <Box
                sx={{
                  borderRadius: '4px',
                  boxShadow: '0px 9px 46px 8px #0000001F',
                  marginTop: '0.2em',
                }}>
                <Button
                  buttonProps={{
                    size: 'medium',
                    variant: 'outlined',
                    onClick: () => setOpenNewDialog(true),
                    sx: {
                      display: 'flex',
                      flexDirection: 'column',
                      justifyContent: 'flex-start',
                      textAlign: 'left',
                      alignItems: 'flex-start',
                      width: '100%',
                      padding: '1em 2em',
                    },
                  }}>
                  <Box
                    sx={{
                      display: 'flex',
                      flexDirection: 'row',
                      alignItems: 'center',
                      paddingBottom: '0.6em',
                    }}>
                    <AutoAwesome />
                    <Typography variant="subtitle2" sx={{paddingLeft: '0.5em'}}>
                      {t('Enable Automatic ID Generation')}
                    </Typography>
                  </Box>

                  <Typography
                    variant="body2"
                    color={theme.palette.text.secondary}>
                    {t('Allows for easier number input')}
                  </Typography>
                </Button>
              </Box>
            )
          )}
        </Grid>

        <Grid item md={4}>
          <DatePicker
            containerStyles={{mr: '1em', width: '100%'}}
            getSelectedDate={(date) => {
              if (date) {
                setValues({
                  ...values,
                  registrationDate: format(date, 'yyyy-MM-dd'),
                });
              }
            }}
            disableMask
            textFieldProps={{
              label: t('Customer Since'),
              name: 'registrationDate',
              helperText:
                errors.registrationDate && touched.registrationDate
                  ? errors.registrationDate
                  : '',
              error: !!(touched.registrationDate && errors.registrationDate),
              sx: {width: '100%'},
              onBlur: handleBlur,
            }}
          />
        </Grid>

        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g 000 000 000',
              label: 'Cost Center',
              name: 'costCenter',
              value: values.costCenter,
              helperText: touched.costCenter && errors.costCenter,
              error: !!errors.costCenter && touched.costCenter,
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>

        <Grid item md={4}>
          <SelectPriority />
        </Grid>

        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              label: 'VAT/Tax number',
              name: 'taxNumber',
              value: values.taxNumber,
              helperText: touched.taxNumber && errors.taxNumber,
              error: !!errors.taxNumber && touched.taxNumber,
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
      </Grid>

      <Typography variant="h6" pt="2rem" pb="1.5rem">
        {t('Billing Address')}
      </Typography>
      <Grid container spacing={3}>
        <Grid item md={2.5}>
          <FormInput
            props={{
              size: 'small',
              label: 'Name',
              name: 'billingAddress.component.name',
              value: values.billingAddress?.component?.name ?? '',
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
        <Grid item md={2.5}>
          <FormInput
            props={{
              size: 'small',
              label: 'Address line 1',
              name: 'billingAddress.component.street',
              value: values.billingAddress?.component?.street ?? '',
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
        <Grid item md={2.5}>
          <FormInput
            props={{
              size: 'small',
              label: 'Address line 2',
              name: 'billingAddress.component.street2',
              value: values.billingAddress?.component?.street2 ?? '',
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
        <Grid item md={2.5}>
          <FormInput
            props={{
              size: 'small',
              label: 'City',
              name: 'billingAddress.component.city',
              value: values.billingAddress?.component?.city ?? '',
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
        <Grid item md={1.5}>
          <FormInput
            props={{
              size: 'small',
              label: 'ZIP/Postal Code',
              name: 'billingAddress.component.postalCode',
              value: values.billingAddress?.component?.postalCode ?? '',
              ...defaultProps,
            }}
            handleFocus={handleFocus}
          />
        </Grid>
        <Grid item md={2.5}>
          <FormSelect
            labelId="billingAddress.component.country"
            label="Country"
            options={countriesOptions}
            selectProps={{
              id: 'billingAddress.component.country',
              name: 'billingAddress.component.country',
              value: values.billingAddress?.component?.country ?? '',
              multiple: false,
              onChange: handleChange,
            }}
          />
        </Grid>
        <Grid item md={2.5}>
          <FormSelect
            labelId="billingAddress.component.state"
            label="State/Province/Region"
            options={statesByCountry(values.billingAddress?.component?.country)}
            selectProps={{
              id: 'billingAddress.component.state',
              name: 'billingAddress.component.state',
              value: values.billingAddress?.component?.state ?? '',
              multiple: false,
              onChange: handleChange,
            }}
          />
        </Grid>
      </Grid>

      <Box
        pt={4}
        pb={2}
        display="flex"
        alignItems="center"
        justifyContent="space-between">
        <Typography variant="h6">{t('Beneficiary address')}</Typography>
        {showBeneficiaryAddress && (
          <IconButton onClick={removeBeneficiaryAddress} size="small">
            <Delete />
          </IconButton>
        )}
      </Box>
      {showBeneficiaryAddress ? (
        <Grid container spacing={3}>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'Name',
                name: 'beneficiaryAddress.component.name',
                value: values.beneficiaryAddress?.component?.name ?? '',
                ...defaultProps,
              }}
              handleFocus={handleFocus}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'Address line 1',
                name: 'beneficiaryAddress.component.street',
                value: values.beneficiaryAddress?.component?.street ?? '',
                ...defaultProps,
              }}
              handleFocus={handleFocus}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'Address line 2',
                name: 'beneficiaryAddress.component.street2',
                value: values.beneficiaryAddress?.component?.street2 ?? '',
                ...defaultProps,
              }}
              handleFocus={handleFocus}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'City',
                name: 'beneficiaryAddress.component.city',
                value: values.beneficiaryAddress?.component?.city ?? '',
                ...defaultProps,
              }}
              handleFocus={handleFocus}
            />
          </Grid>
          <Grid item md={1.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'ZIP/Postal Code',
                name: 'beneficiaryAddress.component.postalCode',
                value: values.beneficiaryAddress?.component?.postalCode ?? '',
                ...defaultProps,
              }}
              handleFocus={handleFocus}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormSelect
              labelId="beneficiaryAddress.component.country"
              label="Country"
              options={countriesOptions}
              selectProps={{
                id: 'beneficiaryAddress.component.country',
                name: 'beneficiaryAddress.component.country',
                value: values.beneficiaryAddress?.component?.country ?? '',
                multiple: false,
                onChange: handleChange,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormSelect
              labelId="beneficiaryAddress.component.state"
              label="State/Province/Region"
              options={statesByCountry(
                values.beneficiaryAddress?.component?.country,
              )}
              selectProps={{
                id: 'beneficiaryAddress.component.state',
                name: 'beneficiaryAddress.component.state',
                value: values.beneficiaryAddress?.component?.state ?? '',
                multiple: false,
                onChange: handleChange,
              }}
            />
          </Grid>
        </Grid>
      ) : (
        <Button
          buttonProps={{
            size: 'medium',
            variant: 'outlined',
            onClick: () => setShowBeneficiaryAddress(true),
            sx: {background: 'transparent'},
          }}>
          <Typography variant="subtitle2">
            {t('Add Beneficiary Address')}
          </Typography>
        </Button>
      )}

      <Box
        pt={4}
        pb={2}
        display="flex"
        alignItems="center"
        justifyContent="space-between">
        <Typography variant="h6">
          {t('Send invoice via different address')}
        </Typography>
        {showSendInvoiceViaAddress && (
          <IconButton onClick={removeSendInvoiceViaAddress} size="small">
            <Delete />
          </IconButton>
        )}
      </Box>
      {showSendInvoiceViaAddress ? (
        <Grid container spacing={3}>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'Name',
                name: 'otherAddress.component.name',
                value: values.otherAddress?.component?.name ?? '',
                ...defaultProps,
              }}
              handleFocus={handleFocus}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'Address line 1',
                name: 'otherAddress.component.street',
                value: values.otherAddress?.component?.street ?? '',
                ...defaultProps,
              }}
              handleFocus={handleFocus}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'Address line 2',
                name: 'otherAddress.component.street2',
                value: values.otherAddress?.component?.street2 ?? '',
                ...defaultProps,
              }}
              handleFocus={handleFocus}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'City',
                name: 'otherAddress.component.city',
                value: values.otherAddress?.component?.city ?? '',
                ...defaultProps,
              }}
              handleFocus={handleFocus}
            />
          </Grid>
          <Grid item md={1.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'ZIP/Postal Code',
                name: 'otherAddress.component.postalCode',
                value: values.otherAddress?.component?.postalCode ?? '',
                ...defaultProps,
              }}
              handleFocus={handleFocus}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormSelect
              labelId="otherAddress.component.country"
              label="Country"
              options={countriesOptions}
              selectProps={{
                id: 'otherAddress.component.country',
                name: 'otherAddress.component.country',
                value: values.otherAddress?.component?.country ?? '',
                multiple: false,
                onChange: handleChange,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormSelect
              labelId="otherAddress.component.state"
              label="State/Province/Region"
              options={statesByCountry(values.otherAddress?.component?.country)}
              selectProps={{
                id: 'otherAddress.component.state',
                name: 'otherAddress.component.state',
                value: values.otherAddress?.component?.state ?? '',
                multiple: false,
                onChange: handleChange,
              }}
            />
          </Grid>
        </Grid>
      ) : (
        <Button
          buttonProps={{
            size: 'medium',
            variant: 'outlined',
            onClick: () => setShowSendInvoiceViaAddress(true),
            sx: {
              background: 'transparent',
            },
          }}>
          <Typography variant="subtitle2">
            {t('Add Send invoice via')}
          </Typography>
        </Button>
      )}

      <AutoGeneratedIdDialog
        openDialog={openNewDialog}
        setOpenDialog={setOpenNewDialog}
      />
    </Dialog>
  );
};

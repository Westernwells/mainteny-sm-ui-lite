import {useCallback, useEffect, useState} from 'react';
import {format} from 'date-fns';
import {useTranslation} from 'react-i18next';
import {useFormik, useFormikContext} from 'formik';
import Grid from '@mui/material/Grid';
import * as Yup from 'yup';
import Box from '@mui/material/Box';
import InputAdornment from '@mui/material/InputAdornment';
import IconButton from '@mui/material/IconButton';
import Delete from '@mui/icons-material/Delete';
import {countriesOptions, getStatesByCountry} from 'utils/countries';
import {FormInput} from 'components/form/FormInput';
import {Dialog} from 'components/Dialog';
import {DatePicker} from 'components/DatePicker';
import {FormSelect} from 'components/form/FormSelect';
import {Button} from 'components/Button';
import {ServiceCompanyNumberType} from 'models/service-company';
import {Typography} from '@mui/material';
import {useQueryCustomers} from 'hooks/reactQuery/useCustomers';
import {PropertyOwnerView} from 'models/propertyManager';
import {createEmptyResource} from 'utils/paging-utils';
import AutoGeneratedIdDialog from 'components/AutoGeneratedIdDialog';
import {ComboBox} from 'components/ComboBox';
import {
  useCompanyAutoNumberConfig,
  useCompanyNextNumber,
} from 'hooks/reactQuery/useCompanies';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import {CustomerEditForm} from './model';
import {SelectPriority} from './SelectPriority';

interface Props {
  openDialog: boolean;
  onClose: () => void;
}

const phoneValidationRE =
  /^((\\+[1-9]{1,4}[ \\-]*)|(\\([0-9]{2,3}\\)[ \\-]*)|([0-9]{2,4})[ \\-]*)*?[0-9]{3,4}?[ \\-]*[0-9]{3,4}?$/;

const isExternalIdUnique = async (
  resource: PropertyOwnerView[],
  value?: string,
) => {
  if (!value) {
    return true;
  }
  try {
    return !(resource && resource.some((item) => item.externalId === value));
  } catch (error) {
    console.error('Error checking externalId uniqueness:', error);
    return true;
  }
};

export const EditCustomerForm = ({openDialog, onClose}: Props) => {
  const {t} = useTranslation();
  const {user} = useUserSession();
  const [initValue, setInitValue] = useState('');
  const [updatedValue, setUpdatedValue] = useState('');
  const {values: formikValues, handleSubmit} =
    useFormikContext<CustomerEditForm>();

  const {data: customerResource = createEmptyResource<PropertyOwnerView>(50)} =
    useQueryCustomers(
      {
        pageIndex: 0,
        pageSize: 50,
        query: updatedValue,
      },
      {keepPreviousData: true},
    );

  const validationSchema = Yup.object().shape({
    name: Yup.string().required('Customer Name is required'),
    email: Yup.string().email('Enter a valid email'),
    billingEmail: Yup.string().email('Enter a valid email'),
    phone: Yup.string().matches(phoneValidationRE, 'Phone number is not valid'),
    secondaryPhoneNumber: Yup.string().matches(
      phoneValidationRE,
      'Phone number is not valid',
    ),
    billingAddress: Yup.object().nullable(),
    beneficiaryAddress: Yup.object().nullable(),
    otherAddress: Yup.object().nullable(),
    externalId: Yup.string().test(
      'checkExternalId',
      'This ID is already taken. Please enter a different one.',
      async (value) => {
        if (value !== initValue) {
          return isExternalIdUnique(customerResource.data, value);
        }
        return true;
      },
    ),
  });

  const formik = useFormik<CustomerEditForm>({
    initialValues: {...formikValues},
    onSubmit: () => {
      handleSubmit();
    },
    validationSchema,
  });

  const [openNewDialog, setOpenNewDialog] = useState<boolean>(false);

  const {data: companyAutoNumberConfig} = useCompanyAutoNumberConfig(
    user?.userAccount.serviceCompany.id,
  );

  const {data: companyNextNumber} = useCompanyNextNumber(
    {
      type: ServiceCompanyNumberType.PROPERTY_OWNER,
    },
    user?.userAccount.serviceCompany.id,
  );

  const generateNextNumber = () => {
    formik.setFieldValue('externalId', companyNextNumber?.value);
  };

  useEffect(() => {
    setInitValue(formik.values.externalId!);
  }, []);

  useEffect(() => {
    setUpdatedValue(formik.values.externalId);
  }, [formik]);

  const [showBeneficiaryAddress, setShowBeneficiaryAddress] = useState(
    !!formik.values.beneficiaryAddress || false,
  );
  const [showSendInvoiceViaAddress, setShowSendInvoiceViaAddress] = useState(
    !!formik.values.otherAddress || false,
  );

  const statesByCountry = useCallback(
    (country?: string) => getStatesByCountry(country ?? ''),
    [
      formik.values.billingAddress?.component?.country,
      formik.values.beneficiaryAddress?.component?.country,
      formik.values.otherAddress?.component?.country,
    ],
  );

  const removeBeneficiaryAddress = () => {
    formik.setFieldValue('beneficiaryAddress.fullName', null);
    setShowBeneficiaryAddress(false);
  };

  const removeSendInvoiceViaAddress = () => {
    formik.setFieldValue('otherAddress.fullName', null);
    setShowSendInvoiceViaAddress(false);
  };

  const defaultProps = {
    onChange: formik.handleChange,
    onBlur: formik.handleBlur,
  };

  const handleClose = () => {
    formik.resetForm();
    onClose();
  };

  return (
    <Dialog
      title="Edit Information"
      onCancel={handleClose}
      onSave={formik.submitForm}
      disableSaveBtn={!!Object.keys(formik.errors).length || !formik.dirty}
      dialogProps={{
        maxWidth: 'lg',
        open: openDialog || false,
      }}>
      <Typography variant="h6" pt="1rem" pb="1.5rem">
        {t('Basic Information')}
      </Typography>
      <Grid container spacing={3}>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g Mainteny GmbH',
              label: 'Customer Name',
              name: 'name',
              value: formik.values.name,
              helperText: formik.touched.name && formik.errors.name,
              error: !!formik.errors.name && formik.touched.name,
              required: true,
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g johndoe@example.com',
              label: 'Email',
              name: 'email',
              value: formik.values.email,
              helperText: formik.touched.email && formik.errors.email,
              error: !!formik.errors.email && formik.touched.email,
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g johndoe@example.com',
              label: 'Billing Email Address',
              name: 'billingEmail',
              value: formik.values.billingEmail,
              helperText:
                formik.touched.billingEmail && formik.errors.billingEmail,
              error:
                !!formik.errors.billingEmail && formik.touched.billingEmail,
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g +34 12345678',
              label: 'Phone',
              name: 'phone',
              value: formik.values.phone,
              helperText: formik.touched.phone && formik.errors.phone,
              error: !!formik.errors.phone && formik.touched.phone,
              InputProps: {
                startAdornment: (
                  <InputAdornment position="start">+</InputAdornment>
                ),
              },
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g +34 12345678',
              label: '2nd Phone',
              name: 'secondaryPhoneNumber',
              value: formik.values.secondaryPhoneNumber,
              helperText:
                formik.touched.secondaryPhoneNumber &&
                formik.errors.secondaryPhoneNumber,
              error:
                !!formik.errors.secondaryPhoneNumber &&
                formik.touched.secondaryPhoneNumber,
              InputProps: {
                startAdornment: (
                  <InputAdornment position="start"> + </InputAdornment>
                ),
              },
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g mainteny.com',
              label: 'Website/URL',
              name: 'url',
              value: formik.values.url,
              helperText: formik.touched.url && formik.errors.url,
              error: !!formik.errors.url && formik.touched.url,
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={4}>
          <ComboBox
            options={[]}
            initialValue={
              formik.values.externalId
                ? {
                    label: formik.values.externalId,
                    value: formik.values.externalId,
                  }
                : null
            }
            initialQuery={formik.values.externalId}
            getValue={(item) => {
              formik.setFieldValue('externalId', item?.value);
            }}
            autoIdProps={{
              handleAction: companyAutoNumberConfig?.configRecords.find(
                (item: any) =>
                  item.type === ServiceCompanyNumberType.PROPERTY_OWNER,
              )?.enabled
                ? () => {
                    generateNextNumber();
                  }
                : () => {
                    setOpenNewDialog(true);
                  },
              isEnabled: companyAutoNumberConfig?.configRecords.find(
                (item: any) =>
                  item.type === ServiceCompanyNumberType.PROPERTY_OWNER,
              )?.enabled,
            }}
            textFieldProps={{
              size: 'small',
              placeholder: 'e.g 1234',
              label: 'Customer Number',
              name: 'externalId',
              value: formik.values.externalId,
              helperText: formik.touched.externalId && formik.errors.externalId,
              error: !!formik.errors.externalId && formik.touched.externalId,
              ...defaultProps,
            }}
          />
        </Grid>

        <Grid item md={4}>
          <DatePicker
            containerStyles={{mr: '1em', width: '100%'}}
            getSelectedDate={(date) => {
              if (date) {
                formik.setValues({
                  ...formik.values,
                  registrationDate: format(date, 'yyyy-MM-dd'),
                });
              }
            }}
            disableMask
            textFieldProps={{
              label: t('Customer Since'),
              name: 'registrationDate',
              helperText:
                formik.errors.registrationDate &&
                formik.touched.registrationDate
                  ? formik.errors.registrationDate
                  : '',
              error: !!(
                formik.touched.registrationDate &&
                formik.errors.registrationDate
              ),
              sx: {width: '100%'},
              onBlur: formik.handleBlur,
            }}
          />
        </Grid>

        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              placeholder: 'e.g 000 000 000',
              label: 'Cost Center',
              name: 'costCenter',
              value: formik.values.costCenter,
              helperText: formik.touched.costCenter && formik.errors.costCenter,
              error: !!formik.errors.costCenter && formik.touched.costCenter,
              ...defaultProps,
            }}
          />
        </Grid>

        <Grid item md={4}>
          <SelectPriority />
        </Grid>

        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              label: 'VAT ID',
              name: 'vatId',
              value: formik.values.vatId,
              helperText: formik.touched.vatId && formik.errors.vatId,
              error: !!formik.errors.vatId && formik.touched.vatId,
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={4}>
          <FormInput
            props={{
              size: 'small',
              label: 'Offsetting Account',
              name: 'offsettingAccount',
              value: formik.values.offsettingAccount,
              helperText:
                formik.touched.offsettingAccount &&
                formik.errors.offsettingAccount,
              error:
                !!formik.errors.offsettingAccount &&
                formik.touched.offsettingAccount,
              ...defaultProps,
            }}
          />
        </Grid>
      </Grid>

      <Typography variant="h6" pt="2rem" pb="1.5rem">
        {t('Billing Address')}
      </Typography>
      <Grid container spacing={3}>
        <Grid item md={2.5}>
          <FormInput
            props={{
              size: 'small',
              label: 'Name',
              name: 'billingAddress.component.name',
              value: formik.values.billingAddress?.component?.name ?? '',
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={2.5}>
          <FormInput
            props={{
              size: 'small',
              label: 'Address line 1',
              name: 'billingAddress.component.street',
              value: formik.values.billingAddress?.component?.street ?? '',
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={2.5}>
          <FormInput
            props={{
              size: 'small',
              label: 'Address line 2',
              name: 'billingAddress.component.street2',
              value: formik.values.billingAddress?.component?.street2 ?? '',
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={2.5}>
          <FormInput
            props={{
              size: 'small',
              label: 'City',
              name: 'billingAddress.component.city',
              value: formik.values.billingAddress?.component?.city ?? '',
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={1.5}>
          <FormInput
            props={{
              size: 'small',
              label: 'ZIP/Postal Code',
              name: 'billingAddress.component.postalCode',
              value: formik.values.billingAddress?.component?.postalCode ?? '',
              ...defaultProps,
            }}
          />
        </Grid>
        <Grid item md={2.5}>
          <FormSelect
            labelId="billingAddress.component.country"
            label="Country"
            options={countriesOptions}
            selectProps={{
              id: 'billingAddress.component.country',
              name: 'billingAddress.component.country',
              value: formik.values.billingAddress?.component?.country ?? '',
              multiple: false,
              onChange: formik.handleChange,
            }}
          />
        </Grid>
        <Grid item md={2.5}>
          <FormSelect
            labelId="billingAddress.component.state"
            label="State/Province/Region"
            options={statesByCountry(
              formik.values.billingAddress?.component?.country,
            )}
            selectProps={{
              id: 'billingAddress.component.state',
              name: 'billingAddress.component.state',
              value: formik.values.billingAddress?.component?.state ?? '',
              multiple: false,
              onChange: formik.handleChange,
            }}
          />
        </Grid>
      </Grid>

      <Box
        pt={4}
        pb={2}
        display="flex"
        alignItems="center"
        justifyContent="space-between">
        <Typography variant="h6">{t('Beneficiary address')}</Typography>
        {showBeneficiaryAddress && (
          <IconButton onClick={removeBeneficiaryAddress} size="small">
            <Delete />
          </IconButton>
        )}
      </Box>
      {showBeneficiaryAddress ? (
        <Grid container spacing={3}>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'Name',
                name: 'beneficiaryAddress.component.name',
                value: formik.values.beneficiaryAddress?.component?.name ?? '',
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'Address line 1',
                name: 'beneficiaryAddress.component.street',
                value:
                  formik.values.beneficiaryAddress?.component?.street ?? '',
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'Address line 2',
                name: 'beneficiaryAddress.component.street2',
                value:
                  formik.values.beneficiaryAddress?.component?.street2 ?? '',
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'City',
                name: 'beneficiaryAddress.component.city',
                value: formik.values.beneficiaryAddress?.component?.city ?? '',
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid item md={1.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'ZIP/Postal Code',
                name: 'beneficiaryAddress.component.postalCode',
                value:
                  formik.values.beneficiaryAddress?.component?.postalCode ?? '',
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormSelect
              labelId="beneficiaryAddress.component.country"
              label="Country"
              options={countriesOptions}
              selectProps={{
                id: 'beneficiaryAddress.component.country',
                name: 'beneficiaryAddress.component.country',
                value:
                  formik.values.beneficiaryAddress?.component?.country ?? '',
                multiple: false,
                ...defaultProps,
                onChange: formik.handleChange,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormSelect
              labelId="beneficiaryAddress.component.state"
              label="State/Province/Region"
              options={statesByCountry(
                formik.values.beneficiaryAddress?.component?.country,
              )}
              selectProps={{
                id: 'beneficiaryAddress.component.state',
                name: 'beneficiaryAddress.component.state',
                value: formik.values.beneficiaryAddress?.component?.state ?? '',
                multiple: false,
                ...defaultProps,
                onChange: formik.handleChange,
              }}
            />
          </Grid>
        </Grid>
      ) : (
        <Button
          buttonProps={{
            size: 'medium',
            variant: 'outlined',
            onClick: () => setShowBeneficiaryAddress(true),
            sx: {background: 'transparent'},
          }}>
          <Typography variant="subtitle2">
            {t('Add Beneficiary Address')}
          </Typography>
        </Button>
      )}

      <Box
        pt={4}
        pb={2}
        display="flex"
        alignItems="center"
        justifyContent="space-between">
        <Typography variant="h6">
          {t('Send invoice via different address')}
        </Typography>
        {showSendInvoiceViaAddress && (
          <IconButton onClick={removeSendInvoiceViaAddress} size="small">
            <Delete />
          </IconButton>
        )}
      </Box>
      {showSendInvoiceViaAddress ? (
        <Grid container spacing={3}>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'Name',
                name: 'otherAddress.component.name',
                value: formik.values.otherAddress?.component?.name ?? '',
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'Address line 1',
                name: 'otherAddress.component.street',
                value: formik.values.otherAddress?.component?.street ?? '',
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'Address line 2',
                name: 'otherAddress.component.street2',
                value: formik.values.otherAddress?.component?.street2 ?? '',
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'City',
                name: 'otherAddress.component.city',
                value: formik.values.otherAddress?.component?.city ?? '',
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid item md={1.5}>
            <FormInput
              props={{
                size: 'small',
                label: 'ZIP/Postal Code',
                name: 'otherAddress.component.postalCode',
                value: formik.values.otherAddress?.component?.postalCode ?? '',
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormSelect
              labelId="otherAddress.component.country"
              label="Country"
              options={countriesOptions}
              selectProps={{
                id: 'otherAddress.component.country',
                name: 'otherAddress.component.country',
                value: formik.values.otherAddress?.component?.country ?? '',
                multiple: false,
                onChange: formik.handleChange,
              }}
            />
          </Grid>
          <Grid item md={2.5}>
            <FormSelect
              labelId="otherAddress.component.state"
              label="State/Province/Region"
              options={statesByCountry(
                formik.values.otherAddress?.component?.country,
              )}
              selectProps={{
                id: 'otherAddress.component.state',
                name: 'otherAddress.component.state',
                value: formik.values.otherAddress?.component?.state ?? '',
                multiple: false,
                onChange: formik.handleChange,
              }}
            />
          </Grid>
        </Grid>
      ) : (
        <Button
          buttonProps={{
            size: 'medium',
            variant: 'outlined',
            onClick: () => setShowSendInvoiceViaAddress(true),
            sx: {
              background: 'transparent',
            },
          }}>
          <Typography variant="subtitle2">
            {t('Add Send invoice via')}
          </Typography>
        </Button>
      )}

      <AutoGeneratedIdDialog
        openDialog={openNewDialog}
        setOpenDialog={setOpenNewDialog}
      />
    </Dialog>
  );
};

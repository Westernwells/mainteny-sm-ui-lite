import {useEffect, useState, Dispatch, SetStateAction} from 'react';
import {useFormikContext} from 'formik';
import {useTranslation} from 'react-i18next';
import Box from '@mui/material/Box';
import useTheme from '@mui/material/styles/useTheme';
import InputAdornment from '@mui/material/InputAdornment';
import Typography from '@mui/material/Typography';
import PhoneIcon from '@mui/icons-material/Phone';
import {Email} from '@mui/icons-material';
import {FormInput} from 'components/form/FormInput';
import {Dialog} from 'components/Dialog';
import {Role} from 'models/user';
import {ServiceCompanyNumberType} from 'models/service-company';
import AutoGeneratedIdDialog from 'components/AutoGeneratedIdDialog';
import {ComboBox} from 'components/ComboBox';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import {
  useCompanyAutoNumberConfig,
  useCompanyNextNumber,
} from 'hooks/reactQuery/useCompanies';
import {SelectShift} from './SelectShift';
import {EmployeeAccountData} from './model';
import {SelectAddress} from './SelectAddress';
import {SelectEmployeeRole} from './SelectEmployeeRole';
import {SelectServiceOrderTypes} from './SelectServiceOrderTypes';

interface Props {
  openDialog: boolean;
  onClose: () => void;
  setCurrentEmployeeId: Dispatch<SetStateAction<string>>;
}

export const EditEmployeeForm = ({
  openDialog,
  onClose,
  setCurrentEmployeeId,
}: Props) => {
  const {t} = useTranslation();
  const theme = useTheme();
  const {user} = useUserSession();

  const {
    values: formikValues,
    handleChange,
    handleBlur,
    handleSubmit,
    touched,
    errors,
    dirty,
    resetForm,
    setFieldValue,
  } = useFormikContext<EmployeeAccountData>();

  const defaultProps = {
    onChange: handleChange,
    onBlur: handleBlur,
  };

  const [openNewDialog, setOpenNewDialog] = useState<boolean>(false);

  const {data: companyAutoNumberConfig} = useCompanyAutoNumberConfig(
    user?.userAccount.serviceCompany.id,
  );

  const {data: companyNextNumber} = useCompanyNextNumber(
    {
      type: ServiceCompanyNumberType.EMPLOYEE,
    },
    user?.userAccount.serviceCompany.id,
  );

  const generateNextNumber = () => {
    setFieldValue('employeeId', companyNextNumber?.value);
  };

  const handleClose = () => {
    resetForm();
    onClose();
  };

  useEffect(() => {
    setCurrentEmployeeId(formikValues.employeeId);
  }, [formikValues.employeeId]);

  return (
    <Dialog
      title="Edit Basic Information"
      onCancel={handleClose}
      onSave={handleSubmit}
      disableSaveBtn={
        !!Object.keys(errors).length || !dirty || !formikValues?.shifts?.length
      }
      dialogProps={{
        maxWidth: 'md',
        open: openDialog || false,
      }}>
      <Box
        component="form"
        height="100%"
        display="flex"
        flexDirection="column"
        justifyContent="space-between">
        <Box flexGrow={1}>
          <Box display="flex" gap="1em" justifyContent="space-between">
            <Box>
              <Box
                display="flex"
                gap="1em"
                sx={{
                  marginBlock: '0.5em',
                  marginBottom: '1.5em',
                }}>
                {[
                  {
                    id: 'firstName',
                    label: t('First Name'),
                    placeholder: 'Blake',
                    value: formikValues.firstName,
                    helperText: touched.firstName && errors.firstName,
                    error: !!errors.firstName && touched.firstName,
                    required: true,
                    ...defaultProps,
                  },
                  {
                    id: 'lastName',
                    label: t('Last Name'),
                    placeholder: 'Norton',
                    value: formikValues.lastName,
                    helperText: touched.lastName && errors.lastName,
                    error: !!errors.lastName && touched.lastName,
                    required: true,
                    ...defaultProps,
                  },
                ].map((item, index) => (
                  <FormInput
                    key={index}
                    fieldProps={{
                      ...item,
                      ...defaultProps,
                    }}
                  />
                ))}
              </Box>
              <Box display="flex" flexDirection="column" gap="1em">
                {[
                  {
                    id: 'phone',
                    label: t('Phone'),
                    placeholder: '49 17163 995801',
                    value: formikValues.phone,
                    InputProps: {
                      startAdornment: (
                        <InputAdornment position="start"> + </InputAdornment>
                      ),
                      endAdornment: (
                        <InputAdornment position="end">
                          <PhoneIcon />
                        </InputAdornment>
                      ),
                    },
                    helperText: touched.phone && errors.phone,
                    error: !!errors.phone && touched.phone,
                    ...defaultProps,
                  },
                ].map((item, index) => (
                  <FormInput
                    key={index}
                    fieldProps={{
                      ...item,
                      ...defaultProps,
                    }}
                  />
                ))}
                <SelectAddress />
                {[
                  {
                    id: 'team',
                    label: t('Team'),
                    placeholder: '100',
                    value: formikValues.team,
                    helperText: touched.team && errors.team,
                    error: !!errors.team && touched.team,
                    ...defaultProps,
                  },
                ].map((item, index) => (
                  <FormInput
                    key={index}
                    fieldProps={{
                      ...item,
                      ...defaultProps,
                    }}
                  />
                ))}
              </Box>
            </Box>
            <Box
              display="flex"
              flexDirection="column"
              sx={{minWidth: '28.125em'}}
              gap="1em">
              <SelectEmployeeRole />
              {[
                {
                  id: 'email',
                  label: t('Email'),
                  placeholder: 'john@astralift.com',
                  InputProps: {
                    endAdornment: (
                      <InputAdornment position="end">
                        <Email />
                      </InputAdornment>
                    ),
                  },
                  value: formikValues.email,
                  helperText: touched.email && errors.email,
                  error: !!errors.email && touched.email,
                  required: true,
                  ...defaultProps,
                },
              ].map((item, index) => (
                <FormInput
                  key={index}
                  fieldProps={{
                    ...item,
                    ...defaultProps,
                  }}
                />
              ))}

              <Box
                display="flex"
                flexDirection="column"
                sx={{minWidth: '28.125em'}}
                gap="0em">
                <ComboBox
                  options={[]}
                  initialValue={
                    formikValues.employeeId
                      ? {
                          label: 'Employee Id',
                          value: formikValues.employeeId,
                        }
                      : null
                  }
                  initialQuery={formikValues.employeeId}
                  getValue={(item) => {
                    setFieldValue('employeeId', item?.value);
                  }}
                  autoIdProps={{
                    handleAction: companyAutoNumberConfig?.configRecords.find(
                      (item: any) =>
                        item.type === ServiceCompanyNumberType.EMPLOYEE,
                    )?.enabled
                      ? () => {
                          generateNextNumber();
                        }
                      : () => {
                          setOpenNewDialog(true);
                        },
                    isEnabled: companyAutoNumberConfig?.configRecords.find(
                      (item: any) =>
                        item.type === ServiceCompanyNumberType.EMPLOYEE,
                    )?.enabled,
                  }}
                  textFieldProps={{
                    id: 'employeeId',
                    name: 'employeeId',
                    label: t('Employee ID'),
                    placeholder: '12345678',
                    value: formikValues.employeeId,
                    helperText: touched.employeeId && errors.employeeId,
                    error: !!errors.employeeId && touched.employeeId,
                    ...defaultProps,
                  }}
                />
              </Box>
            </Box>
          </Box>
          {formikValues.roles.includes(Role.TECHNICIAN) && (
            <>
              <Typography
                variant="h6"
                my=".75em"
                sx={{color: theme.palette.text.primary}}>
                {t('Order Types')}
              </Typography>
              <SelectServiceOrderTypes
                values={formikValues}
                setFieldValue={setFieldValue}
              />
            </>
          )}
          <Typography
            variant="h6"
            my=".75em"
            sx={{color: theme.palette.text.primary}}>
            {t('Shift Time')}
            <Typography component="span" sx={{color: 'red'}}>
              *
            </Typography>
          </Typography>
          <SelectShift values={formikValues} setFieldValue={setFieldValue} />
        </Box>
      </Box>

      <AutoGeneratedIdDialog
        openDialog={openNewDialog}
        setOpenDialog={setOpenNewDialog}
      />
    </Dialog>
  );
};

import React, {useState, useEffect} from 'react';
import {useFormikContext} from 'formik';
import {useTranslation} from 'react-i18next';
import Box from '@mui/material/Box';
import useTheme from '@mui/material/styles/useTheme';
import InputAdornment from '@mui/material/InputAdornment';
import Typography from '@mui/material/Typography';
import PhoneIcon from '@mui/icons-material/Phone';
import {AutoAwesome, Email} from '@mui/icons-material';
import {FormInput} from 'components/form/FormInput';
import {Dialog} from 'components/Dialog';
import {Role, UserView} from 'models/user';
import {Button} from 'components/Button';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import {
  useCompanyAutoNumberConfig,
  useCompanyNextNumber,
} from 'hooks/reactQuery/useCompanies';
import {ServiceCompanyNumberType} from 'models/service-company';
import {createEmptyResource} from 'utils/paging-utils';
import {useQueryUserAccounts} from 'hooks/reactQuery/useUserAccount';
import {getRoles} from 'utils/work-hours-utils';
import AutoGeneratedIdDialog from 'components/AutoGeneratedIdDialog';
import {SelectShift} from './SelectShift';
import {EmployeeAccountData} from './model';
import {SelectAddress} from './SelectAddress';
import {SelectEmployeeRole} from './SelectEmployeeRole';
import {SelectServiceOrderTypes} from './SelectServiceOrderTypes';

interface Props {
  openDialog: boolean;
  onClose: () => void;
}

export const EditEmployeeForm = ({openDialog, onClose}: Props) => {
  const {t} = useTranslation();
  const theme = useTheme();

  const {user} = useUserSession();

  const {
    values,
    touched,
    errors,
    handleChange,
    handleBlur,
    handleSubmit,
    setFieldValue,
    submitForm,
  } = useFormikContext<EmployeeAccountData>();

  const defaultProps = {
    onChange: handleChange,
    onBlur: handleBlur,
  };

  const [initId, setInitId] = useState(values.employeeId);

  const [openNewDialog, setOpenNewDialog] = useState<boolean>(false);
  const [activeField, setActiveField] = useState<string>('');

  const handleFocus = (e: any) => {
    setActiveField(e.target.name);
  };

  const {data: userAccountResource = createEmptyResource<UserView>(25)} =
    useQueryUserAccounts(
      {
        pageIndex: 0,
        pageSize: 25,
        query: values.employeeId,
        roles: getRoles(''),
      },
      {keepPreviousData: true},
    );

  const {data: companyAutoNumberConfig} = useCompanyAutoNumberConfig(
    user?.userAccount.serviceCompany.id,
  );

  const {data: companyNextNumber, refetch: refetchCompanyNumber} =
    useCompanyNextNumber(
      {
        type: ServiceCompanyNumberType.EMPLOYEE,
      },
      user?.userAccount.serviceCompany.id,
    );

  useEffect(() => {
    setInitId(values.employeeId);
  }, []);

  return (
    <Dialog
      title="Edit Basic Information"
      onCancel={onClose}
      onSave={submitForm}
      disableSaveBtn={!!Object.keys(errors).length}
      dialogProps={{
        maxWidth: 'md',
        open: openDialog || false,
      }}>
      <Box
        component="form"
        onSubmit={handleSubmit}
        height="100%"
        display="flex"
        flexDirection="column"
        justifyContent="space-between">
        <Box flexGrow={1}>
          <Box display="flex" gap="1em" justifyContent="space-between">
            <Box>
              <Box
                display="flex"
                gap="1em"
                sx={{
                  marginBlock: '0.5em',
                  marginBottom: '1.5em',
                }}>
                {[
                  {
                    id: 'firstName',
                    label: t('First Name'),
                    placeholder: 'Blake',
                    value: values.firstName,
                    helperText: touched.firstName && errors.firstName,
                    error: !!errors.firstName && touched.firstName,
                    required: true,
                  },
                  {
                    id: 'lastName',
                    label: t('Last Name'),
                    placeholder: 'Norton',
                    value: values.lastName,
                    helperText: touched.lastName && errors.lastName,
                    error: !!errors.lastName && touched.lastName,
                    required: true,
                  },
                ].map((item, index) => (
                  <FormInput
                    key={index}
                    props={{
                      ...item,
                      ...defaultProps,
                    }}
                  />
                ))}
              </Box>
              <Box display="flex" flexDirection="column" gap="1em">
                {[
                  {
                    id: 'phone',
                    label: t('Phone'),
                    placeholder: '49 17163 995801',
                    value: values.phone,
                    InputProps: {
                      startAdornment: (
                        <InputAdornment position="start"> + </InputAdornment>
                      ),
                      endAdornment: (
                        <InputAdornment position="end">
                          <PhoneIcon />
                        </InputAdornment>
                      ),
                    },
                    helperText: touched.phone && errors.phone,
                    error: !!errors.phone && touched.phone,
                  },
                ].map((item, index) => (
                  <FormInput
                    key={index}
                    props={{
                      ...item,
                      ...defaultProps,
                    }}
                    handleFocus={handleFocus}
                  />
                ))}
                <SelectAddress />
                {[
                  {
                    id: 'team',
                    label: t('Team'),
                    placeholder: '100',
                    value: values.team,
                    helperText: touched.team && errors.team,
                    error: !!errors.team && touched.team,
                  },
                ].map((item, index) => (
                  <FormInput
                    key={index}
                    props={{
                      ...item,
                      ...defaultProps,
                    }}
                    handleFocus={handleFocus}
                  />
                ))}
              </Box>
            </Box>
            <Box
              display="flex"
              flexDirection="column"
              sx={{minWidth: '28.125em'}}
              gap="1em">
              <SelectEmployeeRole />
              {[
                {
                  id: 'email',
                  label: t('Email'),
                  placeholder: 'john@astralift.com',
                  InputProps: {
                    endAdornment: (
                      <InputAdornment position="end">
                        <Email />
                      </InputAdornment>
                    ),
                  },
                  value: values.email,
                  helperText: touched.email && errors.email,
                  error: !!errors.email && touched.email,
                  required: true,
                },
              ].map((item, index) => (
                <FormInput
                  key={index}
                  props={{
                    ...item,
                    ...defaultProps,
                  }}
                  handleFocus={handleFocus}
                />
              ))}

              {[
                {
                  id: 'employeeId',
                  name: 'employeeId',
                  label: t('Employee ID'),
                  placeholder: '12345678',
                  value: values.employeeId,
                  helperText: touched.employeeId && errors.employeeId,
                  error: !!errors.employeeId && touched.employeeId,
                },
              ].map((item, index) => (
                <>
                  <FormInput
                    key={index}
                    props={{
                      ...item,
                      ...defaultProps,
                    }}
                    handleFocus={handleFocus}
                  />
                  {(activeField === 'employeeId' || touched.employeeId) &&
                    values.employeeId &&
                    initId !== values.employeeId &&
                    userAccountResource?.data.filter(
                      (userItem: UserView) =>
                        userItem.userData.externalId === values.employeeId,
                    ).length > 0 && (
                      <Typography
                        color="error"
                        fontSize="0.75rem"
                        letterSpacing="0.03em"
                        padding="0.45em 0.65em">
                        {t(
                          'This ID is already taken. Please enter a different one.',
                        )}
                      </Typography>
                    )}
                  {activeField === 'employeeId' &&
                  !values.employeeId &&
                  companyAutoNumberConfig?.configRecords.find(
                    (configRecord) =>
                      configRecord.type === ServiceCompanyNumberType.EMPLOYEE,
                  )?.enabled ? (
                    <Box
                      sx={{
                        borderRadius: '4px',
                        boxShadow: '0px 9px 46px 8px #0000001F',
                        marginTop: '0.2em',
                      }}>
                      <Button
                        buttonProps={{
                          onClick: () => {
                            refetchCompanyNumber();
                            setFieldValue(
                              'employeeId',
                              companyNextNumber?.value,
                            );
                          },
                          sx: {
                            display: 'flex',
                            flexDirection: 'column',
                            justifyContent: 'flex-start',
                            textAlign: 'left',
                            alignItems: 'flex-start',
                            width: '100%',
                            padding: '1em',
                          },
                        }}>
                        <Box
                          sx={{
                            display: 'flex',
                            flexDirection: 'row',
                            alignItems: 'center',
                            paddingBottom: '0.6em',
                          }}>
                          <AutoAwesome />
                          <Typography
                            variant="caption"
                            fontWeight="700"
                            sx={{paddingLeft: '0.5em'}}>
                            {t('Generate ID')}
                          </Typography>
                        </Box>

                        <Typography
                          variant="caption"
                          color={theme.palette.text.secondary}>
                          {t('Customizable in Settings')}
                        </Typography>
                      </Button>
                    </Box>
                  ) : (
                    activeField === 'employeeId' &&
                    !values.employeeId &&
                    !companyAutoNumberConfig?.configRecords.find(
                      (configRecord) =>
                        configRecord.type === ServiceCompanyNumberType.EMPLOYEE,
                    )?.enabled && (
                      <Box
                        sx={{
                          borderRadius: '4px',
                          boxShadow: '0px 9px 46px 8px #0000001F',
                          marginTop: '-1em',
                        }}>
                        <Button
                          buttonProps={{
                            size: 'medium',
                            variant: 'outlined',
                            onClick: () => setOpenNewDialog(true),
                            sx: {
                              display: 'flex',
                              flexDirection: 'column',
                              justifyContent: 'flex-start',
                              textAlign: 'left',
                              alignItems: 'flex-start',
                              width: '100%',
                              padding: '1em',
                            },
                          }}>
                          <Box
                            sx={{
                              display: 'flex',
                              flexDirection: 'row',
                              alignItems: 'center',
                              paddingBottom: '0.6em',
                            }}>
                            <AutoAwesome />
                            <Typography
                              variant="caption"
                              sx={{paddingLeft: '0.5em'}}
                              fontWeight="700">
                              {t('Enable Automatic ID Generation')}
                            </Typography>
                          </Box>

                          <Typography
                            variant="caption"
                            color={theme.palette.text.secondary}>
                            {t('Allows for easier number input')}
                          </Typography>
                        </Button>
                      </Box>
                    )
                  )}
                </>
              ))}
            </Box>
          </Box>
          {values.roles.includes(Role.TECHNICIAN) && (
            <>
              <Typography
                variant="h6"
                my=".75em"
                sx={{color: theme.palette.text.primary}}>
                {t('Order Types')}
              </Typography>
              <SelectServiceOrderTypes
                values={values}
                setFieldValue={setFieldValue}
              />
            </>
          )}
          <Typography
            variant="h6"
            my=".75em"
            sx={{color: theme.palette.text.primary}}>
            {t('Shift Time')}
            <Typography component="span" sx={{color: 'red'}}>
              *
            </Typography>
          </Typography>
          <SelectShift values={values} setFieldValue={setFieldValue} />
        </Box>
      </Box>

      <AutoGeneratedIdDialog
        openDialog={openNewDialog}
        setOpenDialog={setOpenNewDialog}
      />
    </Dialog>
  );
};

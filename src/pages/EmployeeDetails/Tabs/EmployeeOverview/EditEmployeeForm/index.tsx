import {useState, useEffect} from 'react';
import {useFormik, useFormikContext} from 'formik';
import {useTranslation} from 'react-i18next';
import * as Yup from 'yup';
import Box from '@mui/material/Box';
import useTheme from '@mui/material/styles/useTheme';
import InputAdornment from '@mui/material/InputAdornment';
import Typography from '@mui/material/Typography';
import PhoneIcon from '@mui/icons-material/Phone';
import {Email} from '@mui/icons-material';
import {FormInput} from 'components/form/FormInput';
import {Dialog} from 'components/Dialog';
import {Role, UserView} from 'models/user';
import {ServiceCompanyNumberType} from 'models/service-company';
import {createEmptyResource} from 'utils/paging-utils';
import {useQueryUserAccounts} from 'hooks/reactQuery/useUserAccount';
import {getRoles} from 'utils/work-hours-utils';
import AutoGeneratedIdDialog from 'components/AutoGeneratedIdDialog';
import {ComboBox} from 'components/ComboBox';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import {
  useCompanyAutoNumberConfig,
  useCompanyNextNumber,
} from 'hooks/reactQuery/useCompanies';
import {SelectShift} from './SelectShift';
import {EmployeeAccountData} from './model';
import {SelectAddress} from './SelectAddress';
import {SelectEmployeeRole} from './SelectEmployeeRole';
import {SelectServiceOrderTypes} from './SelectServiceOrderTypes';

interface Props {
  openDialog: boolean;
  onClose: () => void;
}

const phoneValidationRE =
  /^((\\+[1-9]{1,4}[ \\-]*)|(\\([0-9]{2,3}\\)[ \\-]*)|([0-9]{2,4})[ \\-]*)*?[0-9]{3,4}?[ \\-]*[0-9]{3,4}?$/;

const isExternalIdUnique = async (resource: UserView[], value?: string) => {
  if (!value) {
    return true;
  }
  try {
    return !(
      resource && resource.some((item) => item.userData.externalId === value)
    );
  } catch (error) {
    console.error('Error checking externalId uniqueness:', error);
    return true;
  }
};

export const EditEmployeeForm = ({openDialog, onClose}: Props) => {
  const {t} = useTranslation();
  const theme = useTheme();
  const {user} = useUserSession();
  const [initValue, setInitValue] = useState('');
  const [updatedValue, setUpdatedValue] = useState('');
  const {values: formikValues, handleSubmit} =
    useFormikContext<EmployeeAccountData>();

  const {data: userAccountResource = createEmptyResource<UserView>(25)} =
    useQueryUserAccounts(
      {
        pageIndex: 0,
        pageSize: 25,
        query: updatedValue,
        roles: getRoles(''),
      },
      {keepPreviousData: true},
    );

  const validationSchema = Yup.object().shape({
    firstName: Yup.string().required('First name is required'),
    lastName: Yup.string().required('Last name is required'),
    email: Yup.string()
      .email('Enter a valid email')
      .required('Email is required'),
    team: Yup.string().matches(/^[0-9]+$/, 'Team is not valid'),
    address: Yup.object().nullable().required('Address is required'),
    phone: Yup.string().matches(phoneValidationRE, 'Phone number is not valid'),
    employeeId: Yup.string().test(
      'checkExternalId',
      'This ID is already taken. Please enter a different one.',
      async (value) => {
        if (value !== initValue) {
          return isExternalIdUnique(userAccountResource.data, value);
        }
        return true;
      },
    ),
  });

  const formik = useFormik<EmployeeAccountData>({
    initialValues: {...formikValues},
    onSubmit: () => {
      handleSubmit();
    },
    validationSchema,
  });

  const defaultProps = {
    onChange: formik.handleChange,
    onBlur: formik.handleBlur,
  };

  const [openNewDialog, setOpenNewDialog] = useState<boolean>(false);

  const {data: companyAutoNumberConfig} = useCompanyAutoNumberConfig(
    user?.userAccount.serviceCompany.id,
  );

  const {data: companyNextNumber} = useCompanyNextNumber(
    {
      type: ServiceCompanyNumberType.EMPLOYEE,
    },
    user?.userAccount.serviceCompany.id,
  );

  const generateNextNumber = () => {
    formik.setFieldValue('employeeId', companyNextNumber?.value);
  };

  useEffect(() => {
    setInitValue(formik.values.employeeId);
  }, []);

  useEffect(() => {
    setUpdatedValue(formik.values.employeeId);
  }, [formik]);

  const handleClose = () => {
    formik.resetForm();
    onClose();
  };

  return (
    <Dialog
      title="Edit Basic Information"
      onCancel={handleClose}
      onSave={formik.submitForm}
      disableSaveBtn={!!Object.keys(formik.errors).length || !formik.dirty}
      dialogProps={{
        maxWidth: 'md',
        open: openDialog || false,
      }}>
      <Box
        component="form"
        onSubmit={formik.handleSubmit}
        height="100%"
        display="flex"
        flexDirection="column"
        justifyContent="space-between">
        <Box flexGrow={1}>
          <Box display="flex" gap="1em" justifyContent="space-between">
            <Box>
              <Box
                display="flex"
                gap="1em"
                sx={{
                  marginBlock: '0.5em',
                  marginBottom: '1.5em',
                }}>
                {[
                  {
                    id: 'firstName',
                    label: t('First Name'),
                    placeholder: 'Blake',
                    value: formik.values.firstName,
                    helperText:
                      formik.touched.firstName && formik.errors.firstName,
                    error:
                      !!formik.errors.firstName && formik.touched.firstName,
                    required: true,
                  },
                  {
                    id: 'lastName',
                    label: t('Last Name'),
                    placeholder: 'Norton',
                    value: formik.values.lastName,
                    helperText:
                      formik.touched.lastName && formik.errors.lastName,
                    error: !!formik.errors.lastName && formik.touched.lastName,
                    required: true,
                  },
                ].map((item, index) => (
                  <FormInput
                    key={index}
                    props={{
                      ...item,
                      ...defaultProps,
                    }}
                  />
                ))}
              </Box>
              <Box display="flex" flexDirection="column" gap="1em">
                {[
                  {
                    id: 'phone',
                    label: t('Phone'),
                    placeholder: '49 17163 995801',
                    value: formik.values.phone,
                    InputProps: {
                      startAdornment: (
                        <InputAdornment position="start"> + </InputAdornment>
                      ),
                      endAdornment: (
                        <InputAdornment position="end">
                          <PhoneIcon />
                        </InputAdornment>
                      ),
                    },
                    helperText: formik.touched.phone && formik.errors.phone,
                    error: !!formik.errors.phone && formik.touched.phone,
                  },
                ].map((item, index) => (
                  <FormInput
                    key={index}
                    props={{
                      ...item,
                      ...defaultProps,
                    }}
                  />
                ))}
                <SelectAddress />
                {[
                  {
                    id: 'team',
                    label: t('Team'),
                    placeholder: '100',
                    value: formik.values.team,
                    helperText: formik.touched.team && formik.errors.team,
                    error: !!formik.errors.team && formik.touched.team,
                  },
                ].map((item, index) => (
                  <FormInput
                    key={index}
                    props={{
                      ...item,
                      ...defaultProps,
                    }}
                  />
                ))}
              </Box>
            </Box>
            <Box
              display="flex"
              flexDirection="column"
              sx={{minWidth: '28.125em'}}
              gap="1em">
              <SelectEmployeeRole />
              {[
                {
                  id: 'email',
                  label: t('Email'),
                  placeholder: 'john@astralift.com',
                  InputProps: {
                    endAdornment: (
                      <InputAdornment position="end">
                        <Email />
                      </InputAdornment>
                    ),
                  },
                  value: formik.values.email,
                  helperText: formik.touched.email && formik.errors.email,
                  error: !!formik.errors.email && formik.touched.email,
                  required: true,
                },
              ].map((item, index) => (
                <FormInput
                  key={index}
                  props={{
                    ...item,
                    ...defaultProps,
                  }}
                />
              ))}

              <Box
                display="flex"
                flexDirection="column"
                sx={{minWidth: '28.125em'}}
                gap="0em">
                <ComboBox
                  options={[]}
                  initialValue={
                    formik.values.employeeId
                      ? {
                          label: formik.values.employeeId,
                          value: formik.values.employeeId,
                        }
                      : null
                  }
                  initialQuery={formik.values.employeeId}
                  getValue={(item) => {
                    formik.setFieldValue('employeeId', item?.value);
                  }}
                  autoIdProps={{
                    handleAction: companyAutoNumberConfig?.configRecords.find(
                      (item: any) =>
                        item.type === ServiceCompanyNumberType.EMPLOYEE,
                    )?.enabled
                      ? () => {
                          generateNextNumber();
                        }
                      : () => {
                          setOpenNewDialog(true);
                        },
                    isEnabled: companyAutoNumberConfig?.configRecords.find(
                      (item: any) =>
                        item.type === ServiceCompanyNumberType.EMPLOYEE,
                    )?.enabled,
                  }}
                  textFieldProps={{
                    id: 'employeeId',
                    name: 'employeeId',
                    label: t('Employee ID'),
                    placeholder: '12345678',
                    value: formik.values.employeeId,
                    helperText:
                      formik.touched.employeeId && formik.errors.employeeId,
                    error:
                      !!formik.errors.employeeId && formik.touched.employeeId,
                    onBlur: formik.handleBlur,
                    onChange: formik.handleChange,
                  }}
                />
              </Box>
            </Box>
          </Box>
          {formik.values.roles.includes(Role.TECHNICIAN) && (
            <>
              <Typography
                variant="h6"
                my=".75em"
                sx={{color: theme.palette.text.primary}}>
                {t('Order Types')}
              </Typography>
              <SelectServiceOrderTypes
                values={formik.values}
                setFieldValue={formik.setFieldValue}
              />
            </>
          )}
          <Typography
            variant="h6"
            my=".75em"
            sx={{color: theme.palette.text.primary}}>
            {t('Shift Time')}
            <Typography component="span" sx={{color: 'red'}}>
              *
            </Typography>
          </Typography>
          <SelectShift
            values={formik.values}
            setFieldValue={formik.setFieldValue}
          />
        </Box>
      </Box>

      <AutoGeneratedIdDialog
        openDialog={openNewDialog}
        setOpenDialog={setOpenNewDialog}
      />
    </Dialog>
  );
};

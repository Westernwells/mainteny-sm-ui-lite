import {Box} from '@mui/system';
import {FormInput} from 'components/form/FormInput';
import Grid from '@mui/material/Grid';
import {FormikErrors, FormikValues, useFormik} from 'formik';
import {UnitDetailsFormModel} from 'models/unitForm';
import * as Yup from 'yup';
import {useEffect, useState} from 'react';
import {PageCard} from 'components/PageCard';
import {convertToText} from 'utils/utils';
import {ComboBox} from 'components/ComboBox';
import {createEmptyResource} from 'utils/paging-utils';
import {useCacheValues} from 'hooks/reactQuery/useElevator';
import {CacheTypes} from 'models/misc';
import {ElevatorCategory, ElevatorView} from 'models/elevator';
import InputAdornment from '@mui/material/InputAdornment';
import {useTranslation} from 'react-i18next';
import {
  useCompanyAutoNumberConfig,
  useCompanyNextNumber,
} from 'hooks/reactQuery/useCompanies';
import {ServiceCompanyNumberType} from 'models/service-company';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import AutoGeneratedIdDialog from 'components/AutoGeneratedIdDialog';
import {AutoAwesome} from '@mui/icons-material';
import {Typography, Button} from '@mui/material';
import {theme} from 'theme';

interface Props {
  getUnitDetailsFormErrors?: (val: FormikErrors<UnitDetailsFormModel>) => void;
  getUnitDetailsFormValues?: (val: FormikValues) => void;
  initialValues?: UnitDetailsFormModel;
  customerResource: ElevatorView[];
}

const validationSchema = Yup.object().shape({
  category: Yup.string()
    .nullable()
    .oneOf(
      Object.values(ElevatorCategory).map((c) => convertToText(c)),
      'Invalid unit category',
    )
    .required('Category is required'),
  unitType: Yup.string().nullable(),
});

export const UnitDetailsForm = ({
  getUnitDetailsFormErrors,
  getUnitDetailsFormValues,
  initialValues,
  customerResource,
}: Props) => {
  const {t} = useTranslation();
  const [unitTypeQuery, setUnitTypeQuery] = useState('');
  const [modelQuery, setModelQuery] = useState('');
  const formik = useFormik<UnitDetailsFormModel>({
    initialValues: {
      category: initialValues?.category,
      manufacturer: initialValues?.manufacturer,
      externalId: initialValues?.externalId,
      numberOfStops: initialValues?.numberOfStops,
      cabinType: initialValues?.cabinType,
      emergencyPhoneProvider: initialValues?.emergencyPhoneProvider,
      unitType: initialValues?.unitType,
      model: initialValues?.model,
      serialNumber: initialValues?.serialNumber,
      unitCapacity: initialValues?.unitCapacity,
      spendingLimit: initialValues?.spendingLimit,
      emergencyContactNumber: initialValues?.emergencyContactNumber,
      yearBuilt: initialValues?.yearBuilt,
      modelOfController: initialValues?.modelOfController,
      manufacturerOfController: initialValues?.manufacturerOfController,
    },
    onSubmit: () => {},
    validationSchema,
  });

  const {data: elevatorTypeResource = createEmptyResource<string>()} =
    useCacheValues(
      {
        pageIndex: 0,
        pageSize: 10,
        query: unitTypeQuery,
      },
      CacheTypes.ELEVATOR_TYPE,
    );

  const {data: elevatorModelsResource = createEmptyResource<string>()} =
    useCacheValues(
      {
        pageIndex: 0,
        pageSize: 10,
        query: modelQuery,
      },
      CacheTypes.ELEVATOR_MODEL,
    );

  useEffect(() => {
    if (getUnitDetailsFormErrors) {
      getUnitDetailsFormErrors(formik.errors);
    }

    if (getUnitDetailsFormValues) {
      getUnitDetailsFormValues(formik.values);
    }
  }, [formik]);

  const {user} = useUserSession();
  const [openDialog, setOpenDialog] = useState<boolean>(false);
  const [activeField, setActiveField] = useState<string>('');

  const handleFocus = (e: any) => {
    setActiveField(e.target.name);
  };

  const {data: companyAutoNumberConfig} = useCompanyAutoNumberConfig(
    user?.userAccount.serviceCompany.id,
  );

  const {data: companyNextNumber, refetch: refetchCompanyNumber} =
    useCompanyNextNumber(
      {
        type: ServiceCompanyNumberType.ELEVATOR,
      },
      user?.userAccount.serviceCompany.id,
    );

  useEffect(() => {
    formik.setFieldValue('externalId', companyNextNumber?.value);
  }, [companyNextNumber]);

  return (
    <PageCard
      headerLabel="Unit Details"
      containerStyles={{flexGrow: 1, overflowY: 'scroll', height: 0}}
      headerStyles={{mt: '0.5em'}}>
      <Box sx={{mt: '0.5em'}} component="form">
        <Grid container spacing={2}>
          <Grid item xs={12} sm={4} md={4}>
            <ComboBox
              options={Object.keys(ElevatorCategory).map((item) => ({
                label: t(convertToText(item)),
                value: convertToText(item),
              }))}
              initialValue={
                formik.values.category
                  ? {
                      label: formik.values.category,
                      value: formik.values.category,
                    }
                  : null
              }
              initialQuery={formik.values.category}
              getValue={(item) => formik.setFieldValue('category', item?.value)}
              textFieldProps={{
                name: 'category',
                label: t('Unit Category'),
                onBlur: formik.handleBlur,
                error: !!(formik.touched.category && formik.errors.category),
                helperText:
                  formik.touched.category && formik.errors.category
                    ? formik.errors.category
                    : '',
                placeholder: t('e.g. Elevator'),
                required: true,
              }}
            />
          </Grid>

          <Grid item xs={12} sm={4} md={4}>
            <ComboBox
              options={elevatorTypeResource.data.map((item) => ({
                label: item,
                value: item,
              }))}
              getValue={(item) => formik.setFieldValue('unitType', item?.value)}
              initialValue={
                formik.values.unitType
                  ? {
                      label: formik.values.unitType,
                      value: formik.values.unitType,
                    }
                  : null
              }
              initialQuery={formik.values.unitType}
              getQuery={(item) => setUnitTypeQuery(item || '')}
              textFieldProps={{
                placeholder: 'e.g. Hydraulic',
                name: 'unitType',
                label: 'Unit Type',
                required: false,
                onBlur: formik.handleBlur,
                error: !!(formik.touched.unitType && formik.errors.unitType),
                helperText:
                  formik.touched.unitType && formik.errors.unitType
                    ? formik.errors.unitType
                    : '',
              }}
            />
          </Grid>

          <Grid item xs={12} sm={4} md={4}>
            <FormInput
              props={{
                placeholder: 'e.g. Elevator Installation Meier',
                label: 'Manufacturer',
                name: 'manufacturer',
                value: formik.values.manufacturer,
                onBlur: formik.handleBlur,
                onChange: formik.handleChange,
              }}
            />
          </Grid>

          <Grid item xs={12} sm={4} md={4}>
            <FormInput
              props={{
                placeholder: 'e.g. 000001',
                label: 'Unit Number',
                name: 'externalId',
                value: formik.values.externalId,
                error: !!(
                  formik.touched.externalId && formik.errors.externalId
                ),
                helperText:
                  formik.touched.externalId && formik.errors.externalId
                    ? formik.errors.externalId
                    : '',
                onBlur: formik.handleBlur,
                onChange: formik.handleChange,
              }}
              handleFocus={handleFocus}
            />
            {(activeField === 'externalId' || formik.touched.externalId) &&
              formik.values.externalId &&
              customerResource.filter(
                (item) => item.externalId === formik.values.externalId,
              ).length > 0 && (
                <Typography
                  color="error"
                  fontSize="0.75rem"
                  letterSpacing="0.03em"
                  padding="0.45em 0.65em">
                  {t('This ID is already taken. Please enter a different one.')}
                </Typography>
              )}
            {activeField === 'externalId' &&
            !formik.values.externalId &&
            companyAutoNumberConfig?.configRecords.find(
              (item) => item.type === ServiceCompanyNumberType.ELEVATOR,
            )?.enabled ? (
              <Box
                sx={{
                  borderRadius: '4px',
                  boxShadow: '0px 9px 46px 8px #0000001F',
                  marginTop: '0.2em',
                }}>
                <Button
                  sx={{
                    display: 'flex',
                    flexDirection: 'column',
                    justifyContent: 'flex-start',
                    textAlign: 'left',
                    alignItems: 'flex-start',
                    width: '100%',
                    padding: '1em 2em',
                  }}
                  onClick={() => {
                    refetchCompanyNumber();
                    formik.setFieldValue(
                      'externalId',
                      companyNextNumber?.value,
                    );
                  }}>
                  <Box
                    sx={{
                      display: 'flex',
                      flexDirection: 'row',
                      alignItems: 'center',
                      paddingBottom: '0.6em',
                    }}>
                    <AutoAwesome />
                    <Typography variant="subtitle2" sx={{paddingLeft: '0.5em'}}>
                      {t('Generate ID')}
                    </Typography>
                  </Box>

                  <Typography
                    variant="body2"
                    color={theme.palette.text.secondary}>
                    {t('Customizable in Settings')}
                  </Typography>
                </Button>
              </Box>
            ) : (
              activeField === 'externalId' &&
              !formik.values.externalId &&
              !companyAutoNumberConfig?.configRecords.find(
                (item) => item.type === ServiceCompanyNumberType.ELEVATOR,
              )?.enabled && (
                <Box
                  sx={{
                    borderRadius: '4px',
                    boxShadow: '0px 9px 46px 8px #0000001F',
                    marginTop: '0.2em',
                  }}>
                  <Button
                    sx={{
                      display: 'flex',
                      flexDirection: 'column',
                      justifyContent: 'flex-start',
                      textAlign: 'left',
                      alignItems: 'flex-start',
                      width: '100%',
                      padding: '1em 2em',
                    }}
                    onClick={() => setOpenDialog(true)}>
                    <Box
                      sx={{
                        display: 'flex',
                        flexDirection: 'row',
                        alignItems: 'center',
                        paddingBottom: '0.6em',
                      }}>
                      <AutoAwesome />
                      <Typography
                        variant="subtitle2"
                        sx={{paddingLeft: '0.5em'}}>
                        {t('Enable Automatic ID Generation')}
                      </Typography>
                    </Box>

                    <Typography
                      variant="body2"
                      color={theme.palette.text.secondary}>
                      {t('Allows for easier number input')}
                    </Typography>
                  </Button>
                </Box>
              )
            )}
          </Grid>

          <Grid item xs={12} sm={4} md={4}>
            <ComboBox
              options={elevatorModelsResource.data.map((item) => ({
                label: item,
                value: item,
              }))}
              getValue={(item) =>
                formik.setFieldValue('model', item?.value || '')
              }
              initialValue={
                formik.values.model
                  ? {
                      label: formik.values.model,
                      value: formik.values.model,
                    }
                  : null
              }
              initialQuery={formik.values.model}
              getQuery={(item) => setModelQuery(item || '')}
              textFieldProps={{
                name: 'model',
                label: 'Model',
                placeholder: 'e.g. S2000',
                onBlur: formik.handleBlur,
                error: !!(formik.touched.model && formik.errors.model),
                helperText:
                  formik.touched.model && formik.errors.model
                    ? formik.errors.model
                    : '',
              }}
            />
          </Grid>

          <Grid item xs={12} sm={4} md={4}>
            <FormInput
              props={{
                placeholder: 'e.g. SHX00000000001',
                label: 'Serial Number',
                name: 'serialNumber',
                value: formik.values.serialNumber,
                onBlur: formik.handleBlur,
                onChange: formik.handleChange,
              }}
              handleFocus={handleFocus}
            />
          </Grid>

          <Grid item xs={12} sm={4} md={4}>
            <FormInput
              props={{
                size: 'small',
                placeholder: 'e.g. 10',
                label: 'Number of Stops',
                name: 'numberOfStops',
                type: 'number',
                inputProps: {min: 0},
                value: formik.values.numberOfStops,
                onBlur: formik.handleBlur,
                onChange: formik.handleChange,
              }}
              handleFocus={handleFocus}
            />
          </Grid>

          <Grid item xs={12} sm={4} md={4}>
            <FormInput
              props={{
                name: 'unitCapacity',
                label: 'Unit Capacity',
                placeholder: 'e.g. 1000 kg',
                value: formik.values.unitCapacity,
                onBlur: formik.handleBlur,
                onChange: formik.handleChange,
                error: !!(
                  formik.touched.unitCapacity && formik.errors.unitCapacity
                ),
                helperText:
                  formik.touched.unitCapacity && formik.errors.unitCapacity
                    ? formik.errors.unitCapacity
                    : '',
                InputProps: {
                  endAdornment: (
                    <InputAdornment position="start">kg</InputAdornment>
                  ),
                },
              }}
              handleFocus={handleFocus}
            />
          </Grid>

          <Grid item xs={12} sm={4} md={4}>
            <FormInput
              props={{
                size: 'small',
                placeholder: 'e.g. 2 doors',
                label: 'Cabin Type',
                name: 'cabinType',
                value: formik.values.cabinType,
                onBlur: formik.handleBlur,
                onChange: formik.handleChange,
              }}
              handleFocus={handleFocus}
            />
          </Grid>

          <Grid item xs={12} sm={4} md={4}>
            <FormInput
              props={{
                size: 'small',
                disabled: true,
                placeholder: 'Enter Spending Limit',
                label: 'Spending Limit',
                name: 'spendingLimit',
                error: !!formik.errors.spendingLimit,
                value: formik.values.spendingLimit,
                onBlur: formik.handleBlur,
                onChange: formik.handleChange,
              }}
              handleFocus={handleFocus}
            />
          </Grid>

          <Grid item xs={12} sm={4} md={4}>
            <FormInput
              props={{
                size: 'small',
                placeholder: 'e.g. SafeLine',
                label: 'Emergency Phone Provider',
                name: 'emergencyPhoneProvider',
                value: formik.values.emergencyPhoneProvider,
                onBlur: formik.handleBlur,
                onChange: formik.handleChange,
              }}
              handleFocus={handleFocus}
            />
          </Grid>

          <Grid item xs={12} sm={4} md={4}>
            <FormInput
              props={{
                name: 'emergencyContactNumber',
                label: 'Emergency Contact Number',
                placeholder: 'e.g. +49 1000 00000000',
                value: formik.values.emergencyContactNumber,
                onBlur: formik.handleBlur,
                onChange: formik.handleChange,
              }}
              handleFocus={handleFocus}
            />
          </Grid>

          <Grid item xs={12} sm={4} md={4}>
            <FormInput
              props={{
                name: 'yearBuilt',
                label: 'Year Built',
                placeholder: 'e.g. 2000',
                type: 'number',
                inputProps: {min: 0},
                value: formik.values.yearBuilt,
                onBlur: formik.handleBlur,
                onChange: formik.handleChange,
              }}
              handleFocus={handleFocus}
            />
          </Grid>

          <Grid item xs={12} sm={4} md={4}>
            <FormInput
              props={{
                name: 'modelOfController',
                label: 'Model of Controller',
                placeholder: 'e.g. TX2000',
                value: formik.values.modelOfController,
                onBlur: formik.handleBlur,
                onChange: formik.handleChange,
              }}
              handleFocus={handleFocus}
            />
          </Grid>

          <Grid item xs={12} sm={4} md={4}>
            <FormInput
              props={{
                name: 'manufacturerOfController',
                label: 'Manufacturer of Controller',
                placeholder: 'e.g. Schneider',
                value: formik.values.manufacturerOfController,
                onBlur: formik.handleBlur,
                onChange: formik.handleChange,
              }}
              handleFocus={handleFocus}
            />
          </Grid>
        </Grid>
      </Box>
      <AutoGeneratedIdDialog
        openDialog={openDialog}
        setOpenDialog={setOpenDialog}
      />
    </PageCard>
  );
};

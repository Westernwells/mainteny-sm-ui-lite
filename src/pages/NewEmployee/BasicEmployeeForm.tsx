import {useEffect, useState} from 'react';
import {Box} from '@mui/system';
import Grid from '@mui/material/Grid';
import {FormikErrors, useFormik} from 'formik';
import * as Yup from 'yup';
import {Button, InputAdornment, Typography} from '@mui/material';
import Email from '@mui/icons-material/Email';
import PhoneIcon from '@mui/icons-material/Phone';
import {PageCard} from 'components/PageCard';
import {BasicEmployeeFormModel} from 'models/employee';
import {FormInput} from 'components/form/FormInput';
import {AddressAutoComplete} from 'components/AddressAutoComplete';
import {AutoAwesome} from '@mui/icons-material';
import {t} from 'i18next';
import {ServiceCompanyNumberType} from 'models/service-company';
import {theme} from 'theme';
import {
  useCompanyAutoNumberConfig,
  useCompanyNextNumber,
} from 'hooks/reactQuery/useCompanies';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import {UserView} from 'models/user';
import AutoGeneratedIdDialog from 'components/AutoGeneratedIdDialog';

interface Props {
  getBasicEmployeeFormErrors?: (
    val: FormikErrors<BasicEmployeeFormModel>,
  ) => void;
  getBasicEmployeeFormValues?: (val: BasicEmployeeFormModel) => void;
  initialValues?: BasicEmployeeFormModel;
  employeeResource: UserView[];
}

export const phoneValidationRE =
  /^((\\+[1-9]{1,4}[ \\-]*)|(\\([0-9]{2,3}\\)[ \\-]*)|([0-9]{2,4})[ \\-]*)*?[0-9]{3,4}?[ \\-]*[0-9]{3,4}?$/;

const validationSchema = Yup.object().shape({
  firstName: Yup.string().required('First name is required'),
  lastName: Yup.string().required('Last name is required'),
  email: Yup.string()
    .email('Enter a valid email')
    .required('Email is required'),
  team: Yup.string().matches(/^[0-9]+$/, 'Team is not valid'),
  phone: Yup.string()
    .required('Phone number is required')
    .matches(phoneValidationRE, 'Phone number is not valid'),
  address: Yup.object().required(),
});

export const BasicEmployeeForm = ({
  getBasicEmployeeFormErrors,
  getBasicEmployeeFormValues,
  initialValues,
  employeeResource,
}: Props) => {
  const formik = useFormik<BasicEmployeeFormModel>({
    initialValues: {
      firstName: initialValues?.firstName || '',
      lastName: initialValues?.lastName || '',
      phone: initialValues?.phone || '',
      address: initialValues?.address || null,
      email: initialValues?.email || '',
      employeeId: initialValues?.employeeId || '',
      team: initialValues?.team || '',
    },
    onSubmit: () => {},
    validationSchema,
  });

  useEffect(() => {
    if (getBasicEmployeeFormErrors) {
      getBasicEmployeeFormErrors(formik.errors);
    }

    if (getBasicEmployeeFormValues) {
      getBasicEmployeeFormValues(formik.values);
    }
  }, [formik]);

  const defaultProps = {
    InputLabelProps: {shrink: true},
    onChange: formik.handleChange,
    onBlur: formik.handleBlur,
  };
  const {user} = useUserSession();

  const [openDialog, setOpenDialog] = useState<boolean>(false);
  const [activeField, setActiveField] = useState<string>('');

  const handleFocus = (e: any) => {
    setActiveField(e.target.name);
  };
  const {data: companyAutoNumberConfig} = useCompanyAutoNumberConfig(
    user?.userAccount.serviceCompany.id,
  );

  const {data: companyNextNumber, refetch: refetchCompanyNumber} =
    useCompanyNextNumber(
      {
        type: ServiceCompanyNumberType.EMPLOYEE,
      },
      user?.userAccount.serviceCompany.id,
    );

  useEffect(() => {
    formik.setFieldValue('employeeId', companyNextNumber?.value);
  }, [companyNextNumber]);

  return (
    <PageCard
      headerLabel="Basic Information"
      containerStyles={{flexGrow: 1}}
      headerStyles={{mt: '0.5em'}}>
      <Box sx={{mt: '0.5em'}} component="form">
        <Grid container spacing={2}>
          <Grid item md={4}>
            <Box display="flex" gap="1em" marginBottom="1em">
              {[
                {
                  id: 'firstName',
                  name: 'firstName',
                  label: 'First Name',
                  placeholder: 'e.g. John',
                  value: formik.values.firstName,
                  helperText:
                    formik.touched.firstName && formik.errors.firstName,
                  error: !!formik.errors.firstName && formik.touched.firstName,
                  required: true,
                },
                {
                  id: 'lastName',
                  name: 'lastName',
                  label: 'Last Name',
                  placeholder: 'e.g. Meier',
                  value: formik.values.lastName,
                  helperText: formik.touched.lastName && formik.errors.lastName,
                  error: !!formik.errors.lastName && formik.touched.lastName,
                  required: true,
                },
              ].map((item, index) => (
                <FormInput
                  key={index}
                  props={{
                    ...item,
                    ...defaultProps,
                  }}
                />
              ))}
            </Box>
            <Box display="flex" gap="1em" marginBottom="1em">
              <AddressAutoComplete
                initialValue={formik.values.address?.fullName || ''}
                inputError={
                  formik.errors.address && formik.touched.address
                    ? formik.errors.address
                    : ''
                }
                handleBlur={formik.handleBlur}
                textFieldProps={{
                  InputLabelProps: {shrink: true},
                  placeholder: 'e.g. Karl-Liebknecht-Str. 32, 10178 Berlin',
                  required: true,
                }}
                getAddress={(address) =>
                  formik.setFieldValue('address', address)
                }
              />
            </Box>
          </Grid>
          <Grid item md={8}>
            <Box display="flex" gap="1em" marginBottom="1em">
              {[
                {
                  id: 'phone',
                  name: 'phone',
                  label: 'Phone',
                  placeholder: 'e.g. +49 173 12345678',
                  value: formik.values.phone,
                  InputProps: {
                    startAdornment: (
                      <InputAdornment position="start"> + </InputAdornment>
                    ),
                    endAdornment: (
                      <InputAdornment position="end">
                        <PhoneIcon />
                      </InputAdornment>
                    ),
                  },
                  helperText: formik.touched.phone && formik.errors.phone,
                  error: !!formik.errors.phone && formik.touched.phone,
                  required: true,
                },
                {
                  id: 'email',
                  name: 'email',
                  label: 'Email',
                  placeholder: 'e.g johndoe@example.com',
                  InputProps: {
                    endAdornment: (
                      <InputAdornment position="end">
                        <Email />
                      </InputAdornment>
                    ),
                  },
                  value: formik.values.email,
                  helperText: formik.touched.email && formik.errors.email,
                  error: !!formik.errors.email && formik.touched.email,
                  required: true,
                },
              ].map((item, index) => (
                <FormInput
                  key={index}
                  props={{
                    ...item,
                    ...defaultProps,
                  }}
                />
              ))}
            </Box>
            <Box display="flex" gap="1em">
              {[
                {
                  id: 'team',
                  name: 'team',
                  label: 'Team',
                  placeholder: 'e.g 2',
                  value: formik.values.team,
                  helperText: formik.touched.team && formik.errors.team,
                  error: !!formik.errors.team && formik.touched.team,
                },
                {
                  id: 'employeeId',
                  name: 'employeeId',
                  label: 'Employee ID',
                  placeholder: 'e.g. 00001',
                  value: formik.values.employeeId,
                  helperText:
                    formik.touched.employeeId && formik.errors.employeeId,
                  error:
                    !!formik.errors.employeeId && formik.touched.employeeId,
                },
              ].map((item, index) => (
                <FormInput
                  key={index}
                  props={{
                    ...item,
                    ...defaultProps,
                  }}
                  handleFocus={handleFocus}
                />
              ))}
            </Box>
            {(activeField === 'employeeId' || formik.touched.employeeId) &&
              formik.values.employeeId &&
              employeeResource.filter(
                (item) => item.userData.number === formik.values.employeeId,
              ).length > 0 && (
                <Typography
                  color="error"
                  fontSize="0.75rem"
                  letterSpacing="0.03em"
                  padding="0.45em 0.65em">
                  {t('This ID is already taken. Please enter a different one.')}
                </Typography>
              )}
            {activeField === 'employeeId' &&
            !formik.values.employeeId &&
            companyAutoNumberConfig?.configRecords.find(
              (item) => item.type === ServiceCompanyNumberType.EMPLOYEE,
            )?.enabled ? (
              <Box
                sx={{
                  borderRadius: '4px',
                  boxShadow: '0px 9px 46px 8px #0000001F',
                  marginTop: '0.2em',
                  width: '49%',
                  float: 'right',
                }}>
                <Button
                  sx={{
                    display: 'flex',
                    flexDirection: 'column',
                    justifyContent: 'flex-start',
                    textAlign: 'left',
                    alignItems: 'flex-start',
                    width: '100%',
                    padding: '1em 2em',
                  }}
                  onClick={() => {
                    refetchCompanyNumber();
                    formik.setFieldValue(
                      'employeeId',
                      companyNextNumber?.value,
                    );
                  }}>
                  <Box
                    sx={{
                      display: 'flex',
                      flexDirection: 'row',
                      alignItems: 'center',
                      paddingBottom: '0.6em',
                    }}>
                    <AutoAwesome />
                    <Typography variant="subtitle2" sx={{paddingLeft: '0.5em'}}>
                      {t('Generate ID')}
                    </Typography>
                  </Box>

                  <Typography
                    variant="body2"
                    color={theme.palette.text.secondary}>
                    {t('Customizable in Settings')}
                  </Typography>
                </Button>
              </Box>
            ) : (
              activeField === 'employeeId' &&
              !formik.values.employeeId &&
              !companyAutoNumberConfig?.configRecords.find(
                (item) => item.type === ServiceCompanyNumberType.EMPLOYEE,
              )?.enabled && (
                <Box
                  sx={{
                    borderRadius: '4px',
                    boxShadow: '0px 9px 46px 8px #0000001F',
                    marginTop: '0.2em',
                    width: '49%',
                    float: 'right',
                  }}>
                  <Button
                    sx={{
                      display: 'flex',
                      flexDirection: 'column',
                      justifyContent: 'flex-start',
                      textAlign: 'left',
                      alignItems: 'flex-start',
                      width: '100%',
                      padding: '1em 2em',
                    }}
                    onClick={() => setOpenDialog(true)}>
                    <Box
                      sx={{
                        display: 'flex',
                        flexDirection: 'row',
                        alignItems: 'center',
                        paddingBottom: '0.6em',
                      }}>
                      <AutoAwesome />
                      <Typography
                        variant="subtitle2"
                        sx={{paddingLeft: '0.5em'}}>
                        {t('Enable Automatic ID Generation')}
                      </Typography>
                    </Box>

                    <Typography
                      variant="body2"
                      color={theme.palette.text.secondary}>
                      {t('Allows for easier number input')}
                    </Typography>
                  </Button>
                </Box>
              )
            )}
          </Grid>
        </Grid>
      </Box>
      <AutoGeneratedIdDialog
        openDialog={openDialog}
        setOpenDialog={setOpenDialog}
      />
    </PageCard>
  );
};

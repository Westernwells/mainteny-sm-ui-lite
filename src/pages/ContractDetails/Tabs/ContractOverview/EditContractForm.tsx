import {FC, useEffect, useState} from 'react';
import {useTranslation} from 'react-i18next';
import InputAdornment from '@mui/material/InputAdornment';
import Grid from '@mui/material/Grid';
import {FormInput} from 'components/form/FormInput';
import AutoGeneratedIdDialog from 'components/AutoGeneratedIdDialog';
import {
  ContractOrderField,
  ContractUpdateRequest,
  ContractView,
} from 'models/contract';
import {ServiceCompanyNumberType} from 'models/service-company';
import {Order} from 'models/misc';
import {FormikProps} from 'formik';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import {useQueryContract} from 'hooks/reactQuery/useContract';
import {FormSelect} from 'components/form/FormSelect';
import {getCurrencySymbol} from 'utils/currency';
import {invoiceCycle} from 'utils/contract-utils';
import {DatePicker} from 'components/DatePicker';
import {format, getMonth, getYear} from 'date-fns';
import {toDate} from 'utils/datetime';
import {createEmptyResource} from 'utils/paging-utils';
import AutoEditDropdown from 'components/AutoEditDropdown';

interface Props {
  formik: FormikProps<ContractUpdateRequest>;
  currency: string;
}

const EditContractForm: FC<Props> = ({formik, currency}) => {
  const {t} = useTranslation();
  const {user} = useUserSession();

  const [openNewDialog, setOpenNewDialog] = useState<boolean>(false);
  const [activeField, setActiveField] = useState<string>('');

  const [initId, setInitId] = useState(formik.values.externalId);

  const {data: contractResource = createEmptyResource<ContractView>(50)} =
    useQueryContract(
      {
        pageIndex: 0,
        pageSize: 50,
        query: formik.values?.externalId ?? '',
        order: Order.DESC,
        orderBy: ContractOrderField.CREATED_TIME,
      },
      {keepPreviousData: true},
    );

  const currencySymbol = getCurrencySymbol[currency];

  const handleFocus = (e: any) => {
    setActiveField(e.target.name);
  };

  const handleBlur = (e: any) => {
    setTimeout(() => {
      setActiveField(e.target.name);
      formik.handleBlur(e);
    }, 100);
  };

  useEffect(() => {
    setInitId(formik.values.externalId);
  }, []);

  const externalIdInputProps = {
    size: 'small',
    placeholder: 'e.g 1234',
    label: 'Contract Number',
    name: 'externalId',
    value: formik.values.externalId,
    helperText: formik.touched.externalId && formik.errors.externalId,
    error: !!formik.errors.externalId && formik.touched.externalId,
    onChange: formik.handleChange,
    onBlur: handleBlur,
  };

  return (
    <Grid container spacing={2} sx={{mt: '0.5em'}}>
      <Grid item md={6}>
        <FormSelect
          labelId="typeSelect-label"
          label="Contract name"
          options={(
            user?.userAccount?.serviceCompany?.settings?.contractNameTypes ?? []
          ).map((item) => ({
            label: item.name,
            value: item.name,
          }))}
          selectProps={{
            id: 'typeSelect',
            value: formik.values.name,
            onChange: formik.handleChange,
            error: !!formik.errors.name,
            placeholder: 'Select contract name',
            name: 'name',
          }}
          required
        />
      </Grid>
      <Grid item md={6}>
        <AutoEditDropdown
          activeField={activeField}
          initId={initId}
          formik={formik}
          setOpenNewDialog={setOpenNewDialog}
          numberType={ServiceCompanyNumberType.CONTRACT}
          serviceTypeResource={contractResource.data}
          handleFocus={handleFocus}
          fieldProps={externalIdInputProps}
        />
      </Grid>

      <Grid item md={6}>
        <FormInput
          props={{
            placeholder: 'Enter number of visits',
            label: 'Number of Visits',
            name: 'visitsNumber',
            type: 'number',
            value: Number(formik.values.visitsNumber).toString(),
            onBlur: formik.handleBlur,
            onChange: formik.handleChange,
          }}
        />
      </Grid>
      <Grid item md={6}>
        <FormInput
          props={{
            placeholder: t('Enter price/year (in {{currencySymbol}})', {
              currencySymbol,
            }),
            label: t(`Price/Year (excl. VAT, in {{currencySymbol}})`, {
              currencySymbol,
            }),
            name: 'price',
            type: 'number',
            value: Number(formik.values.price).toString(),
            onBlur: formik.handleBlur,
            onChange: formik.handleChange,
            required: true,
            InputProps: {
              startAdornment: (
                <InputAdornment position="start" color="text.primary">
                  {currencySymbol}
                </InputAdornment>
              ),
            },
          }}
        />
      </Grid>
      <Grid item md={6}>
        <FormInput
          props={{
            placeholder: t(`Enter spending limit (in {{currencySymbol}})`, {
              currencySymbol,
            }),
            label: t(`Spending Limit (in {{currencySymbol}})`, {
              currencySymbol,
            }),
            name: 'spendingLimit',
            value: Number(formik.values.spendingLimit).toString(),
            onBlur: formik.handleBlur,
            onChange: formik.handleChange,
            InputProps: {
              startAdornment: (
                <InputAdornment position="start" color="text.primary">
                  {currencySymbol}
                </InputAdornment>
              ),
            },
          }}
        />
      </Grid>
      <Grid item md={6}>
        <FormInput
          props={{
            placeholder: 'Enter renewal period (in months)',
            label: 'Renewal Period (in months)',
            name: 'renewalTerms',
            type: 'number',
            value: formik.values.renewalTerms,
            onBlur: formik.handleBlur,
            onChange: formik.handleChange,
            error: !!formik.errors.renewalTerms,
            helperText: formik.errors.renewalTerms,
            inputProps: {
              min: 0,
              max: 12,
            },
          }}
        />
      </Grid>
      <Grid item md={6}>
        <FormSelect
          labelId="invoiceDueSelect-label"
          label="Invoice Cycle"
          options={Object.keys(invoiceCycle).map((key) => ({
            label: invoiceCycle[key],
            value: key,
          }))}
          selectProps={{
            id: 'invoiceCycleSelect',
            value:
              formik.values.invoiceCycle >= 0
                ? t(formik.values.invoiceCycle.toString())
                : '',
            onChange: formik.handleChange,
            error: !!formik.errors.invoiceCycle,
            name: 'invoiceCycle',
          }}
          required
        />
      </Grid>

      <Grid item md={6}>
        <FormInput
          props={{
            placeholder: 'Enter payment due (in days)',
            label: 'Payment Due (in days)',
            name: 'invoiceDueDays',
            type: 'number',
            value: Number(formik.values.invoiceDueDays).toString(),
            onBlur: formik.handleBlur,
            onChange: formik.handleChange,
            error: !!formik.errors.invoiceDueDays,
          }}
        />
      </Grid>

      <Grid item md={6}>
        <FormInput
          props={{
            placeholder: 'Enter yearly price adjustment',
            label: 'Yearly Price Adjustment (%)',
            name: 'annualPriceAdjustmentPercentage',
            type: 'number',
            value: Number(
              formik.values.annualPriceAdjustmentPercentage,
            ).toString(),
            onBlur: formik.handleBlur,
            onChange: formik.handleChange,
            error: !!formik.errors.annualPriceAdjustmentPercentage,
          }}
        />
      </Grid>

      <Grid item md={6}>
        <FormInput
          props={{
            placeholder: 'Enter discount',
            label: 'Discount (first 14 days)',
            name: 'discounts',
            type: 'number',
            value: Number(formik.values.discounts).toString(),
            onBlur: formik.handleBlur,
            onChange: formik.handleChange,
            error: !!formik.errors.discounts,
            helperText: formik.errors.discounts,
            InputProps: {
              endAdornment: (
                <InputAdornment position="end" color="text.primary">
                  %
                </InputAdornment>
              ),
            },
          }}
        />
      </Grid>

      <Grid item md={6}>
        <FormInput
          props={{
            placeholder: 'Enter notice period',
            label: 'Notice Period (in months)',
            name: 'noticePeriodInMonth',
            type: 'number',
            value: Number(formik.values.noticePeriodInMonth).toString(),
            onBlur: formik.handleBlur,
            onChange: formik.handleChange,
            error: !!formik.errors.noticePeriodInMonth,
          }}
        />
      </Grid>

      <Grid item md={6}>
        <DatePicker
          defaultDate={
            formik.values.firstMaintenance &&
            new Date(
              formik.values.firstMaintenance?.year,
              formik.values.firstMaintenance?.month,
            )
          }
          dateFormat="MMM yyyy"
          disableMask
          containerStyles={{mr: '1em', width: '100%'}}
          getSelectedDate={(date) => {
            if (date) {
              formik.setValues({
                ...formik.values,
                firstMaintenance: {
                  year: getYear(date),
                  month: getMonth(date),
                },
              });
            }
          }}
          textFieldProps={{
            label: t('First Maintenance Visit'),
            name: 'firstMaintenance',
            helperText:
              formik.errors.firstMaintenance && formik.touched.firstMaintenance
                ? formik.errors.firstMaintenance
                : '',
            error: !!(
              formik.touched.firstMaintenance && formik.errors.firstMaintenance
            ),
            sx: {width: '100%'},
            onBlur: formik.handleBlur,
          }}
        />
      </Grid>

      <Grid item md={6}>
        <DatePicker
          defaultDate={
            formik.values.firstInvoiceDate
              ? toDate(formik.values.firstInvoiceDate)
              : null
          }
          containerStyles={{mr: '1em', width: '100%'}}
          getSelectedDate={(date) => {
            if (date) {
              formik.setValues({
                ...formik.values,
                firstInvoiceDate: format(date, 'yyyy-MM-dd'),
              });
            }
          }}
          disableMask
          textFieldProps={{
            label: t('First Invoice'),
            name: 'firstInvoiceDate',
            helperText:
              formik.errors.firstInvoiceDate && formik.touched.firstInvoiceDate
                ? formik.errors.firstInvoiceDate
                : '',
            error: !!(
              formik.touched.firstInvoiceDate && formik.errors.firstInvoiceDate
            ),
            sx: {width: '100%'},
            onBlur: formik.handleBlur,
          }}
        />
      </Grid>
      <AutoGeneratedIdDialog
        openDialog={openNewDialog}
        setOpenDialog={setOpenNewDialog}
      />
    </Grid>
  );
};

export default EditContractForm;

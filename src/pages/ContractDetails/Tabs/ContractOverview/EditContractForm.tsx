import {FC, useEffect, useState} from 'react';
import {useTranslation} from 'react-i18next';
import InputAdornment from '@mui/material/InputAdornment';
import Grid from '@mui/material/Grid';
import {FormInput} from 'components/form/FormInput';
import {
  ContractBasicInfoFormModel,
  ContractUpdateRequest,
} from 'models/contract';
import {ServiceCompanyNumberType} from 'models/service-company';
import {FormikProps} from 'formik';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import {getCurrencySymbol} from 'utils/currency';
import {DatePicker} from 'components/DatePicker';
import {format} from 'date-fns';
import {toDate} from 'utils/datetime';
import {Box, Typography} from '@mui/material';
import {Switch} from 'components/Switch';
import Alert from '@mui/material/Alert';
import {useFormatDate} from 'hooks/useFormatDate';
import {ComboBox} from 'components/ComboBox';
import {
  useCompanyAutoNumberConfig,
  useCompanyNextNumber,
} from 'hooks/reactQuery/useCompanies';
import {T} from 'utils/i18n-utils';
import AutoGeneratedIdDialog from 'components/AutoGeneratedIdDialog';
import ContractName from 'components/ContractName';

interface Props {
  formik: FormikProps<ContractUpdateRequest>;
  currency: string;
  initialValues: ContractUpdateRequest;
}

const EditContractForm: FC<Props> = ({formik, currency, initialValues}) => {
  const {t} = useTranslation();
  const {user} = useUserSession();
  const formatDate = useFormatDate();
  const [openNewDialog, setOpenNewDialog] = useState<boolean>(false);
  const {data: companyAutoNumberConfig} = useCompanyAutoNumberConfig(
    user?.userAccount.serviceCompany.id,
  );

  const {data: companyNextNumber} = useCompanyNextNumber(
    {
      type: ServiceCompanyNumberType.CONTRACT,
    },
    user?.userAccount.serviceCompany.id,
  );

  const generateNextNumber = () => {
    formik.setFieldValue('externalId', companyNextNumber?.value);
  };

  useEffect(() => {
    formik.setValues(initialValues);
  }, [initialValues]);

  const currencySymbol = getCurrencySymbol[currency];

  return (
    <Grid container spacing={1.8} sx={{mt: '0.1em'}}>
      {!formik.values.autoRenewalCancelled && (
        <Grid item md={12}>
          <Alert severity="error">
            {t('This contract is ending on {{endDate}}', {
              endDate: formatDate(formik.values.endDate),
            })}
          </Alert>
        </Grid>
      )}

      <Grid item md={12} mb={0.5}>
        <Typography variant="body2" color="textSecondary">
          {t('General Information')}
        </Typography>
      </Grid>

      <Grid item md={3}>
        <ContractName
          formik={
            formik as FormikProps<
              ContractBasicInfoFormModel | ContractUpdateRequest
            >
          }
        />
      </Grid>

      <Grid item md={3}>
        <DatePicker
          defaultDate={
            formik.values.startDate ? toDate(formik.values.startDate) : null
          }
          containerStyles={{mr: '1em', width: '100%'}}
          getSelectedDate={(date) => {
            if (date) {
              formik.setValues({
                ...formik.values,
                startDate: format(date, 'yyyy-MM-dd'),
              });
            }
          }}
          disableMask
          textFieldProps={{
            label: t('Contract Start Date'),
            name: 'startDate',
            helperText:
              formik.errors.startDate && formik.touched.startDate
                ? formik.errors.startDate
                : '',
            error: !!(formik.touched.startDate && formik.errors.startDate),
            sx: {width: '100%'},
            onBlur: formik.handleBlur,
          }}
        />
      </Grid>

      <Grid item md={3}>
        <FormInput
          onValueChange={(values) => {
            formik.setFieldValue(values.name as string, values.value);
          }}
          inputType="currency"
          numericFormatProps={{disabled: true}}
          props={{
            placeholder: t('Enter value/year (in {{currencySymbol}})', {
              currencySymbol,
            }),
            label: t(`Contract value/Year`),
            name: 'price',
            type: 'number',
            value: Number(formik.values.price).toString(),
            onBlur: formik.handleBlur,
            required: true,
            InputProps: {
              startAdornment: (
                <InputAdornment position="start" color="text.primary">
                  {currencySymbol}
                </InputAdornment>
              ),
            },
          }}
        />
      </Grid>

      <Grid item md={3}>
        <Box sx={{display: 'flex', alignItems: 'center'}}>
          <Switch
            value={formik.values.autoRenewalCancelled}
            onChanged={(value) =>
              formik.setFieldValue('autoRenewalCancelled', value)
            }
          />
          <Typography flex="0 0 70%" height="1.5em">
            {T('Auto-renewal')}
          </Typography>
        </Box>
      </Grid>

      <Grid item md={3}>
        <ComboBox
          options={[]}
          initialValue={
            formik.values.externalId
              ? {
                  label: formik.values.externalId,
                  value: formik.values.externalId,
                }
              : null
          }
          initialQuery={formik.values.externalId}
          getValue={(item) => {
            formik.setFieldValue('externalId', item?.value);
          }}
          autoIdProps={{
            handleAction: companyAutoNumberConfig?.configRecords.find(
              (item: any) =>
                item.type === ServiceCompanyNumberType.PROPERTY_OWNER,
            )?.enabled
              ? () => {
                  generateNextNumber();
                }
              : () => {
                  setOpenNewDialog(true);
                },
            isEnabled: companyAutoNumberConfig?.configRecords.find(
              (item: any) => item.type === ServiceCompanyNumberType.CONTRACT,
            )?.enabled,
          }}
          textFieldProps={{
            size: 'small',
            placeholder: 'e.g 1234',
            label: 'Contract ID',
            name: 'externalId',
            value: formik.values.externalId,
            helperText: formik.touched.externalId && formik.errors.externalId,
            error: !!formik.errors.externalId && formik.touched.externalId,
            onChange: formik.handleChange,
            onBlur: formik.handleBlur,
          }}
        />
      </Grid>

      <Grid item md={3}>
        <DatePicker
          defaultDate={
            formik.values.endDate ? toDate(formik.values.endDate) : null
          }
          containerStyles={{mr: '1em', width: '100%'}}
          getSelectedDate={(date) => {
            if (date) {
              formik.setValues({
                ...formik.values,
                endDate: format(date, 'yyyy-MM-dd'),
              });
            }
          }}
          disableMask
          textFieldProps={{
            label: t('Contract End'),
            name: 'endDate',
            helperText:
              formik.errors.endDate && formik.touched.endDate
                ? formik.errors.endDate
                : '',
            error: !!(formik.touched.endDate && formik.errors.endDate),
            sx: {width: '100%'},
            onBlur: formik.handleBlur,
          }}
        />
      </Grid>

      <Grid item md={3}>
        <FormInput
          props={{
            placeholder: 'Enter yearly price adjustment',
            label: 'Price Adjustment/Year',
            name: 'annualPriceAdjustmentPercentage',
            type: 'number',
            value: Number(
              formik.values.annualPriceAdjustmentPercentage,
            ).toString(),
            onBlur: formik.handleBlur,
            onChange: formik.handleChange,
            error: !!formik.errors.annualPriceAdjustmentPercentage,
            InputProps: {
              endAdornment: (
                <InputAdornment position="end" color="text.primary">
                  %
                </InputAdornment>
              ),
            },
          }}
        />
      </Grid>

      <Grid item md={3}>
        <FormInput
          props={{
            placeholder: 'Renewal period (in months)',
            label: 'Renewal Period (in months)',
            name: 'renewalTerms',
            type: 'number',
            value: formik.values.renewalTerms,
            onBlur: formik.handleBlur,
            onChange: formik.handleChange,
            error: !!formik.errors.renewalTerms,
            helperText: formik.errors.renewalTerms,
            inputProps: {
              min: 0,
              max: 12,
            },
            disabled: !formik.values.autoRenewalCancelled,
          }}
        />
      </Grid>

      <Grid item md={3}>
        <FormInput
          props={{
            placeholder: 'Number of Units',
            label: 'Number of Units',
            name: 'visitsNumber',
            type: 'number',
            value: Number(formik.values.numberOfUnits).toString(),
            disabled: true,
          }}
        />
      </Grid>

      <Grid md={6} />

      <Grid item md={3}>
        <FormInput
          props={{
            placeholder: 'Enter notice period',
            label: 'Notice Period (in months)',
            name: 'noticePeriodInMonth',
            type: 'number',
            value: Number(formik.values.noticePeriodInMonth).toString(),
            onBlur: formik.handleBlur,
            onChange: formik.handleChange,
            inputProps: {
              min: 0,
              max: 12,
            },
            error: !!formik.errors.noticePeriodInMonth,
          }}
        />
      </Grid>
      <AutoGeneratedIdDialog
        openDialog={openNewDialog}
        setOpenDialog={setOpenNewDialog}
      />
    </Grid>
  );
};

export default EditContractForm;

import {FormikProps} from 'formik';
import Grid from '@mui/material/Grid';
import {FormInput} from 'components/form/FormInput';
import {AddressAutoComplete} from 'components/AddressAutoComplete';
import {ArticleSupplierView, UpdateArticleSupplierRecord} from 'models/article';
import {
  useCompanyAutoNumberConfig,
  useCompanyNextNumber,
} from 'hooks/reactQuery/useCompanies';
import {ServiceCompanyNumberType} from 'models/service-company';
import {useState, useEffect} from 'react';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import AutoGeneratedIdDialog from 'components/AutoGeneratedIdDialog';
import {Box, Typography, useTheme} from '@mui/material';
import {Button} from 'components/Button';
import {AutoAwesome} from '@mui/icons-material';
import {t} from 'i18next';
import {useQueryArticleSuppliers} from 'hooks/reactQuery/useArticle';
import {createEmptyResource, makePage} from 'utils/paging-utils';

export const EditBasicInfoForm = ({
  formik,
}: {
  formik: FormikProps<UpdateArticleSupplierRecord>;
}) => {
  const defaultProps = {
    InputLabelProps: {shrink: true},
    onChange: formik.handleChange,
    onBlur: formik.handleBlur,
  };

  const theme = useTheme();
  const {user} = useUserSession();

  const [initId, setInitId] = useState(formik.values.externalId);

  const [openNewDialog, setOpenNewDialog] = useState<boolean>(false);
  const [activeField, setActiveField] = useState<string>('');

  const handleFocus = (e: any) => {
    setActiveField(e.target.name);
  };

  const {
    data: articleSupplierResource = createEmptyResource<ArticleSupplierView>(
      25,
    ),
  } = useQueryArticleSuppliers(makePage(0, 50), formik.values.externalId, {
    keepPreviousData: true,
  });

  const {data: companyAutoNumberConfig} = useCompanyAutoNumberConfig(
    user?.userAccount.serviceCompany.id,
  );

  const {data: companyNextNumber, refetch: refetchCompanyNumber} =
    useCompanyNextNumber(
      {
        type: ServiceCompanyNumberType.ARTICLE_SUPPLIER,
      },
      user?.userAccount.serviceCompany.id,
    );

  useEffect(() => {
    setInitId(formik.values.externalId);
  }, []);

  return (
    <Grid container component="form" spacing={3} pt={2}>
      <Grid item xs={6}>
        <FormInput
          props={{
            label: 'Name',
            name: 'name',
            placeholder: 'e.g. Flat cable, 16G0.75+2x(2x0.5)',
            type: 'text',
            required: true,
            value: formik.values.name,
            helperText: formik.touched.name && formik.errors.name,
            error: !!(formik.touched.name && formik.errors.name),
            ...defaultProps,
          }}
          handleFocus={handleFocus}
        />
      </Grid>

      <Grid item xs={6}>
        <FormInput
          props={{
            label: 'ID',
            name: 'externalId',
            placeholder: 'e.g. 000001',
            type: 'text',
            required: true,
            value: formik.values.externalId,
            helperText: formik.touched.externalId && formik.errors.externalId,
            error: !!(formik.touched.externalId && formik.errors.externalId),
            ...defaultProps,
          }}
          handleFocus={handleFocus}
        />

        {(activeField === 'externalId' || formik.touched.externalId) &&
          formik.values.externalId &&
          initId !== formik.values.externalId &&
          articleSupplierResource?.data.filter(
            (item) => item.externalId === formik.values.externalId,
          ).length > 0 && (
            <Typography
              color="error"
              fontSize="0.75rem"
              letterSpacing="0.03em"
              padding="0.45em 0.65em">
              {t('This ID is already taken. Please enter a different one.')}
            </Typography>
          )}
        {activeField === 'externalId' &&
        !formik.values.externalId &&
        companyAutoNumberConfig?.configRecords.find(
          (item) => item.type === ServiceCompanyNumberType.ARTICLE_SUPPLIER,
        )?.enabled ? (
          <Box
            sx={{
              borderRadius: '4px',
              boxShadow: '0px 9px 46px 8px #0000001F',
              marginTop: '0.2em',
            }}>
            <Button
              buttonProps={{
                onClick: () => {
                  refetchCompanyNumber();
                  formik.setFieldValue('externalId', companyNextNumber?.value);
                },
                sx: {
                  display: 'flex',
                  flexDirection: 'column',
                  justifyContent: 'flex-start',
                  textAlign: 'left',
                  alignItems: 'flex-start',
                  width: '100%',
                  padding: '1em 2em',
                },
              }}>
              <Box
                sx={{
                  display: 'flex',
                  flexDirection: 'row',
                  alignItems: 'center',
                  paddingBottom: '0.6em',
                }}>
                <AutoAwesome />
                <Typography variant="subtitle2" sx={{paddingLeft: '0.5em'}}>
                  {t('Generate ID')}
                </Typography>
              </Box>

              <Typography variant="body2" color={theme.palette.text.secondary}>
                {t('Customizable in Settings')}
              </Typography>
            </Button>
          </Box>
        ) : (
          activeField === 'externalId' &&
          !formik.values.externalId &&
          !companyAutoNumberConfig?.configRecords.find(
            (item) => item.type === ServiceCompanyNumberType.ARTICLE_SUPPLIER,
          )?.enabled && (
            <Box
              sx={{
                borderRadius: '4px',
                boxShadow: '0px 9px 46px 8px #0000001F',
                marginTop: '0.2em',
              }}>
              <Button
                buttonProps={{
                  size: 'medium',
                  variant: 'outlined',
                  onClick: () => setOpenNewDialog(true),
                  sx: {
                    display: 'flex',
                    flexDirection: 'column',
                    justifyContent: 'flex-start',
                    textAlign: 'left',
                    alignItems: 'flex-start',
                    width: '100%',
                    padding: '1em 2em',
                  },
                }}>
                <Box
                  sx={{
                    display: 'flex',
                    flexDirection: 'row',
                    alignItems: 'center',
                    paddingBottom: '0.6em',
                  }}>
                  <AutoAwesome />
                  <Typography variant="subtitle2" sx={{paddingLeft: '0.5em'}}>
                    {t('Enable Automatic ID Generation')}
                  </Typography>
                </Box>

                <Typography
                  variant="body2"
                  color={theme.palette.text.secondary}>
                  {t('Allows for easier number input')}
                </Typography>
              </Button>
            </Box>
          )
        )}
      </Grid>

      <Grid item xs={6}>
        <FormInput
          props={{
            label: 'Email',
            name: 'email',
            placeholder: 'e.g johndoe@example.com',
            required: true,
            value: formik.values.email,
            helperText: formik.touched.email && formik.errors.email,
            error: !!(formik.touched.email && formik.errors.email),
            ...defaultProps,
          }}
          handleFocus={handleFocus}
        />
      </Grid>

      <Grid item xs={6}>
        <FormInput
          props={{
            label: 'Phone',
            name: 'phone',
            placeholder: 'e.g. 49 173 12345678',
            type: 'text',
            required: true,
            value: formik.values.phone,
            helperText: formik.touched.phone && formik.errors.phone,
            error: !!(formik.touched.phone && formik.errors.phone),
            ...defaultProps,
          }}
          handleFocus={handleFocus}
        />
      </Grid>

      <Grid item xs={6}>
        <AddressAutoComplete
          initialValue={formik.values.address?.fullName || ''}
          inputError={
            formik.errors.address?.fullName && formik.touched.address
              ? formik.errors.address.fullName
              : ''
          }
          handleBlur={formik.handleBlur}
          textFieldProps={{
            InputLabelProps: {shrink: true},
            placeholder: 'e.g. Karl-Liebknecht-Str. 32, 10178 Berlin',
            required: true,
          }}
          getAddress={(address) => formik.setFieldValue('address', address)}
        />
      </Grid>

      <Grid item xs={6}>
        <FormInput
          props={{
            label: 'Website',
            name: 'url',
            placeholder: 'e.g. www.web.com',
            type: 'text',
            value: formik.values.url,
            helperText: formik.touched.url && formik.errors.url,
            error: !!(formik.touched.url && formik.errors.url),
            ...defaultProps,
          }}
          handleFocus={handleFocus}
        />
      </Grid>

      <Grid item xs={6}>
        <FormInput
          props={{
            label: 'Category',
            name: 'category',
            placeholder: 'e.g. Cable',
            type: 'text',
            value: formik.values.category,
            helperText: formik.touched.category && formik.errors.category,
            error: !!(formik.touched.category && formik.errors.category),
            ...defaultProps,
          }}
          handleFocus={handleFocus}
        />
      </Grid>

      <AutoGeneratedIdDialog
        openDialog={openNewDialog}
        setOpenDialog={setOpenNewDialog}
      />
    </Grid>
  );
};

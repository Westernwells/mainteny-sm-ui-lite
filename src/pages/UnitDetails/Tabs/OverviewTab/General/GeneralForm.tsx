import Grid from '@mui/material/Grid';
import {ComboBox} from 'components/ComboBox';
import {FormInput} from 'components/form/FormInput';
import {useCacheValues} from 'hooks/reactQuery/useElevator';
import {ElevatorCategory, ElevatorStatus} from 'models/elevator';
import {CacheTypes} from 'models/misc';
import {GeneralFormModel} from 'models/unitForm';
import {useState} from 'react';
import {createEmptyResource} from 'utils/paging-utils';
import {convertToText} from 'utils/utils';
import {useTranslation} from 'react-i18next';
import {ServiceCompanyNumberType} from 'models/service-company';
import AutoGeneratedIdDialog from 'components/AutoGeneratedIdDialog';
import InputAdornment from '@mui/material/InputAdornment';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import {
  useCompanyAutoNumberConfig,
  useCompanyNextNumber,
} from 'hooks/reactQuery/useCompanies';
import {ComboBoxNew} from 'components/ComboBoxNew';
import {UseFormWatch, UseFormRegister, UseFormSetValue} from 'react-hook-form';
import FormControl from '@mui/material/FormControl';
import Select from '@mui/material/Select';
import MenuItem from '@mui/material/MenuItem';
import InputLabel from '@mui/material/InputLabel';
import {getCurrencySymbol, useCurrentCurrency} from 'utils/currency';
import sortOptions from 'utils/sortOptions';

interface Props {
  register: UseFormRegister<GeneralFormModel>;
  watch: UseFormWatch<GeneralFormModel>;
  setValue: UseFormSetValue<GeneralFormModel>;
}

export const EditUnitDetailsForm = ({register, watch, setValue}: Props) => {
  const {t} = useTranslation();
  const {user} = useUserSession();
  const currentCurrency = useCurrentCurrency();
  const [modelQuery, setModelQuery] = useState('');
  const [openDialog, setOpenDialog] = useState<boolean>(false);

  const {data: elevatorModelsResource = createEmptyResource<string>()} =
    useCacheValues(
      {
        pageIndex: 0,
        pageSize: 10,
        query: modelQuery,
      },
      CacheTypes.ELEVATOR_MODEL,
    );

  const {data: companyAutoNumberConfig} = useCompanyAutoNumberConfig(
    user?.userAccount.serviceCompany.id,
  );

  const {data: companyNextNumber, refetch} = useCompanyNextNumber(
    {
      type: ServiceCompanyNumberType.ELEVATOR,
    },
    user?.userAccount.serviceCompany.id,
  );

  const generateNextNumber = async () => {
    if (!companyNextNumber?.value) {
      const {data: refetchedCompanyNextNumber} = await refetch();
      return setValue('externalId', refetchedCompanyNextNumber?.value);
    }
    setValue('externalId', companyNextNumber?.value);
  };

  return (
    <Grid container spacing={2} component="form">
      <Grid item md={6}>
        <ComboBoxNew
          options={Object.keys(ElevatorCategory)
            .map((item) => ({
              label: t(convertToText(item)),
              value: convertToText(item),
            }))
            .sort(sortOptions)}
          initialValue={
            watch('category')
              ? {
                  label: t(convertToText(watch('category') as string)),
                  value: watch('category') as string,
                }
              : null
          }
          initialQuery={watch('category')}
          getValue={(item) => setValue('category', item?.value)}
          textFieldProps={{
            label: 'Unit Category',
            placeholder: t('e.g Escalator'),
            required: true,
            defaultValue: watch('category'),
            ...register('category'),
          }}
        />
      </Grid>

      <Grid item md={6}>
        <ComboBoxNew
          options={elevatorModelsResource.data.map((item) => ({
            label: item,
            value: item,
          }))}
          getValue={(item) => {
            setValue('model', item?.value);
          }}
          initialValue={
            watch('model')
              ? {
                  label: watch('model') as string,
                  value: watch('model') as string,
                }
              : null
          }
          initialQuery={watch('model')}
          getQuery={(item) => setModelQuery(item || '')}
          textFieldProps={{
            name: 'model',
            label: t('Model'),
            placeholder: t('e.g. S2000'),
          }}
        />
      </Grid>

      <Grid item md={6}>
        <FormInput
          fieldProps={{
            placeholder: 'E.g. Thyssenkrupp, schindler',
            label: 'Manufacturer',
            ...register('manufacturer'),
          }}
        />
      </Grid>

      <Grid item md={6}>
        <FormInput
          fieldProps={{
            placeholder: 'Fabric number',
            label: 'Serial Number',
            ...register('serialNumber'),
          }}
        />
      </Grid>

      <Grid item md={6}>
        <ComboBox
          options={[]}
          initialValue={
            watch('externalId')
              ? {
                  label: watch('externalId') as string,
                  value: watch('externalId') as string,
                }
              : null
          }
          initialQuery={watch('externalId')}
          getValue={(item) => {
            setValue('externalId', item?.value);
          }}
          autoIdProps={{
            handleAction: companyAutoNumberConfig?.configRecords.find(
              (item: any) => item.type === ServiceCompanyNumberType.ELEVATOR,
            )?.enabled
              ? () => {
                  generateNextNumber();
                }
              : () => {
                  setOpenDialog(true);
                },
            isEnabled: companyAutoNumberConfig?.configRecords.find(
              (item: any) => item.type === ServiceCompanyNumberType.ELEVATOR,
            )?.enabled,
          }}
          textFieldProps={{
            placeholder: 'e.g. 100001',
            label: 'Unit Number',
            name: 'externalId',
            value: watch('externalId'),
            onChange: (e) => setValue('externalId', e.target.value),
          }}
        />
      </Grid>

      <Grid item md={6}>
        <FormInput
          inputType="currency"
          fieldProps={{
            size: 'small',
            placeholder: 'e.g. 150',
            label: 'Spending Limit',
            type: 'number',
            inputProps: {
              min: 0,
              defaultValue: watch('spendingLimit'),
              ...register('spendingLimit'),
            },
            InputProps: {
              sx: {alignItems: 'center'},
              startAdornment: (
                <InputAdornment position="end" sx={{marginRight: '0.3rem'}}>
                  {getCurrencySymbol[currentCurrency.code]}
                </InputAdornment>
              ),
            },
          }}
        />
      </Grid>

      <Grid item md={6}>
        <FormInput
          fieldProps={{
            size: 'small',
            placeholder: 'e.g. 2021',
            label: 'Year Built',
            type: 'number',
            inputProps: {min: 0},
            ...register('yearBuilt'),
          }}
        />
      </Grid>

      <Grid item md={6}>
        <FormControl fullWidth>
          <InputLabel
            size="small"
            shrink
            variant="outlined"
            id="demo-simple-select-label">
            {t('Status')}
          </InputLabel>
          <Select
            labelId="demo-simple-select-label"
            label={t('Status')}
            size="small"
            defaultValue={watch('status')}
            notched
            {...register('status')}>
            <MenuItem value={ElevatorStatus.RUNNING}>{t('Running')}</MenuItem>
            <MenuItem value={ElevatorStatus.BROKEN}>{t('Broken')}</MenuItem>
            <MenuItem value={ElevatorStatus.JOB_ONGOING}>
              {t('Job ongoing')}
            </MenuItem>
            <MenuItem value={ElevatorStatus.UNKNOWN}>{t('Unknown')}</MenuItem>
            <MenuItem value={ElevatorStatus.OUT_OF_SERVICE}>
              {t('Out of service')}
            </MenuItem>
          </Select>
        </FormControl>
      </Grid>

      <AutoGeneratedIdDialog
        openDialog={openDialog}
        setOpenDialog={setOpenDialog}
      />
    </Grid>
  );
};

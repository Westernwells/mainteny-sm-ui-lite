import {
  FormControl,
  Grid,
  InputLabel,
  MenuItem,
  Select,
  TextField,
  Tooltip,
  Typography,
} from '@mui/material';
import Box from '@mui/material/Box';
import InputAdornment from '@mui/material/InputAdornment';
import AutoGeneratedIdDialog from 'components/AutoGeneratedIdDialog';
import {ComboBox} from 'components/ComboBox';
import {FormInput} from 'components/form/FormInput';
import {FormSelect} from 'components/form/FormSelect';
import {LanguageContext} from 'context/LanguageProvider';
import {FormikProps, getIn} from 'formik';
import {
  useCompanyAutoNumberConfig,
  useCompanyNextNumber,
} from 'hooks/reactQuery/useCompanies';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import {useVats} from 'hooks/reactQuery/useVats';
import {ArticleType, CostPackage} from 'models/article';
import {
  ArticleBasicFormModel,
  createMeasurementOptions,
  MeasurementUnit,
} from 'models/articleForm';
import {ServiceCompanyNumberType} from 'models/service-company';
import {useContext, useState} from 'react';
import {useTranslation} from 'react-i18next';
import {NumericFormat} from 'react-number-format';
import {theme} from 'theme';
import {getFilteredArticleTypeOptions} from 'utils/article-utils';
import {
  formatCurrency,
  getCurrencySymbol,
  getDecimalSeparator,
  getThousandsSeparator,
} from 'utils/currency';
import {getAmountFromPercentage} from 'utils/utils';
import {Receipt, ReceiptOutlined} from '@mui/icons-material';

export const EditBasicInfoForm = ({
  containerStyles,
  formik,
  articleCostPackage,
}: {
  containerStyles?: {[key: string]: any};
  formik: FormikProps<ArticleBasicFormModel>;
  articleCostPackage?: CostPackage;
}) => {
  const {t} = useTranslation();
  const {user} = useUserSession();
  const {language: selectedLng} = useContext(LanguageContext);
  const {data: taxRates} = useVats();

  const [openNewDialog, setOpenNewDialog] = useState<boolean>(false);

  const {data: companyAutoNumberConfig} = useCompanyAutoNumberConfig(
    user?.userAccount.serviceCompany.id,
  );

  const {data: companyNextNumber} = useCompanyNextNumber(
    {
      type: ServiceCompanyNumberType.ARTICLE,
    },
    user?.userAccount.serviceCompany.id,
  );

  const generateNextNumber = () => {
    formik.setFieldValue('externalId', companyNextNumber?.value);
  };

  const currencySymbol =
    getCurrencySymbol[formik.values.unitPurchaseAmountCurrency];

  const handleTypeChange = (selectedValue: ArticleType) => {
    formik.setFieldValue('type', selectedValue);
    if (selectedValue === ArticleType.PACKAGE) {
      formik.setFieldValue('costPackage', {
        laborPercentage: articleCostPackage?.laborPercentage ?? 50,
        materialPercentage: articleCostPackage?.materialPercentage ?? 50,
      });
    } else {
      formik.setFieldValue('costPackage', undefined);
    }
  };
  const defaultProps = {
    InputLabelProps: {shrink: true},
    onChange: formik.handleChange,
    onBlur: formik.handleBlur,
  };

  return (
    <Box
      display="flex"
      flexWrap="wrap"
      component="form"
      sx={{alignItems: 'end'}}>
      <Box sx={{...containerStyles}}>
        <FormInput
          fieldProps={{
            label: t('Name'),
            name: 'name',
            placeholder: t('e.g. Flat cable, 16G0.75+2x(2x0.5)'),
            type: 'text',
            required: true,
            value: formik.values.name,
            error: !!(formik.touched.name && formik.errors.name),
            helperText: formik.errors.name,
            onBlur: formik.handleBlur,
            onChange: formik.handleChange,
          }}
        />
      </Box>

      <Box
        sx={{
          width: '49%',
          pr: '1rem',
          mr: '0.25rem',
          my: '0.5rem',
        }}>
        <ComboBox
          options={[]}
          initialValue={
            formik.values.externalId
              ? {
                  label: formik.values.externalId,
                  value: formik.values.externalId,
                }
              : null
          }
          initialQuery={formik.values.externalId}
          getValue={(item) => {
            formik.setFieldValue('externalId', item?.value);
          }}
          autoIdProps={{
            handleAction: companyAutoNumberConfig?.configRecords.find(
              (item: any) => item.type === ServiceCompanyNumberType.ARTICLE,
            )?.enabled
              ? () => {
                  generateNextNumber();
                }
              : () => {
                  setOpenNewDialog(true);
                },
            isEnabled: companyAutoNumberConfig?.configRecords.find(
              (item: any) => item.type === ServiceCompanyNumberType.ARTICLE,
            )?.enabled,
          }}
          textFieldProps={{
            size: 'small',
            placeholder: 'e.g 1234',
            label: 'Article Number',
            name: 'externalId',
            value: formik.values.externalId,
            helperText: formik.touched.externalId && formik.errors.externalId,
            error: !!formik.errors.externalId && formik.touched.externalId,
            onChange: formik.handleChange,
            onBlur: formik.handleBlur,
          }}
        />
      </Box>

      <FormInput
        containerStyles={{...containerStyles}}
        fieldProps={{
          name: 'manufacturer',
          label: t('Manufacturer'),
          placeholder: t('e.g. Meier'),
          variant: 'outlined',
          type: 'text',
          value: formik.values.manufacturer,
          helperText: formik.errors.manufacturer,
          onBlur: formik.handleBlur,
          onChange: formik.handleChange,
        }}
      />
      <FormInput
        containerStyles={{...containerStyles}}
        fieldProps={{
          name: 'model',
          label: t('Model'),
          placeholder: t('e.g. 16G0.75+2x(2x0.5)'),
          variant: 'outlined',
          type: 'text',
          value: formik.values.model,
          helperText: formik.errors.model,
          onBlur: formik.handleBlur,
          onChange: formik.handleChange,
        }}
      />
      <FormInput
        containerStyles={{...containerStyles}}
        fieldProps={{
          label: t('Category'),
          name: 'category',
          placeholder: t('e.g. Cable'),
          type: 'text',
          value: formik.values.category,
          error: !!(formik.touched.category && formik.errors.category),
          onBlur: formik.handleBlur,
          onChange: formik.handleChange,
        }}
      />
      <Box
        display="flex"
        justifyContent="space-between"
        sx={{...containerStyles}}>
        <FormControl fullWidth required={false}>
          <InputLabel size="small" shrink variant="outlined">
            {t('Purchase VAT')}
          </InputLabel>
          <Select
            label={t('Purchase VAT')}
            size="small"
            value={formik.values.unitPurchaseVat}
            renderValue={(value) =>
              taxRates?.find((item) => item.id === value)?.name || ''
            }
            name="unitPurchaseVat"
            notched
            {...defaultProps}
            required={false}
            MenuProps={{
              anchorOrigin: {
                vertical: 'bottom',
                horizontal: 'right',
              },
              transformOrigin: {
                vertical: 'top',
                horizontal: 'right',
              },
              slotProps: {
                paper: {
                  sx: {
                    maxWidth: '20rem',
                  },
                },
              },
            }}>
            {taxRates?.map((taxRate) => (
              <MenuItem
                value={taxRate.id}
                key={taxRate.id}
                sx={{
                  flexDirection: 'column',
                  alignItems: 'flex-start',
                }}>
                <Box display="flex" maxWidth="100%" gap={1}>
                  <Typography variant="body1" noWrap color="primary.dark">
                    {taxRate.name}
                  </Typography>
                  <Tooltip title={taxRate.legalNote} arrow placement="top">
                    {taxRate.legalNote ? (
                      <Receipt fontSize="small" />
                    ) : (
                      <ReceiptOutlined fontSize="small" />
                    )}
                  </Tooltip>
                </Box>
                <Typography variant="body2" color="text.secondary">
                  {taxRate.percentage}%
                </Typography>
              </MenuItem>
            ))}
          </Select>
        </FormControl>

        <FormControl fullWidth required={false}>
          <InputLabel size="small" shrink variant="outlined">
            {t('Selling VAT')}
          </InputLabel>
          <Select
            label={t('Selling VAT')}
            size="small"
            value={formik.values.unitSellingVat}
            renderValue={(value) =>
              taxRates?.find((item) => item.id === value)?.name || ''
            }
            name="unitSellingVat"
            notched
            {...defaultProps}
            required={false}
            MenuProps={{
              anchorOrigin: {
                vertical: 'bottom',
                horizontal: 'right',
              },
              transformOrigin: {
                vertical: 'top',
                horizontal: 'right',
              },
              slotProps: {
                paper: {
                  sx: {
                    maxWidth: '20rem',
                  },
                },
              },
            }}>
            {taxRates?.map((taxRate) => (
              <MenuItem
                value={taxRate.id}
                key={taxRate.id}
                sx={{
                  flexDirection: 'column',
                  alignItems: 'flex-start',
                }}>
                <Box display="flex" maxWidth="100%" gap={1}>
                  <Typography variant="body1" noWrap color="primary.dark">
                    {taxRate.name}
                  </Typography>
                  <Tooltip title={taxRate.legalNote} arrow placement="top">
                    {taxRate.legalNote ? (
                      <Receipt fontSize="small" />
                    ) : (
                      <ReceiptOutlined fontSize="small" />
                    )}
                  </Tooltip>
                </Box>
                <Typography variant="body2" color="text.secondary">
                  {taxRate.percentage}%
                </Typography>
              </MenuItem>
            ))}
          </Select>
        </FormControl>
      </Box>

      <FormSelect
        containerStyles={{...containerStyles}}
        labelId="select-unit-label"
        label="Unit"
        options={createMeasurementOptions(selectedLng, MeasurementUnit.UE)}
        resetOption={{label: t('Select Unit')}}
        selectProps={{
          id: 'select-unit',
          value: formik.values.unit,
          onChange: formik.handleChange,
          error: !!(formik.touched.unit && formik.errors.unit),
          placeholder: t('Select Unit'),
          name: 'unit',
        }}
        required
      />

      <Box
        display="flex"
        justifyContent="space-between"
        sx={{...containerStyles}}>
        <FormInput
          containerStyles={{pr: '1rem'}}
          onValueChange={(values) => {
            formik.setFieldValue(values.name as string, values.value);
          }}
          inputType="currency"
          fieldProps={{
            name: 'unitPurchaseAmount',
            label: t('Purchase price (excl. VAT)'),
            placeholder: t(`e.g. 150{{currencySymbol}}`, {currencySymbol}),
            inputProps: {min: 0},
            type: 'number',
            value: formik.values.unitPurchaseAmount,
            helperText: formik.errors.unitPurchaseAmount,
            onBlur: formik.handleBlur,
            InputProps: {
              startAdornment: (
                <InputAdornment position="start">
                  {currencySymbol}
                </InputAdornment>
              ),
            },
          }}
        />

        <FormInput
          onValueChange={(values) => {
            formik.setFieldValue(values.name as string, values.value);
          }}
          inputType="currency"
          fieldProps={{
            name: 'unitSellingAmount',
            label: t('Selling price (excl. VAT)'),
            placeholder: t(`e.g. 200{{currencySymbol}}`, {currencySymbol}),
            inputProps: {min: 0},
            type: 'number',
            required: true,
            value: formik.values.unitSellingAmount,
            error: !!(
              formik.touched.unitSellingAmount &&
              formik.errors.unitSellingAmount
            ),
            helperText: formik.errors.unitSellingAmount,
            onBlur: formik.handleBlur,
            onChange: formik.handleChange,
            InputProps: {
              startAdornment: (
                <InputAdornment position="start">
                  {currencySymbol}
                </InputAdornment>
              ),
            },
          }}
        />
      </Box>

      <FormInput
        containerStyles={{...containerStyles}}
        fieldProps={{
          name: 'storageLocation',
          label: t('Storage Location'),
          placeholder: t('e.g. Rack 20, Box 4'),
          variant: 'outlined',
          type: 'text',
          value: formik.values.storageLocation,
          helperText: formik.errors.storageLocation,
          onBlur: formik.handleBlur,
          onChange: formik.handleChange,
        }}
      />

      <Grid container sx={{pt: 2}}>
        <Grid item xs={12} sm={2} gap={2}>
          <FormSelect
            containerStyles={{width: '87%'}}
            label="Type"
            options={getFilteredArticleTypeOptions({
              excludeTypes: [ArticleType.MIX],
            })}
            selectProps={{
              value: formik.values.type,
              onChange: (e) => handleTypeChange(e.target.value as ArticleType),
              name: 'type',
              error: !!(formik.touched.type && formik.errors.type),
            }}
            labelId="article-type"
            required
          />
        </Grid>

        {formik.values.type === ArticleType.PACKAGE && (
          <>
            <Grid item xs={12} sm={2} gap={2}>
              <NumericFormat
                value={formik.values.costPackage?.laborPercentage}
                customInput={TextField}
                suffix="%"
                allowLeadingZeros={false}
                decimalScale={2}
                decimalSeparator={getDecimalSeparator(selectedLng)}
                thousandSeparator={getThousandsSeparator(selectedLng)}
                sx={{
                  width: '100%',
                  bgcolor: 'white',
                  '& .MuiInputBase-root': {
                    pr: 0,
                  },
                  '& .MuiOutlinedInput-input': {
                    textAlign: 'right',
                    background: '#FFFFFF',
                  },
                }}
                isAllowed={(values) => {
                  const {floatValue} = values;
                  if (!floatValue) {
                    return true;
                  }

                  if (floatValue < 0) {
                    return false;
                  }

                  const maxValue = 100;

                  return floatValue <= maxValue;
                }}
                InputProps={{
                  name: 'costPackage.laborPercentage',
                  placeholder: t(`e.g. 50%`),
                  id: `costPackage.laborPercentage`,
                  inputMode: 'numeric',
                  error: !!getIn(formik.errors, 'costPackage.laborPercentage'),
                  onBlur: formik.handleBlur,
                  disabled: formik.values.type !== ArticleType.PACKAGE,
                  sx: {width: '87%'},
                }}
                InputLabelProps={{
                  shrink: true,
                }}
                label={t('Labor')}
                onValueChange={(values) => {
                  formik.setFieldValue(
                    'costPackage.laborPercentage',
                    Number(values.value),
                  );
                }}
                size="small"
              />
              {!!formik.values.costPackage?.laborPercentage && (
                <Typography
                  variant="caption"
                  color={theme.palette.primary.main}
                  sx={{
                    justifyContent: 'right',
                    display: 'flex',
                    py: 1,
                    pr: 3,
                  }}>
                  {formatCurrency(
                    getAmountFromPercentage(
                      Number(formik.values.costPackage?.laborPercentage),
                      Number(formik.values.unitSellingAmount),
                    ),
                  )}
                </Typography>
              )}
            </Grid>

            <Grid item xs={12} sm={2} gap={2}>
              <NumericFormat
                value={
                  formik.values.type === ArticleType.PACKAGE
                    ? 100 - Number(formik.values.costPackage?.laborPercentage)
                    : 0
                }
                customInput={TextField}
                suffix="%"
                allowLeadingZeros={false}
                decimalScale={2}
                decimalSeparator={getDecimalSeparator(selectedLng)}
                thousandSeparator={getThousandsSeparator(selectedLng)}
                sx={{
                  width: '100%',
                  bgcolor: 'white',
                  '& .MuiInputBase-root': {
                    pr: 0,
                  },
                  '& .MuiOutlinedInput-input': {
                    textAlign: 'right',
                    background: '#FFFFFF',
                  },
                }}
                isAllowed={(values) => {
                  const {floatValue} = values;
                  if (!floatValue) {
                    return true;
                  }

                  if (floatValue < 0) {
                    return false;
                  }

                  const maxValue = 100;

                  return floatValue <= maxValue;
                }}
                InputProps={{
                  name: 'costPackage.materialPercentage',
                  placeholder: t(`e.g. 20%`),
                  id: `costPackage.materialPercentage`,
                  inputMode: 'numeric',
                  disabled: true,
                  required: false,
                  error: !!getIn(
                    formik.errors,
                    'costPackage.materialPercentage',
                  ),
                  onBlur: formik.handleBlur,
                  sx: {width: '87%'},
                }}
                InputLabelProps={{
                  shrink: true,
                }}
                label={t('Material')}
                onValueChange={(values) => {
                  formik.setFieldValue(
                    'costPackage.materialPercentage',
                    Number(values.value),
                  );
                }}
                size="small"
              />

              {!!formik.values.costPackage?.laborPercentage && (
                <Typography
                  variant="caption"
                  color={theme.palette.primary.main}
                  sx={{justifyContent: 'right', display: 'flex', py: 1, pr: 3}}>
                  {formatCurrency(
                    Number(formik.values.unitSellingAmount) -
                      getAmountFromPercentage(
                        Number(formik.values.costPackage?.laborPercentage),
                        Number(formik.values.unitSellingAmount),
                      ),
                  )}
                </Typography>
              )}
            </Grid>

            <Grid item xs={12} sm={6} />
          </>
        )}
      </Grid>

      <AutoGeneratedIdDialog
        openDialog={openNewDialog}
        setOpenDialog={setOpenNewDialog}
      />
    </Box>
  );
};

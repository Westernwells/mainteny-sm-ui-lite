import {useEffect, useState} from 'react';
import {FormikProps} from 'formik';
import Box from '@mui/material/Box';
import Grid from '@mui/material/Grid2';
import InputAdornment from '@mui/material/InputAdornment';
import {Email, Phone} from '@mui/icons-material';
import {PageCard} from 'components/PageCard';
import {MultipleSelectCheckmarks} from 'components/MultipleSelectCheckmarks';
import {FormInput} from 'components/form/FormInput';
import {DatePicker} from 'components/DatePicker';
import {useUserSession} from 'hooks/reactQuery/useUserSession';
import {
  useCompanyAutoNumberConfig,
  useCompanyNextNumber,
} from 'hooks/reactQuery/useCompanies';
import {useVats} from 'hooks/reactQuery/useVats';
import {ServiceCompanyNumberType} from 'models/service-company';
import AutoGeneratedIdDialog from 'components/AutoGeneratedIdDialog';
import {ComboBox} from 'components/ComboBox';
import {t} from 'i18next';
import {CustomerBasicInfoFormModel} from './model';
import {T} from 'utils/i18n-utils';
import {FormControl, InputLabel, MenuItem, Select} from '@mui/material';
import {CUSTOMER_ALL_INVOICE_FORMATS} from 'utils/constants';

interface Props {
  formik: FormikProps<CustomerBasicInfoFormModel>;
}

export const BasicCustomerForm = ({formik}: Props) => {
  const defaultProps = {
    InputLabelProps: {shrink: true},
    onChange: formik.handleChange,
    onBlur: formik.handleBlur,
  };

  const {user} = useUserSession();

  const [openDialog, setOpenDialog] = useState<boolean>(false);

  const {data: companyAutoNumberConfig} = useCompanyAutoNumberConfig(
    user?.userAccount.serviceCompany.id,
  );

  const {data: companyNextNumber, refetch} = useCompanyNextNumber(
    {
      type: ServiceCompanyNumberType.PROPERTY_OWNER,
    },
    user?.userAccount.serviceCompany.id,
  );
  const {data: taxRates} = useVats();

  useEffect(() => {
    formik.setFieldValue('externalId', companyNextNumber?.value);
  }, [companyNextNumber]);

  useEffect(() => {
    if (!formik.values.vat) {
      const defaultPercentageVat = taxRates?.find((tR) => tR.isDefault);
      if (defaultPercentageVat) {
        formik.setFieldValue('vat', defaultPercentageVat.id);
      }
    }
  }, [taxRates]);

  const generateNextNumber = async () => {
    if (!companyNextNumber?.value) {
      const {data: refetchedCompanyNextNumber} = await refetch();
      return formik.setFieldValue(
        'externalId',
        refetchedCompanyNextNumber?.value,
      );
    }
    formik.setFieldValue('externalId', companyNextNumber?.value);
  };

  return (
    <PageCard
      headerLabel="Basic Information"
      containerStyles={{flexGrow: 1}}
      headerStyles={{mt: '0.5em'}}>
      <Box sx={{mt: '0.5em'}} component="form">
        <Grid container spacing={3}>
          <Grid size={{md: 4}}>
            <FormInput
              fieldProps={{
                size: 'small',
                placeholder: 'e.g Mainteny GmbH',
                label: 'Customer Name',
                name: 'name',
                value: formik.values.name,
                helperText: formik.touched.name && formik.errors.name,
                error: !!formik.errors.name && formik.touched.name,
                required: true,
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid size={{md: 4}}>
            <FormInput
              fieldProps={{
                size: 'small',
                placeholder: 'e.g johndoe@example.com',
                label: 'Email',
                name: 'email',
                value: formik.values.email,
                helperText: formik.touched.email && formik.errors.email,
                error: !!formik.errors.email && formik.touched.email,
                InputProps: {
                  endAdornment: (
                    <InputAdornment position="end">
                      <Email />
                    </InputAdornment>
                  ),
                },
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid size={{md: 4}}>
            <FormInput
              fieldProps={{
                size: 'small',
                placeholder: 'e.g johndoe@example.com',
                label: 'Billing Email Address',
                name: 'billingEmail',
                value: formik.values.billingEmail,
                helperText:
                  formik.touched.billingEmail && formik.errors.billingEmail,
                error:
                  !!formik.errors.billingEmail && formik.touched.billingEmail,
                InputProps: {
                  endAdornment: (
                    <InputAdornment position="end">
                      <Email />
                    </InputAdornment>
                  ),
                },
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid size={{md: 4}}>
            <FormInput
              fieldProps={{
                size: 'small',
                placeholder: 'e.g +34 12345678',
                label: 'Phone',
                name: 'phone',
                value: formik.values.phone,
                helperText: formik.errors.phone,
                error: !!formik.errors.phone,
                InputProps: {
                  startAdornment: (
                    <InputAdornment position="start"> + </InputAdornment>
                  ),
                  endAdornment: (
                    <InputAdornment position="end">
                      <Phone />
                    </InputAdornment>
                  ),
                },
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid size={{md: 4}}>
            <FormInput
              fieldProps={{
                size: 'small',
                placeholder: 'e.g +34 12345678',
                label: '2nd Phone',
                name: 'secondaryPhoneNumber',
                value: formik.values.secondaryPhoneNumber,
                helperText: formik.errors.secondaryPhoneNumber,
                error: !!formik.errors.secondaryPhoneNumber,
                InputProps: {
                  startAdornment: (
                    <InputAdornment position="start"> + </InputAdornment>
                  ),
                  endAdornment: (
                    <InputAdornment position="end">
                      <Phone />
                    </InputAdornment>
                  ),
                },
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid size={{md: 4}}>
            <FormInput
              fieldProps={{
                size: 'small',
                placeholder: 'e.g mainteny.com',
                label: 'Website/URL',
                name: 'url',
                value: formik.values.url,
                helperText: formik.errors.url,
                error: !!formik.errors.url,
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid size={{md: 4}}>
            <ComboBox
              options={[]}
              initialValue={
                formik.values.externalId
                  ? {
                      label: formik.values.externalId,
                      value: formik.values.externalId,
                    }
                  : null
              }
              initialQuery={formik.values.externalId}
              getValue={(item) => {
                formik.setFieldValue('externalId', item?.value);
              }}
              autoIdProps={{
                externalIdValue: formik.values.externalId,
                handleAction: companyAutoNumberConfig?.configRecords.find(
                  (item: any) =>
                    item?.type === ServiceCompanyNumberType.PROPERTY_OWNER,
                )?.enabled
                  ? () => {
                      generateNextNumber();
                    }
                  : () => {
                      setOpenDialog(true);
                    },
                isEnabled: companyAutoNumberConfig?.configRecords.find(
                  (item: any) =>
                    item?.type === ServiceCompanyNumberType.PROPERTY_OWNER,
                )?.enabled,
              }}
              textFieldProps={{
                name: 'externalId',
                label: T('Customer Number'),
                value: formik.values.externalId,
                onBlur: formik.handleBlur,
                error: !!(
                  formik.touched.externalId && formik.errors.externalId
                ),
                helperText:
                  formik.touched.externalId && formik.errors.externalId
                    ? formik.errors.externalId
                    : '',
                placeholder: t('e.g. 1234'),
                required: true,
              }}
            />
          </Grid>
          <Grid size={{md: 4}}>
            <DatePicker
              getSelectedDate={(newValue) => {
                if (newValue)
                  formik.setFieldValue('registrationDate', newValue);
              }}
              textFieldProps={{
                label: 'Customer Since',
                placeholder: t('Select date'),
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid size={{md: 4}}>
            <FormInput
              fieldProps={{
                size: 'small',
                placeholder: 'e.g 000 000 000',
                label: 'Cost Center',
                name: 'costCenter',
                value: formik.values.costCenter,
                helperText: formik.errors.costCenter,
                error: !!formik.errors.costCenter,
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid size={{md: 4}}>
            <Box display="flex" gap="1em">
              <MultipleSelectCheckmarks
                label="Priority"
                options={['A', 'B', 'C', 'NONE']}
                getSelectedValue={(item: string[]) =>
                  formik.setFieldValue('priority', item[0])
                }
                initialSelectedItems={
                  formik.values.priority ? [formik.values.priority] : ['NONE']
                }
                disableClearBtn
                multiple={false}
                containerStyles={{width: '100%'}}
                formControlStyles={{width: '100%'}}
              />
            </Box>
          </Grid>
          <Grid size={{md: 4}}>
            <FormInput
              fieldProps={{
                size: 'small',
                label: 'VAT ID',
                name: 'vatId',
                value: formik.values.vatId,
                helperText: formik.touched.vatId && formik.errors.vatId,
                error: !!formik.errors.vatId && formik.touched.vatId,
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid size={{md: 4}}>
            <FormInput
              fieldProps={{
                size: 'small',
                label: 'Offsetting Account',
                name: 'offsettingAccount',
                value: formik.values.offsettingAccount,
                helperText:
                  formik.touched.offsettingAccount &&
                  formik.errors.offsettingAccount,
                error:
                  !!formik.errors.offsettingAccount &&
                  formik.touched.offsettingAccount,
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid size={{md: 4}}>
            <FormInput
              labelTooltip="Buyer reference is defined by the customer."
              fieldProps={{
                size: 'small',
                label: 'Buyer reference',
                name: 'buyerReference',
                value: formik.values.buyerReference,
                helperText:
                  formik.touched.buyerReference && formik.errors.buyerReference,
                error:
                  !!formik.errors.buyerReference &&
                  formik.touched.buyerReference,
                ...defaultProps,
              }}
            />
          </Grid>
          <Grid size={{md: 4}}>
            <FormControl fullWidth required={false}>
              <InputLabel size="small" shrink variant="outlined">
                {t('Invoice format')}
              </InputLabel>
              <Select
                label={t('Invoice format')}
                size="small"
                value={formik.values.invoiceFormat}
                name="invoiceFormat"
                notched
                {...defaultProps}
                required={false}>
                {CUSTOMER_ALL_INVOICE_FORMATS.map((format) => (
                  <MenuItem value={format.value} key={format.value}>
                    {t(format.label)}
                  </MenuItem>
                ))}
              </Select>
            </FormControl>
          </Grid>
          <Grid size={{md: 4}}>
            <FormControl fullWidth required={false}>
              <InputLabel size="small" shrink variant="outlined">
                {t('Tax rate')}
              </InputLabel>
              <Select
                label={t('Tax rate')}
                size="small"
                value={formik.values.vat}
                name="vat"
                notched
                {...defaultProps}
                required={false}>
                {taxRates?.map((taxRate) => (
                  <MenuItem value={taxRate.id} key={taxRate.id}>
                    {taxRate.percentage || 0}%
                  </MenuItem>
                ))}
              </Select>
            </FormControl>
          </Grid>
        </Grid>
      </Box>
      <AutoGeneratedIdDialog
        openDialog={openDialog}
        setOpenDialog={setOpenDialog}
      />
    </PageCard>
  );
};
